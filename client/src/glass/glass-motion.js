import { useLayoutEffect } from 'react';

// Authored materials only: this observes mounts, not computed colours or styles.
// Class-only estimate materials share the same lifecycle as native glass tags.
const MATERIALS = [
  '[data-glass]', '[data-glass-accent]', '[data-glass-scrim]',
  '.gc-freq-btn', '.gc-mbb', '.gc-mbb-btn', '.gc-proof', '.gc-gr-card',
  '.gc-scarcity', '.gc-section-cta', '.gc-slot-priority', '.gc-slot-rain', '.gc-tech-chip',
];
const SELECTOR = [
  ...MATERIALS.map((selector) => `html[data-glass-theme] ${selector}`),
  '[data-glass-motion]',
].join(',');
const EASING = 'cubic-bezier(.16,1,.3,1)';
let sharedMotion = null;

const positioned = (element) => ['fixed', 'sticky'].includes(getComputedStyle(element).position);
const containsPositioned = (element) => element instanceof Element
  && (positioned(element) || Array.from(element.querySelectorAll('*')).some(positioned));

function motionKind(element, style) {
  const explicit = element.getAttribute('data-glass-motion');
  // Transforming a positioned shell (or an ancestor of one) can turn the
  // viewport into a local containing block. Preserve those coordinates.
  if (explicit === 'fade' || element.hasAttribute('data-glass-scrim')
    || ['fixed', 'sticky'].includes(style.position) || style.transform !== 'none' && style.transform !== ''
    || Array.from(element.querySelectorAll('*')).some(positioned)) return 'fade';
  if (explicit === 'control' || element.matches('button, a, input, select, textarea, [data-glass="chip"]')) return 'control';
  return 'card';
}

function createMotion() {
  const reduced = window.matchMedia('(prefers-reduced-motion: reduce)');
  const print = window.matchMedia('print');
  const seen = new WeakSet();
  const pending = new Set();
  const playing = new Map();
  const held = new Set();
  const pressedPointers = new Set();
  let releaseTimer = 0;
  let printing = print.matches;
  let disposed = false;

  const eligible = (element) => element.isConnected && element.matches(SELECTOR)
    && !element.closest('[data-glass-motion="off"], [inert], [hidden], [aria-hidden="true"]');
  const settle = (element) => {
    const animation = playing.get(element);
    if (!animation) return;
    playing.delete(element);
    held.delete(element);
    animation.onfinish = null;
    animation.cancel();
    element.removeAttribute('data-glass-motion-state');
  };
  const settleAll = () => Array.from(playing.keys()).forEach(settle);
  const interact = (event) => {
    // Keep the hit target still from pointer-down through click. Settling on
    // pointer-down can move a button away before pointer-up and lose the click.
    // Keyboard focus settles immediately; pointer-generated focus waits.
    if (event.type === 'pointerdown') {
      clearTimeout(releaseTimer);
      pressedPointers.add(event.pointerId);
    }
    for (const element of [...pending, ...playing.keys()]) {
      if (!element.contains(event.target)) continue;
      seen.add(element);
      pending.delete(element);
      intersection.unobserve(element);
      if (event.type === 'pointerdown' && playing.has(element)) {
        held.add(element);
        playing.get(element).pause();
      } else if (!held.has(element)) settle(element);
    }
  };
  const release = (event) => {
    if (event.type === 'blur') pressedPointers.clear();
    else pressedPointers.delete(event.pointerId);
    if (pressedPointers.size) return;
    clearTimeout(releaseTimer);
    // The click generated by pointer-up is dispatched before the next task,
    // including when a consumer stops the event's propagation.
    releaseTimer = window.setTimeout(() => {
      releaseTimer = 0;
      Array.from(held).forEach(settle);
    }, 0);
  };

  const play = (element, delay) => {
    const style = getComputedStyle(element);
    const kind = motionKind(element, style);
    const opacity = Number(style.opacity || 1);
    const start = { opacity: opacity * (kind === 'fade' ? 0.8 : 0.55) };
    const end = { opacity };
    if (kind !== 'fade') {
      start.transform = kind === 'control'
        ? 'perspective(1200px) translateY(6px) rotateX(4deg) scale(.98)'
        : 'perspective(1200px) translateY(16px) rotateX(10deg) rotateY(-4deg) scale(.96)';
      end.transform = 'none';
    }
    element.setAttribute('data-glass-motion-state', kind);
    const animation = element.animate([start, end], {
      duration: kind === 'card' ? 1000 : 450,
      delay,
      easing: EASING,
      fill: 'backwards',
    });
    playing.set(element, animation);
    animation.onfinish = () => settle(element);
  };

  const intersection = new IntersectionObserver((entries) => {
    let stagger = 0;
    for (const { target, isIntersecting } of entries) {
      if (!isIntersecting || !pending.has(target)) continue;
      pending.delete(target);
      intersection.unobserve(target);
      if (!eligible(target)) continue;
      seen.add(target);
      if (disposed || reduced.matches || printing || print.matches
        || target.contains(document.activeElement)) continue;
      // Children already travel with the entering card. A later-added panel
      // or a below-fold child can still enter when it becomes visible.
      if (Array.from(playing.keys()).some((parent) => parent.contains(target)
        && parent.getAttribute('data-glass-motion-state') !== 'fade')) continue;
      play(target, Math.min(stagger, 240));
      stagger += 80;
    }
  }, { threshold: 0, rootMargin: '0px 0px -16px 0px' });

  const enroll = (element) => {
    if (!eligible(element) || seen.has(element) || pending.has(element)) return;
    pending.add(element);
    intersection.observe(element);
  };
  const scan = (root) => {
    if (!(root instanceof Element)) return;
    if (root.matches(SELECTOR)) enroll(root);
    root.querySelectorAll(SELECTOR).forEach(enroll);
  };
  const mutations = new MutationObserver((records) => {
    if (disposed) return;
    for (const record of records) {
      if (record.type === 'attributes') scan(record.target);
      else record.addedNodes.forEach(scan);
    }
    // A dialog can mount inside a card that is still entering. Release its
    // ancestor transform immediately, before the browser paints the overlay.
    for (const element of playing.keys()) {
      if (!eligible(element) || records.some((record) => record.type === 'childList'
        && element.contains(record.target) && Array.from(record.addedNodes).some(containsPositioned))) settle(element);
    }
    for (const element of pending) {
      if (eligible(element)) continue;
      intersection.unobserve(element);
      pending.delete(element);
    }
  });
  const beforePrint = () => { printing = true; settleAll(); };
  const afterPrint = () => { printing = false; };
  const mediaChanged = () => { if (reduced.matches || print.matches) settleAll(); };
  scan(document.body);
  mutations.observe(document.documentElement, {
    childList: true, subtree: true, attributes: true,
    attributeFilter: ['data-glass-theme', 'data-glass', 'data-glass-accent', 'data-glass-scrim', 'data-glass-motion', 'inert', 'hidden', 'aria-hidden'],
  });
  document.addEventListener('focusin', interact, true);
  document.addEventListener('pointerdown', interact, { passive: true, capture: true });
  window.addEventListener('pointerup', release, true);
  window.addEventListener('pointercancel', release, true);
  window.addEventListener('blur', release);
  window.addEventListener('beforeprint', beforePrint);
  window.addEventListener('afterprint', afterPrint);
  reduced.addEventListener('change', mediaChanged);
  print.addEventListener('change', mediaChanged);

  return () => {
    disposed = true;
    mutations.disconnect();
    intersection.disconnect();
    pending.clear();
    clearTimeout(releaseTimer);
    settleAll();
    document.removeEventListener('focusin', interact, true);
    document.removeEventListener('pointerdown', interact, true);
    window.removeEventListener('pointerup', release, true);
    window.removeEventListener('pointercancel', release, true);
    window.removeEventListener('blur', release);
    window.removeEventListener('beforeprint', beforePrint);
    window.removeEventListener('afterprint', afterPrint);
    reduced.removeEventListener('change', mediaChanged);
    print.removeEventListener('change', mediaChanged);
  };
}

/** One observer for overlapping glass scenes and standalone custom glass. */
export function attachGlassMotion() {
  if (typeof Element.prototype.animate !== 'function' || typeof IntersectionObserver !== 'function') return () => {};
  if (!sharedMotion) sharedMotion = { users: 0, cleanup: createMotion() };
  const owner = sharedMotion;
  owner.users += 1;
  let detached = false;
  return () => {
    if (detached) return;
    detached = true;
    owner.users -= 1;
    if (owner.users) return;
    owner.cleanup();
    sharedMotion = null;
  };
}

export function useGlassMotion(active = true) {
  useLayoutEffect(() => active ? attachGlassMotion() : undefined, [active]);
}
