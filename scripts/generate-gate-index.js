#!/usr/bin/env node
/**
 * Writes the generated gate index at the end of docs/gates-and-env.md.
 *
 * One line per GATE_* variable the production code reads: the name, the
 * file(s) that read it, and the one-line description from the
 * server/config/feature-gates.js header when that header has one. The
 * hand-written paragraphs above the index stay the full contract for the
 * gates that have one; the index makes sure a lookup by name
 * (`grep -n 'GATE_NAME' docs/gates-and-env.md`) never comes back empty for a
 * gate that exists.
 *
 * Lines carry file paths, not line numbers: a line number would go stale
 * with every edit above it.
 *
 * Run: `npm run gates:index` after adding, renaming or removing a gate.
 * `npm run check:domain-rules` fails when a gate the code reads has no line.
 */

const fs = require('fs');
const path = require('path');
const { ROOT, scanGates, headerDescriptions } = require('./lib/gate-scan');

const DOC = path.join(ROOT, 'docs/gates-and-env.md');
const START = '<!-- gate-index:start -->';
const END = '<!-- gate-index:end -->';
const MAX_FILES = 3;

const HEADING = [
  '## Index of every gate the code reads (generated)',
  '',
  'Generated by `npm run gates:index` from the code; do not edit by hand. One line per `GATE_*` variable read in `server/` or `client/src/`: the file(s) that read it and, when `server/config/feature-gates.js` describes it in its header, that description. A gate with a paragraph above has its full contract there; a gate with only a line here is documented by the comments at its reader.',
  '',
].join('\n');

function indexLine(name, files, description) {
  const shown = files.slice(0, MAX_FILES).map((file) => `\`${file}\``).join(', ');
  const more = files.length > MAX_FILES ? ` (+${files.length - MAX_FILES} more)` : '';
  const tail = description ? ` — ${description}` : '';
  return `- \`${name}\` — ${shown}${more}${tail}`;
}

function buildBlock() {
  const descriptions = headerDescriptions();
  const lines = [...scanGates().entries()]
    .map(([name, files]) => indexLine(name, files, descriptions.get(name)));
  return `${START}\n${lines.join('\n')}\n${END}`;
}

function main() {
  const doc = fs.readFileSync(DOC, 'utf8');
  const block = buildBlock();
  const start = doc.indexOf(START);
  const end = doc.indexOf(END);
  let next;
  if (start !== -1 && end > start) {
    next = doc.slice(0, start) + block + doc.slice(end + END.length);
  } else {
    next = `${doc.replace(/\n*$/, '\n')}\n${HEADING}\n${block}\n`;
  }
  if (next === doc) {
    console.log('gates:index — docs/gates-and-env.md is up to date.');
    return;
  }
  fs.writeFileSync(DOC, next);
  console.log(`gates:index — wrote ${block.split('\n').length - 2} gate lines to docs/gates-and-env.md.`);
}

if (require.main === module) main();

module.exports = { START, END };
