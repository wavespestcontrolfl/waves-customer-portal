#!/usr/bin/env node
/**
 * Writes docs/gate-index.md, the generated index of every gate.
 *
 * One line per GATE_* variable the production code reads: the name, the
 * file(s) that read it, and the one-line description from the
 * server/config/feature-gates.js header when that header has one. The
 * hand-written paragraphs in docs/gates-and-env.md stay the full contract
 * for the gates that have one; the index makes sure a lookup by name
 * (`grep -n 'GATE_NAME' docs/gates-and-env.md docs/gate-index.md`) never
 * comes back empty for a gate that exists.
 *
 * The index is its own file so a new paragraph added to gates-and-env.md
 * never conflicts with it. Lines carry file paths, not line numbers: a line
 * number would go stale with every edit above it.
 *
 * Run: `npm run gates:index` after adding, renaming or removing a gate.
 * `npm run check:domain-rules` fails when a gate the code reads has no line.
 */

const fs = require('fs');
const path = require('path');
const { ROOT, scanGates, headerDescriptions } = require('./lib/gate-scan');

const INDEX_FILE = 'docs/gate-index.md';
const MAX_FILES = 3;

const HEADING = [
  '# Index of every gate the code reads (generated)',
  '',
  'Generated by `npm run gates:index` from the code; do not edit by hand. One line per `GATE_*` variable read in `server/` or `client/src/`: the file(s) that read it and, when `server/config/feature-gates.js` describes it in its header, that description. A gate with a paragraph in `docs/gates-and-env.md` has its full contract there; a gate with only a line here is documented by the comments at its reader.',
  '',
].join('\n');

function indexLine(name, files, description) {
  const shown = files.slice(0, MAX_FILES).map((file) => `\`${file}\``).join(', ');
  const more = files.length > MAX_FILES ? ` (+${files.length - MAX_FILES} more)` : '';
  const tail = description ? ` — ${description}` : '';
  return `- \`${name}\` — ${shown}${more}${tail}`;
}

// The gate names that have a line in the index file's text.
function indexedGates(text) {
  return new Set([...text.matchAll(/^- `(GATE_[A-Z0-9_]+)`/gm)].map((m) => m[1]));
}

function main() {
  const file = path.join(ROOT, INDEX_FILE);
  const descriptions = headerDescriptions();
  const lines = [...scanGates().entries()]
    .map(([name, files]) => indexLine(name, files, descriptions.get(name)));
  const next = `${HEADING}\n${lines.join('\n')}\n`;
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (next === current) {
    console.log(`gates:index — ${INDEX_FILE} is up to date.`);
    return;
  }
  fs.writeFileSync(file, next);
  console.log(`gates:index — wrote ${lines.length} gate lines to ${INDEX_FILE}.`);
}

if (require.main === module) main();

module.exports = { INDEX_FILE, indexedGates };
