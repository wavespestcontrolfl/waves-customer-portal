const db = require('../models/db');

function dateOnly(value) {
  if (!value) return null;
  if (value instanceof Date) return value.toISOString().slice(0, 10);
  return String(value).split('T')[0].slice(0, 10);
}

function isAutoGeneratedPayPerApplicationInvoice(invoice = {}) {
  const title = String(invoice.title || '').toLowerCase();
  const notes = String(invoice.notes || '').toLowerCase();
  return notes.includes('auto-generated from accepted estimate')
    && notes.includes('customer selected pay per application')
    && (title.includes('first application') || notes.includes('first application'));
}

async function findFirstApplicationInvoiceForEstimateService(svc, conn = db) {
  const sourceEstimateId = svc?.source_estimate_id;
  const customerId = svc?.customer_id;
  const scheduledDate = dateOnly(svc?.scheduled_date);
  if (!sourceEstimateId || !customerId || !scheduledDate) return { invoice: null, liveBeside: null };

  const rows = await conn('invoices as i')
    .join('scheduled_services as first_visit', 'i.scheduled_service_id', 'first_visit.id')
    .where('i.customer_id', customerId)
    .where('first_visit.source_estimate_id', sourceEstimateId)
    .where('first_visit.scheduled_date', scheduledDate)
    // INTENTIONALLY retains refunded/cancelled rows (status quo — codex #3456
    // narrowed scope): this lookup reaches SIBLING scheduled services of the
    // same estimate/date. A REFUNDED sibling first-application invoice keeps
    // suppressing the completion mint exactly as before (no replacement is
    // minted, nothing to reconcile on a bounced refund); the own-visit
    // terminal case is handled in routes/admin-dispatch.js
    // (completionTerminalInvoiceLookup → manual-billing alert).
    .whereNot('i.status', 'void')
    .orderBy('i.created_at', 'desc')
    .select('i.*');

  // A canceled/cancelled match must not end the scan (codex #3456 P1): the
  // caller drops such a row from reuse (splitTerminalCompletionInvoice), and
  // returning ONLY the newest match would then read as "no suppressor" while
  // an OLDER live first-application invoice remains collectible — the mint
  // would cut a second invoice for the same application. So skip the
  // resolved non-refunded vocabulary; and because there is NO reliable
  // refund-event clock to order a refunded match against a live one
  // (invoices carry no refunded_at; created_at is mint time; updated_at
  // moves on unrelated edits — codex #3456 rounds 4–6), a REFUNDED match
  // wins whenever one exists, in ANY mint order: the caller's terminal path
  // parks the visit for a human instead of auto-sending a pay link a
  // bounced refund could turn into a double collection. When both exist,
  // the newest live match rides along as `liveBeside` so the caller's
  // manual-billing alert directs staff to collect THAT invoice instead of
  // creating a duplicate (codex #3456 r7) — same shape as the own-visit
  // reconciliation. All-canceled is NOT a plain fall-through to the mint
  // (codex #3456 late round): the acceptance-time first-application invoice
  // carries the ONE-TIME SETUP FEE beside the visit charge
  // (estimate-public.js accept mints them as one invoice), so an ordinary
  // completion remint would recreate only the visit charge and silently
  // drop the fee. A canceled acceptance match with NO live replacement is
  // surfaced as `canceledSetupFee` — the caller parks the manual-billing
  // alert (bill BOTH charges by hand) instead of partial-reminting. A live
  // match still wins over it (the replacement already stands).
  const InvoiceService = require('./invoice');
  const skipStatuses = InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES.filter((s) => s !== 'refunded');
  const allMatches = (rows || []).filter(isAutoGeneratedPayPerApplicationInvoice);
  const matches = allMatches.filter((row) => !skipStatuses.includes(row.status));
  const refunded = matches.find((row) => row.status === 'refunded') || null;
  const live = matches.find((row) => row.status !== 'refunded') || null; // created_at DESC → newest live match
  if (refunded) return { invoice: refunded, liveBeside: live };
  if (live) return { invoice: live, liveBeside: null };
  const canceledSetupFee = allMatches.find((row) => skipStatuses.includes(row.status) && row.status !== 'void') || null;
  return canceledSetupFee ? { invoice: null, liveBeside: null, canceledSetupFee } : { invoice: null, liveBeside: null };
}

module.exports = {
  dateOnly,
  findFirstApplicationInvoiceForEstimateService,
  isAutoGeneratedPayPerApplicationInvoice,
};
