const db = require('../models/db');

function dateOnly(value) {
  if (!value) return null;
  if (value instanceof Date) return value.toISOString().slice(0, 10);
  return String(value).split('T')[0].slice(0, 10);
}

function isAutoGeneratedPayPerApplicationInvoice(invoice = {}) {
  const title = String(invoice.title || '').toLowerCase();
  const notes = String(invoice.notes || '').toLowerCase();
  return notes.includes('auto-generated from accepted estimate')
    && notes.includes('customer selected pay per application')
    && (title.includes('first application') || notes.includes('first application'));
}

// A row's ORIGINAL date (P1-A, Codex round 13 on PR #5021): the earliest
// reschedule_log.original_date ever recorded for it (the true pre-any-move
// date), or its CURRENT scheduled_date when it has never been rescheduled
// at all. "Earliest" is by reschedule_log.created_at ascending — the FIRST
// reschedule event's original_date is the row's true starting point; a
// later reschedule's original_date is only where it stood just before that
// later move, not where it started. reschedule_log's columns are read per
// the frozen migration that created the table (20260401000022_reschedule_
// system.js: scheduled_service_id, original_date, created_at) — guarded by
// hasTable so a database without the table (should not happen in this
// app, but this backfill fails toward NOT stamping, never toward an
// unguarded query error) falls back to the current scheduled_date alone.
async function originalDateForRow(conn, hasRescheduleLog, id, currentScheduledDate) {
  if (hasRescheduleLog) {
    const earliest = await conn('reschedule_log')
      .where({ scheduled_service_id: id })
      .whereNotNull('original_date')
      .orderBy('created_at', 'asc')
      .first('original_date');
    if (earliest?.original_date) return dateOnly(earliest.original_date);
  }
  return dateOnly(currentScheduledDate);
}

// One-time (bounded, idempotent, RERUNNABLE) backfill of scheduled_services.
// first_application_invoice_id for historical combined first-application
// invoices — owner ruling 2026-09-27. Shared by the schema migration
// (20260927220000, frozen — pushed and never edited) AND the later
// re-run migration (20260928000000) that widens this same function's own
// eligibility without touching the frozen one; also directly
// testable/callable by hand against a live database. Candidate INVOICES
// are still found the OLD way — isAutoGeneratedPayPerApplicationInvoice's
// title/notes text match on a non-void invoice, joined to its own anchor
// visit — there being no stamp yet at all is exactly the problem this
// backfill exists to solve, so text is the only evidence available for
// discovering the historical invoice itself. Invoices are processed in
// created_at order (oldest first) so the result is deterministic.
//
// SIBLING eligibility (P1-A, Codex round 13 — tightens round-11 P2's
// accept-time created_at window, which by itself proved NOT membership
// evidence on its own: (1) two acceptances under the SAME estimate close
// enough together (e.g. 60 seconds apart) put every row from BOTH accepts
// inside EACH OTHER's 120-second window, so the window alone could
// cross-stamp or overwrite the wrong accept's members; (2) the converter
// also creates unpriced recurring parents at accept that are NOT same-trip
// at all — a seasonal unit rolled to a later month, or a companion outside
// the reservation — which land inside the window too even though they
// were never on the anchor's day to begin with). A sibling now needs BOTH:
//   (a) scheduled_services.created_at within 120 seconds of the INVOICE's
//       own created_at (not the anchor's — a reserved-slot anchor can be
//       minted days before the invoice, while the invoice and every
//       promoted sibling are inserted together AT acceptance), AND
//   (b) its ORIGINAL date (originalDateForRow above) equals the anchor's
//       OWN original date — the genuine same-trip signal a plain window
//       match cannot provide: two rows born in the same accept transaction
//       but never actually scheduled together (a seasonal roll, a
//       companion outside the reservation) have DIFFERENT original dates
//       even though their created_at instants coincide, while a genuine
//       same-trip pair that has since diverged keeps its shared original
//       date regardless of where either row has moved to since.
// Also required, independent of the pairing above: never overwrite (only
// scheduled_services rows with first_application_invoice_id IS NULL are
// ever considered, anchor or sibling), and never treat a row as a sibling
// (or as an anchor) when it is ITSELF the scheduled_service_id anchor of
// some OTHER live (non-void) invoice — that row already has its own
// combined-invoice identity and must not be folded into a different
// group's membership.
//
// AMBIGUITY: if a single candidate sibling row satisfies (a) and (b) for
// MORE than one candidate invoice in this run (the two-close-acceptances
// case above, when the accepts also happen to land on the exact same
// original date), this backfill stamps NOTHING for that row — it is
// counted as `ambiguous` and logged (id only) for the office to resolve by
// hand, rather than guessing which invoice actually owns it. A raw
// candidate that satisfies the created_at window (a) but fails the
// original-date match (b) for every candidate invoice it was compared
// against is similarly left unstamped and logged, so the office can review
// it too — it fell inside the timing window but this backfill found no
// same-trip evidence for it.
//
// A single-program invoice (no eligible, non-ambiguous sibling) is never
// stamped as a pair. Idempotent: an already-stamped anchor or sibling is
// excluded from every future rerun by the first_application_invoice_id IS
// NULL guard, so a rerun only ever adds NEW stamps for rows this backfill
// has not yet touched — it never revisits or rewrites a decision it (or a
// real accept-time stamp) already committed.
async function backfillFirstApplicationInvoiceStamps(conn = db) {
  const hasColumn = await conn.schema.hasColumn('scheduled_services', 'first_application_invoice_id');
  if (!hasColumn) return { scanned: 0, stamped: 0, ambiguous: 0 };
  const logger = require('./logger');
  const { CANCELLED_SERVICE_RESOLVED_STATUSES } = require('./invoice');
  const hasRescheduleLog = await conn.schema.hasTable('reschedule_log');

  // A row is never a candidate (anchor OR sibling) once it is already
  // stamped, or while it is itself the scheduled_service_id anchor of some
  // OTHER live invoice — shared by both the anchor query below and the
  // per-invoice sibling query further down. excludeInvoiceAlias lets the
  // anchor query exclude the CURRENT candidate invoice itself from "other"
  // (every anchor row trivially IS the scheduled_service_id of its own
  // invoice `i` — without this exclusion every anchor would always fail
  // its own check); the sibling query passes none, since a sibling row is
  // never the current invoice's own anchor by construction (`s.id <>
  // anchor_id` is already enforced by its own where clause).
  const notAlreadyClaimed = (query, alias, excludeInvoiceAlias = null) => query
    .whereNull(`${alias}.first_application_invoice_id`)
    .whereNotExists(function anchorOfAnotherLiveInvoiceExists() {
      const sub = this.select(1).from('invoices as other')
        .whereRaw(`other.scheduled_service_id = ${alias}.id`)
        .whereRaw('other.status <> \'void\'');
      if (excludeInvoiceAlias) sub.whereRaw(`other.id <> ${excludeInvoiceAlias}.id`);
    });

  const candidates = await notAlreadyClaimed(
    conn('invoices as i')
      .join('scheduled_services as anchor', 'anchor.id', 'i.scheduled_service_id')
      .whereNot('i.status', 'void')
      .whereNotNull('anchor.source_estimate_id')
      .whereNull('anchor.recurring_parent_id')
      .where('anchor.is_recurring', true),
    'anchor',
    'i',
  )
    .orderBy('i.created_at', 'asc')
    .select(
      'i.id as invoice_id', 'i.title', 'i.notes', 'i.created_at as invoice_created_at',
      'anchor.id as anchor_id', 'anchor.customer_id', 'anchor.source_estimate_id', 'anchor.scheduled_date as anchor_scheduled_date',
    );

  // Pass 1: for every candidate invoice (text-recognized, oldest first),
  // find its RAW window+original-date-matched siblings, then tally which
  // invoice(s) each sibling id matched — a sibling matched by more than one
  // invoice is ambiguous and must be excluded from ALL of them, not just
  // "first one wins".
  const matchesByInvoice = new Map(); // invoiceId -> { row, siblingIds: Set }
  const invoicesBySibling = new Map(); // siblingId -> Set(invoiceId)
  const nearMissSiblingIds = new Set(); // in-window, but original date didn't match ANY candidate invoice
  const matchedSiblingIds = new Set();
  let scanned = 0;
  for (const row of candidates) {
    scanned += 1;
    if (!isAutoGeneratedPayPerApplicationInvoice(row)) continue;
    const anchorOriginalDate = await originalDateForRow(conn, hasRescheduleLog, row.anchor_id, row.anchor_scheduled_date);

    const rawSiblings = await notAlreadyClaimed(
      conn('scheduled_services as s')
        .where('s.customer_id', row.customer_id)
        .where('s.source_estimate_id', row.source_estimate_id)
        .whereNot('s.id', row.anchor_id)
        .whereNull('s.recurring_parent_id')
        .where('s.is_recurring', true)
        .whereNull('s.estimated_price')
        .whereNotExists(function ownLiveInvoiceExists() {
          this.select(1).from('invoices as own')
            .whereRaw('own.scheduled_service_id = s.id')
            .whereNotIn('own.status', CANCELLED_SERVICE_RESOLVED_STATUSES);
        })
        .whereRaw('ABS(EXTRACT(EPOCH FROM (s.created_at - ?::timestamptz))) <= 120', [row.invoice_created_at]),
      's',
    )
      .select('s.id', 's.scheduled_date');

    const siblingIds = new Set();
    for (const sib of rawSiblings) {
      const sibOriginalDate = await originalDateForRow(conn, hasRescheduleLog, sib.id, sib.scheduled_date);
      if (anchorOriginalDate && sibOriginalDate && sibOriginalDate === anchorOriginalDate) {
        siblingIds.add(sib.id);
        matchedSiblingIds.add(sib.id);
        if (!invoicesBySibling.has(sib.id)) invoicesBySibling.set(sib.id, new Set());
        invoicesBySibling.get(sib.id).add(row.invoice_id);
      } else {
        nearMissSiblingIds.add(sib.id);
      }
    }
    matchesByInvoice.set(row.invoice_id, { row, siblingIds });
  }

  // Pass 2: resolve ambiguity, then stamp — invoice order is the same
  // created_at-ascending order the candidates were read in.
  let stamped = 0;
  let ambiguous = 0;
  const ambiguousSiblingIds = new Set();
  for (const [siblingId, invoiceIds] of invoicesBySibling) {
    if (invoiceIds.size > 1) ambiguousSiblingIds.add(siblingId);
  }
  if (ambiguousSiblingIds.size) {
    ambiguous = ambiguousSiblingIds.size;
    logger.warn(`[estimate-first-application-invoice] backfill: ${ambiguous} sibling row(s) matched more than one candidate invoice within the accept-time window and original-date evidence — left unstamped for hand review: ${[...ambiguousSiblingIds].join(', ')}`);
  }
  // Anything in the window that never matched ANY invoice's original date,
  // and was never resolved as ambiguous either, fell inside the timing
  // window with no same-trip evidence this backfill could confirm.
  const unresolvedNearMisses = [...nearMissSiblingIds].filter((id) => !matchedSiblingIds.has(id) && !ambiguousSiblingIds.has(id));
  if (unresolvedNearMisses.length) {
    logger.warn(`[estimate-first-application-invoice] backfill: ${unresolvedNearMisses.length} row(s) created within the accept-time window of a combined invoice, but with no matching original-date evidence — left unstamped for hand review: ${unresolvedNearMisses.join(', ')}`);
  }

  for (const { row, siblingIds } of matchesByInvoice.values()) {
    const eligibleSiblingIds = [...siblingIds].filter((id) => !ambiguousSiblingIds.has(id));
    // A single-program invoice (no eligible, non-ambiguous sibling) is
    // never stamped as a pair.
    if (!eligibleSiblingIds.length) continue;
    const memberIds = [row.anchor_id, ...eligibleSiblingIds];
    await conn('scheduled_services').whereIn('id', memberIds).update({ first_application_invoice_id: row.invoice_id });
    stamped += memberIds.length;
  }
  return { scanned, stamped, ambiguous };
}

// Freeze the accept route's per-service authority while it still exists.
// Later closeout must never reconstruct this split from mutable plan prices.
// Unknown composition keeps the existing aggregate and requires office review.
async function itemizeFirstApplication({ estimateId, customerId, scheduledServiceId, rowAmounts, rowDiscounts = [], line }, conn = db) {
  if (process.env.GATE_VISIT_CLOSEOUT !== 'true' || !scheduledServiceId
      || !Array.isArray(rowAmounts) || rowAmounts.length < 2) return [line];
  if (!Array.isArray(rowDiscounts) || rowDiscounts.some((amount) => !Number.isFinite(amount) || amount < 0)) return [line];
  const first = await conn('scheduled_services').where({ id: scheduledServiceId,
    customer_id: customerId, source_estimate_id: estimateId }).first();
  if (!first || first.recurring_parent_id) return [line];
  const members = await conn('scheduled_services').where({ customer_id: customerId,
    source_estimate_id: estimateId, scheduled_date: first.scheduled_date }).whereNull('recurring_parent_id').orderBy('id');
  const { recurringServiceKey, reservedAcceptPerVisitSplit } = require('./estimate-converter');
  const identity = (member) => ({ name: member.service_type });
  // The invoice's separate labeled credit stays intact. Restore only each
  // row's exact accepted credit slice to its gross line, never apportion anew.
  const grossRows = rowAmounts.map((row, index) => ({ ...row,
    amount: Math.round((Number(row.amount) + Number(rowDiscounts[index] || 0)) * 100) / 100,
  }));
  const split = reservedAcceptPerVisitSplit({ reservedPrice: line.unit_price,
    reservedService: identity(members[0]), promotedServices: members.slice(1).map(identity), rowAmounts: grossRows });
  if (!split) return [line];
  const amounts = [split.reserved, ...split.promoted];
  return members.map((member, index) => ({
    ...line, client_id: `scheduled_${member.id}_primary`,
    accepted_service_type: member.service_type, accepted_service_id: member.service_id,
    description: rowAmounts.find((row) => recurringServiceKey(row) === recurringServiceKey(identity(member)))?.name
      || member.service_type,
    quantity: 1, unit_price: amounts[index], amount: amounts[index],
  }));
}

async function findFirstApplicationInvoiceForEstimateService(svc, conn = db, { lockRows = false } = {}) {
  const sourceEstimateId = svc?.source_estimate_id;
  const customerId = svc?.customer_id;
  const scheduledDate = dateOnly(svc?.scheduled_date);
  if (!sourceEstimateId || !customerId || !scheduledDate) return { invoice: null, liveBeside: null };

  // lockRows (transactional callers only): FOR UPDATE OF i returns the
  // LATEST committed row versions and holds them to commit — a plain select
  // classifies snapshot statuses that a concurrent refund/cancel/restore
  // can invalidate before the caller acts (codex #3456 hardening).
  let query = conn('invoices as i')
    .join('scheduled_services as first_visit', 'i.scheduled_service_id', 'first_visit.id')
    .where('i.customer_id', customerId)
    .where('first_visit.source_estimate_id', sourceEstimateId)
    .where('first_visit.scheduled_date', scheduledDate)
    // INTENTIONALLY retains refunded/cancelled rows (status quo — codex #3456
    // narrowed scope): this lookup reaches SIBLING scheduled services of the
    // same estimate/date. A REFUNDED sibling first-application invoice keeps
    // suppressing the completion mint exactly as before (no replacement is
    // minted, nothing to reconcile on a bounced refund); the own-visit
    // terminal case is handled in routes/admin-dispatch.js
    // (completionTerminalInvoiceLookup → manual-billing alert).
    .whereNot('i.status', 'void')
    .orderBy('i.created_at', 'desc')
    .select('i.*');
  if (lockRows) query = query.forUpdate('i');
  const rows = await query;

  // A canceled/cancelled match must not end the scan (codex #3456 P1): the
  // caller drops such a row from reuse (splitTerminalCompletionInvoice), and
  // returning ONLY the newest match would then read as "no suppressor" while
  // an OLDER live first-application invoice remains collectible — the mint
  // would cut a second invoice for the same application. So skip the
  // resolved non-refunded vocabulary; and because there is NO reliable
  // refund-event clock to order a refunded match against a live one
  // (invoices carry no refunded_at; created_at is mint time; updated_at
  // moves on unrelated edits — codex #3456 rounds 4–6), a REFUNDED match
  // wins whenever one exists, in ANY mint order: the caller's terminal path
  // parks the visit for a human instead of auto-sending a pay link a
  // bounced refund could turn into a double collection. When both exist,
  // the newest live match rides along as `liveBeside` so the caller's
  // manual-billing alert directs staff to collect THAT invoice instead of
  // creating a duplicate (codex #3456 r7) — same shape as the own-visit
  // reconciliation. All-canceled is NOT a plain fall-through to the mint
  // (codex #3456 late round): the acceptance-time first-application invoice
  // carries the ONE-TIME SETUP FEE beside the visit charge
  // (estimate-public.js accept mints them as one invoice), so an ordinary
  // completion remint would recreate only the visit charge and silently
  // drop the fee. A canceled acceptance match with NO live replacement is
  // surfaced as `canceledSetupFee` — the caller parks the manual-billing
  // alert (bill BOTH charges by hand) instead of partial-reminting. A live
  // match still wins over it (the replacement already stands).
  const InvoiceService = require('./invoice');
  const skipStatuses = InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES.filter((s) => s !== 'refunded');
  const allMatches = (rows || []).filter(isAutoGeneratedPayPerApplicationInvoice);
  const matches = allMatches.filter((row) => !skipStatuses.includes(row.status));
  const refunded = matches.find((row) => row.status === 'refunded') || null;
  const live = matches.find((row) => row.status !== 'refunded') || null; // created_at DESC → newest live match
  if (refunded) return { invoice: refunded, liveBeside: live };
  if (live) return { invoice: live, liveBeside: null };
  // Only a canceled acceptance invoice that ACTUALLY carried a setup-fee
  // line parks the completion — a canceled "first application only"
  // acceptance invoice has no fee to lose, and parking it would instruct
  // staff to bill a nonexistent charge (codex P0): those remint normally.
  const canceledSetupFee = allMatches.find((row) => skipStatuses.includes(row.status)
    && row.status !== 'void' && invoiceContainsSetupFeeLine(row)) || null;
  return canceledSetupFee ? { invoice: null, liveBeside: null, canceledSetupFee } : { invoice: null, liveBeside: null };
}

// Does this invoice row carry the one-time setup-fee CHARGE? Authoritative
// source: a parsed line_items entry (the acceptance mint writes
// 'WaveGuard Membership — one-time setup fee') — but only a POSITIVE line
// whose text does not say the fee was WAIVED: the converter's real
// annual-prepay line reads "12 months prepaid (setup fee waived)", and
// counting it as a billed fee would let a refunded prepay read as
// fee-collected while nothing was ever billed for it (Codex P0, pre-push
// round 13). Provenance fallback for rows without parseable line items:
// the acceptance notes name the fee only when it was charged
// ("$99 setup fee plus first application" vs "first application only"),
// with the same waived-language rejection.
function invoiceContainsSetupFeeLine(row) {
  let items = row?.line_items;
  if (typeof items === 'string') {
    try { items = JSON.parse(items); } catch { items = null; }
  }
  if (Array.isArray(items) && items.length) {
    return invoiceHasPositiveSetupFeeLine({ line_items: items });
  }
  const notes = String(row?.notes || '');
  return /setup fee/i.test(notes) && !/setup fee waiv/i.test(notes);
}

// Does this invoice bill the BASE plan application? Identity comes from
// the ONE shared predicate (InvoiceService.lineIsBaseApplication — the
// same classifier the switch-supersede restore and prepay-switch undo
// use), so line-identity changes land in one place. This wrapper adds
// the BILLING-EVIDENCE layer its callers need: the line must carry a
// POSITIVE amount (a refunded/credited base line is not the application
// being billed — Codex P0 rounds 6–11), and unreadable rows FAIL CLOSED
// (prove nothing): the callers skip parking or resolve alerts on this
// evidence.
function invoiceBillsBaseApplication(row) {
  const { lineIsBaseApplication } = require('./invoice');
  let items = row?.line_items;
  if (typeof items === 'string') {
    try { items = JSON.parse(items); } catch { items = null; }
  }
  if (!Array.isArray(items) || !items.length) return false;
  return items.some((li) => {
    const qty = li?.quantity != null ? Number(li.quantity) : 1;
    const amt = li?.amount != null ? Number(li.amount) : Number(li?.unit_price) * qty;
    return Number.isFinite(amt) && amt > 0 && lineIsBaseApplication(li);
  });
}

// The amount of the invoice's positive, non-waived one-time setup-fee line
// (null when none) — the shared identity invoiceHasPositiveSetupFeeLine
// checks: description mentions "setup fee" but not "waiv" (the converter's
// annual-prepay line reads "12 months prepaid (setup fee waived)" and would
// otherwise false-match the broader substring test — Codex P0, pre-push
// round 17), and the line carries a positive amount.
function positiveSetupFeeLineAmount(row) {
  let items = row?.line_items;
  if (typeof items === 'string') {
    try { items = JSON.parse(items); } catch { items = null; }
  }
  if (!Array.isArray(items) || !items.length) return null;
  for (const li of items) {
    const desc = String(li?.description || '');
    if (!/setup fee/i.test(desc) || /waiv/i.test(desc)) continue;
    const qty = li?.quantity != null ? Number(li.quantity) : 1;
    const amt = li?.amount != null ? Number(li.amount) : Number(li?.unit_price) * qty;
    if (Number.isFinite(amt) && amt > 0) return amt;
  }
  return null;
}

// STRICT billed-fee evidence for OBLIGATION-CLEARING and ALERT-RESOLVING
// decisions: a positive parsed non-waived setup-fee LINE, no notes
// fallback — provenance text on an unreadable row proves nothing about
// money actually billed (Codex P0, pre-push round 17).
// invoiceContainsSetupFeeLine (above) keeps its notes fallback for the
// #3474 canceledSetupFee PARKING decision, where matching errs toward
// caution (an alert), never toward clearing an obligation.
function invoiceHasPositiveSetupFeeLine(row) {
  return positiveSetupFeeLineAmount(row) != null;
}

// An independent setup-fee document does not cover a performed application.
// Unreadable charges cannot establish the fee-only exception to packet ownership.
function invoiceContainsOnlySetupFeeCharges(row) {
  let items = row?.line_items;
  if (typeof items === 'string') {
    try { items = JSON.parse(items); } catch { return false; }
  }
  if (!Array.isArray(items) || !items.length) return false;
  let hasFee = false;
  for (const line of items) {
    const amount = line?.amount != null ? Number(line.amount)
      : Number(line?.unit_price) * (line?.quantity != null ? Number(line.quantity) : 1);
    if (!Number.isFinite(amount)) return false;
    if (amount <= 0) continue;
    const description = String(line?.description || '');
    if (!/^(?:(?:WaveGuard Membership|Bait Station Setup)\s*[—–-]\s*)?(?:one-time )?setup fee$/i.test(description.trim())
        || require('./invoice').lineIsBaseApplication(line)) return false;
    hasFee = true;
  }
  return hasFee;
}

// Classify rows only after the caller has acquired its own transaction and
// row locks. Setup-fee coverage is estimate-wide; application coverage is
// visit-date scoped, with a missing date failing closed as a possible match.
// Status remains caller-owned because packet ownership survives terminal
// invoice states while adoption deliberately distinguishes them.
function classifyAcceptedEstimateInvoiceCoverage(row, applicationDate) {
  const rowDate = dateOnly(row?.service_date || row?.scheduled_date);
  const targetDate = dateOnly(applicationDate);
  return {
    hasSetupFee: invoiceHasPositiveSetupFeeLine(row),
    setupFeeOnly: invoiceContainsOnlySetupFeeCharges(row),
    matchesApplicationDate: !rowDate || !targetDate || rowDate === targetDate,
  };
}

// Cents totals for coverage comparison (Codex PR r7 P1): boolean
// any-positive-line evidence lets a $9.90 typo retire a $99 obligation —
// resolution compares SUMMED live coverage against the frozen expected
// amounts persisted on the alert.
function sumPositiveSetupFeeCents(row) {
  let items = row?.line_items;
  if (typeof items === 'string') {
    try { items = JSON.parse(items); } catch { items = null; }
  }
  if (!Array.isArray(items)) return 0;
  return items.reduce((sum, li) => {
    const desc = String(li?.description || '');
    if (!/setup fee/i.test(desc) || /waiv/i.test(desc)) return sum;
    const qty = li?.quantity != null ? Number(li.quantity) : 1;
    const amt = li?.amount != null ? Number(li.amount) : Number(li?.unit_price) * qty;
    return Number.isFinite(amt) && amt > 0 ? sum + Math.round(amt * 100) : sum;
  }, 0);
}

// Acceptance invoices stay editable until delivery, so their line JSON cannot
// authorize a setup charge. Compare it with acceptance-frozen evidence: the
// estimate owns the WaveGuard fee and setup_fee_claims owns any rodent fee.
async function acceptanceSetupFeeMatchesAuthority({ invoice, estimateId }, conn = db) {
  const billedCents = sumPositiveSetupFeeCents(invoice);
  const estimate = await conn('estimates').where({ id: estimateId,
    customer_id: invoice.customer_id, status: 'accepted' }).first('estimate_data');
  if (!estimate) return false;
  const { parseEstimateData, snapshotShowsSetupFee } = require('./setup-fee-obligation')._private;
  const estimateData = parseEstimateData(estimate.estimate_data);
  const shown = estimateData.acceptedSetupFeeAmount == null
    ? snapshotShowsSetupFee(estimateData)
    : { evidence: 'shown', amount: estimateData.acceptedSetupFeeAmount };
  const waveGuardCents = shown.evidence === 'shown' && shown.amount != null
    ? Math.round(Number(shown.amount) * 100) : (shown.evidence === 'shown' ? NaN : 0);
  const claim = await conn('setup_fee_claims').where({ invoice_id: invoice.id })
    .forUpdate().noWait().first('amount', 'estimate_id');
  if (claim?.estimate_id && String(claim.estimate_id) !== String(estimateId)) return false;
  const claimCents = claim ? Math.round(Number(claim.amount) * 100) : 0;
  if (![waveGuardCents, claimCents].every(Number.isSafeInteger)
      || Math.min(waveGuardCents, claimCents) < 0 || (claim && claimCents === 0)) return false;
  return billedCents === waveGuardCents + claimCents;
}

function sumBaseApplicationCents(row) {
  let items = row?.line_items;
  if (typeof items === 'string') {
    try { items = JSON.parse(items); } catch { items = null; }
  }
  if (!Array.isArray(items)) return 0;
  const { lineIsBaseApplication } = require('./invoice');
  return items.reduce((sum, li) => {
    const qty = li?.quantity != null ? Number(li.quantity) : 1;
    const amt = li?.amount != null ? Number(li.amount) : Number(li?.unit_price) * qty;
    return Number.isFinite(amt) && amt > 0 && lineIsBaseApplication(li) ? sum + Math.round(amt * 100) : sum;
  }, 0);
}

