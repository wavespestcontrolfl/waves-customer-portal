// Same-trip first-application billing ALERT — periodic SWEEP over STAMPED
// PROVENANCE (owner ruling, 2026-09-27; supersedes the #5021 round-3..9
// "alert from every writer" design AND the round-10..r8 structural-guessing
// sweep — see the PR body for the full ruling history). A reserved-accept
// slot that sells MORE than one recurring program mints ONE combined
// "First service application" invoice, linked to the RESERVED row
// (invoices.scheduled_service_id). Every OTHER program's promoted parent is
// left with estimated_price NULL on purpose — treated as covered by that
// shared invoice, found by a shared date or, once the visits diverge, by the
// member's stamp (see estimate-converter.js reservedAcceptPerVisitSplit and
// estimate-first-application-invoice.js
// findFirstApplicationInvoiceForEstimateService).
//
// PRIOR DESIGNS (superseded, see PR #5021's body for the full history):
// round 1-2 auto-split the shared invoice's money at move time. Round 3-7
// replaced that with a durable, invoice-row hold. Round 8-9 replaced the
// hold with an in-transaction admin alert fired from every date-changing
// writer. Round 10 replaced that with a periodic sweep that GUESSED
// same-trip membership structurally (an unpriced sibling, or one with no
// live invoice of its own) — Codex round-8-on-the-sweep proved that guess
// can't tell a genuine same-trip pair apart from two independently billed
// recurring programs that simply haven't both been invoiced yet.
//
// THIS DESIGN (owner ruling 2026-09-27): record the relationship AT THE
// SOURCE instead of guessing it later. scheduled_services.
// first_application_invoice_id is stamped, once, on every member a combined
// invoice covers — the reserved anchor AND each promoted same-day sibling —
// by estimate-converter.js's stampCombinedFirstApplicationInvoiceCoverage,
// in the SAME transaction that mints the invoice, and ONLY when 2+ programs
// actually share it (a single-program accept is never stamped as a pair).
// A backfill migration (20260927220000) stamped the small number of live
// historical pairs using the OLD text-based recognition
// (isAutoGeneratedPayPerApplicationInvoice) one time. This module now
// NEVER guesses membership: it reads the stamp, period. A periodic sweep
// (every 10-15 minutes, see server/services/scheduler.js) finds every
// stamped visit, groups by invoice, re-derives each group's state fresh
// from current data, and opens/refreshes or clears ONE durable admin alert
// per STAMPED INVOICE GROUP (an estimate can carry more than one, when it
// has more than one stamped combined-invoice group from separate
// acceptances) — judged on live state, never on which write just happened.
// No auto-split, no invoice hold, no structural inference: the office
// splits the invoice by hand.
//
// Candidate discovery (loadCandidates) is now a single, direct query:
// every scheduled_services row with first_application_invoice_id NOT NULL,
// joined to that invoice, restricted to an OPEN invoice OR one with a
// standing alert not yet confirmed resolved (see loadCandidates for the
// exact recovery condition — this replaces the old established-anchor
// history lookup with a much smaller, directly-correlated EXISTS keyed on
// the alert's own stamped invoiceId). groupCandidatesByInvoice groups the
// resulting rows by first_application_invoice_id — ALWAYS exactly the
// invoice's own covered members, never an inferred or unioned set. The
// anchor is simply the member whose id the invoice's own
// scheduled_service_id points at (invoices.scheduled_service_id) — no
// anchor-identity machinery, no union-of-verdicts safety net, no
// established-vs-fresh split: every group is evaluated the same way, once.
//
// Divergence identification (evaluateGroupDivergence/divergingSiblings) is
// UNCHANGED from the structural-guessing design and stays exactly as
// reliable: a sibling diverges whether or not it has picked up its own
// estimated_price, whether or not it has since COMPLETED (completing a
// visit never settles or rewrites the still-open combined invoice), and a
// member in ANY "work will not be performed" terminal status (cancelled,
// skipped, no-show — the shared VISIT_NEVER_RAN_STATUSES vocabulary,
// invoice-helpers.js) still needs review regardless of date divergence,
// since none of those statuses removes its charge from the combined
// invoice (voidOpenInvoicesForCancelledService and its skip/no-show
// equivalents only void an invoice linked to THAT service's OWN
// scheduled_service_id).
//
// A diverging or never-ran member resolves the SAME way either design:
// once it has its OWN LIVE invoice (has_own_live_invoice, linked via
// invoices.scheduled_service_id to its own id — the same linkage
// findFirstApplicationInvoiceForEstimateService uses), the office has
// completed the instructed manual split for that visit and it no longer
// needs an alert. "Live" excludes the full canonical canceled vocabulary
// (InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES), not just void.
// This remains signal (a) ALONE, deliberately, never a dollar
// reconciliation against the combined invoice's total — three independent
// rounds of the structural-guessing design proved a dollar comparison
// unreliable here (setup fees, gross/net plan-credit mismatches,
// multi-sibling attribution ambiguity in a 3+ program group), and none of
// that changes just because membership is now stamped instead of guessed.
//
// Settlement is judged from the GOVERNING invoice's status — paid, prepaid,
// processing, or the canonical void/refunded/canceled/cancelled
// vocabulary (SETTLED_INVOICE_STATUSES, reused directly from
// invoice-helpers.js's INVOICE_UNCOLLECTIBLE_STATUSES) — re-read FRESH
// under FOR UPDATE inside this estimate's own evaluation transaction
// (evaluateEstimateCandidates), never the possibly-stale status
// loadCandidates read outside any per-estimate transaction. The GOVERNING
// invoice (resolveGoverningInvoice) is normally the stamped invoice itself.
// But a reserved anchor's combined invoice can be VOIDED and REBILLED on
// the SAME anchor visit (Charge Now, or completion on the priced reserved
// row, minting a live replacement linked to the same
// invoices.scheduled_service_id) — the accept-time stamp is never rewritten
// when that happens (owner ruling: the stamp stays accept-time-only), so
// once the stamped invoice has gone terminal, evaluateEstimateCandidates
// looks for ANY live invoice on the anchor's own scheduled_service_id — no
// text recognition at all (Codex round-9 P1: InvoiceService.update lets a
// live replacement's title/notes be edited on an unpaid invoice, so relying
// on isAutoGeneratedPayPerApplicationInvoice here let a renamed replacement
// fall back to the dead stamped row and silently clear a still-live
// combined charge). If one exists (the oldest still-collectible one, else
// the newest settled one — Codex round 14 P1), it governs everything
// downstream instead: divergence's own invoiceStatus, the alert's invoice
// number/total/link, and the fingerprint's invoiceId/invoiceTotal (Codex
// round 7 P1 on the prior structural-guessing design: a cancelled/void
// sibling clearing the alert while a live invoice still charged both
// programs). This alert is advisory, never a charge or a hold: the pair is
// still genuinely diverged, with an unpriced sibling and no own live
// invoice, so the office must look regardless of what the anchor's live
// invoice turns out to be — even an UNRELATED hand invoice (a repair, a
// one-off charge) sharing the same scheduled_service_id still governs and
// still raises the alert, since failing toward alerting is this module's
// policy and failing toward silence is exactly the P1 this replaces. A
// terminal stamped invoice with no live invoice on the anchor at all keeps
// today's behavior exactly: it governs itself, settled, and clears.
//
// Durable record: the admin notification itself (notification-service.
// notifyAdmin, category 'billing'), keyed on estimate id + the sorted
// diverging visit ids — no invoice column, no separate "resolved" table.
// When the condition no longer holds (dates realigned, or the governing
// invoice settles/voids with no further live replacement), the standing
// alert for that estimate is marked read with an `autoCleared` stamp.
// Dedupe version is a DETERMINISTIC fingerprint of the live state
// (divergenceStateFingerprint) — anchor date, each unresolved member's own
// id+date+never-ran bucket, and the GOVERNING invoice's id+total — never a
// fresh timestamp, so an unchanged state stays dismissed and only a genuine
// change (including the governing invoice itself changing, e.g. a void
// replaced by a live reissue) reopens it. A standing alert the SWEEP ITSELF
// auto-cleared that recurs is always a genuinely NEW recurrence even when
// the fingerprint happens to exactly match the pre-clear state
// (recurrenceGeneration, bumped only on an auto-cleared recurrence). Race
// safety: the reopen-after-dismissal decision takes the SAME advisory lock
// notifyAdmin's own dedupe path takes, held through notifyAdmin's own
// write.
//
// Fair batching: the whole stamped candidate set is bounded to a
// SWEEP_BATCH_LIMIT-sized batch per tick via a small persisted cursor
// (first_application_sibling_split_sweep_cursor — its `last_estimate_id`
// column now holds the last-visited first_application_invoice_id; the
// column keeps its original name because the migration that created it is
// already pushed and frozen, but a uuid is a uuid either way and the
// pagination logic never inspects which kind of id it holds), ordered and
// wrapped by invoice id so every candidate is visited within a bounded
// number of ticks and none is starved. The "always re-check a standing,
// unconfirmed alert even after its invoice settles" recovery this used to
// need a whole separate established-anchor code path for is now just one
// clause of loadCandidates' own WHERE — every candidate loadCandidates
// returns is equally current, so there is no more "recovery path that
// must never be bounded" to special-case; the same fair batch covers
// everything.
//
// Durability: each candidate INVOICE GROUP is evaluated in its OWN
// transaction. A failure on one group is logged and left for the next
// tick to retry — it never blocks or rolls back any other group's
// evaluation in the same run.

const db = require('../models/db');
const logger = require('./logger');
const InvoiceService = require('./invoice');
const { INVOICE_UNCOLLECTIBLE_STATUSES, VISIT_NEVER_RAN_STATUSES } = require('./invoice-helpers');

// The canonical "this visit will never be serviced" vocabulary: 'skipped'
// and 'no_show' are equally terminal, equally never-serviced statuses on
// the same scheduled_services.status CHECK constraint (AGENTS.md) as
// 'cancelled', and every one of them leaves a same-trip sibling's charge
// on the combined invoice exactly the way a cancellation does. 'canceled'
// (single L) is in the shared list defensively but is not a value the
// CHECK constraint accepts for scheduled_services — harmless to check for,
// never actually matched. Deliberately NOT 'completed': work WAS
// performed, so it is never a "will not be serviced" status.
function neverRan(status) {
  return VISIT_NEVER_RAN_STATUSES.includes(String(status || ''));
}

// Per-status alert phrasing for a never-ran member (raiseDivergenceAlert) —
// falls back to a neutral phrase for any future addition to the shared
// vocabulary this module hasn't been taught specific wording for yet.
const NEVER_RAN_PHRASE = Object.freeze({
  cancelled: 'was cancelled',
  canceled: 'was cancelled',
  skipped: 'was skipped',
  no_show: 'was a no-show',
});
function neverRanPhrase(status) {
  return NEVER_RAN_PHRASE[String(status || '')] || 'will not be serviced';
}

// The canonical "this invoice will never collect any more money"
// vocabulary — reused directly from invoice-helpers.js so this module can
// never locally drift from it (it once did, missing 'processing').
const SETTLED_INVOICE_STATUSES = INVOICE_UNCOLLECTIBLE_STATUSES;
// The subset of SETTLED_INVOICE_STATUSES that actually COLLECTED money
// (as opposed to void/refunded/canceled/cancelled, which never collected
// outstanding money or already gave it back). Same literal set already
// used ad hoc elsewhere in the app (e.g. appointment-card-request.js,
// annual-prepay-renewals.js) for the identical "has this invoice actually
// been charged" question — kept local here rather than promoted to
// invoice-helpers.js since nothing else in THIS module needs it exported.
// P1-C (Codex round 13): a governing invoice going straight to 'clear' the
// instant it settles used to treat a PAID invoice exactly like a VOIDED
// one — but a paid invoice that still covers a member who will never run
// (cancelled/skipped/no-show) left the office holding money for work that
// will not happen, with no alert telling them to refund or credit it.
// 'processing' is deliberately NOT here (Codex round 14 P1): on an invoice it
// means a payment still in flight (an ACH debit, or a card / Terminal /
// saved-card attempt parked for reconciliation) — not collected money yet. It can still
// bounce, so "refund or credit" copy for it would be wrong; it gets its own
// verdict (payment_pending_never_ran) below.
const PAID_INVOICE_STATUSES = Object.freeze(['paid', 'prepaid']);
function isInvoicePaid(status) {
  return PAID_INVOICE_STATUSES.includes(String(status));
}
// A payment still processing (any tender): settled for collection purposes (nothing more
// to send the customer) but not yet money in hand. A never-ran covered member
// here gets a "wait for the payment to resolve" alert, never a refund
// instruction; once the invoice turns paid the paid_never_ran alert takes over
// (different dedupe key, so the pending alert auto-clears), and a bounced
// payment (back to an open status) falls into the ordinary open-invoice review.
const PAYMENT_PENDING_INVOICE_STATUSES = Object.freeze(['processing']);
function isInvoicePaymentPending(status) {
  return PAYMENT_PENDING_INVOICE_STATUSES.includes(String(status));
}
// Every invoice status whose never-ran covered members need the money-side
// review (paid → refund/credit, processing → wait for settlement).
const MONEY_REVIEW_INVOICE_STATUSES = Object.freeze([...PAID_INVOICE_STATUSES, ...PAYMENT_PENDING_INVOICE_STATUSES]);
const SWEEP_LIMIT = 500;
// Scoped to the STAMPED invoice group, not just the estimate (Codex
// round-12 P1): when one estimate has more than one stamped combined-
// invoice group (separate acceptances under the same estimate on
// different dates), an estimate-wide prefix let evaluating group B's
// clear-others-before-raise (and every settle/realign/not_a_pair/
// invoice_missing/no_anchor clear) wipe out group A's still-valid standing
// alert. stampedInvoiceId is the group's fixed identity for its whole
// life — unlike the governing/replacement invoice id, which can shift to
// a live replacement once the stamped invoice goes terminal — so every
// clear and every raise for this group must stay under this exact prefix,
// never the estimate-wide one.
const DEDUPE_PREFIX = (estimateId, stampedInvoiceId) => `first_application_sibling_divergence:${estimateId}:${stampedInvoiceId}:`;

function dateOnly(value) {
  if (!value) return null;
  if (value instanceof Date) return value.toISOString().slice(0, 10);
  return String(value).split('T')[0].slice(0, 10);
}

function isInvoiceSettled(status) {
  return SETTLED_INVOICE_STATUSES.includes(String(status));
}

// Members currently diverging from the anchor's date: not the anchor
// itself — deliberately NOT filtered on estimated_price (a sibling that
// has picked up its own price still shares the same combined charge on
// the invoice until someone actually splits it), NOT filtered on
// completed_at (completing a visit never settles or rewrites the
// still-open COMBINED invoice), and NOT filtered on status at all — a
// never-ran member can still appear here if it also happens to have moved
// off the anchor's date; evaluateGroupDivergence's own
// neverRanNeedingReview is what actually decides a never-ran member's
// fate, date-diverged or not. Also NOT filtered on has_own_live_invoice —
// this is the RAW divergence (dates disagree); evaluateGroupDivergence is
// the one that decides which of these still need an alert.
function divergingSiblings(anchor, members) {
  const anchorDate = dateOnly(anchor.scheduled_date);
  return members.filter((m) => String(m.id) !== String(anchor.id)
    && dateOnly(m.scheduled_date) !== anchorDate);
}

// A top-level sibling in ANY "work will not be performed" terminal status
// (cancelled/skipped/no-show) still covered by the combined invoice: none
// of those statuses removes its share of the combined charge, whether or
// not its date ever diverged from the anchor's. "Covered" mirrors
// has_own_live_invoice's own scope: once the sibling has its own live
// invoice, the office has already hand-split it and it no longer needs
// review. Shared by evaluateGroupDivergence's own open-invoice branch
// (neverRanNeedingReview) AND its paid-invoice branch (P1-C) — the exact
// same membership question ("which covered members will never run and
// haven't been split off yet") whether the invoice is still open or has
// already collected money; only what happens next (alert copy, whether a
// plain date divergence alone also qualifies) differs between the two.
//
// includeAnchor (Codex round 14 P1, paid/processing review; also the
// still-OPEN review below, Codex round 19 P2): the combined invoice bills
// the ANCHOR's own share too, so an invoice whose anchor was cancelled/
// skipped/no-show holds (or, while still open, still charges) money for
// work that will not happen exactly like a never-ran sibling does. For the
// anchor no invoice is treated as "split off": the combined invoice IS the
// anchor's own invoice (invoices.scheduled_service_id), so a live invoice on
// the anchor is never evidence the combined charge moved — even a genuinely
// separate one (a repair, a later visit charge) leaves the combined payment
// in place. The only resolutions are the governing invoice going refunded/
// void, the anchor being reactivated, or a human dismissal (which the
// deterministic fingerprint keeps dismissed while nothing changes).
//
// The open-invoice review used to exclude the anchor on the theory that
// cancelling the anchor voids the open combined invoice through
// voidOpenInvoicesForCancelledService — but that void is fired-and-forget
// (job-status.js) and can fail silently. When it does, an anchor that will
// never run stays covered by a combined invoice nobody has flagged, and
// excluding it here let evaluateGroupDivergence read the group as realigned
// and clear a standing alert (or never raise one) for a still-open invoice
// that still charges for work that will not happen. Both never-ran-covered-
// members verdicts (paid/processing above, and the still-open one below)
// now include the anchor the same way.
function neverRanCoveredMembers(anchor, members, { includeAnchor = false } = {}) {
  return members.filter((m) => {
    if (!neverRan(m.status)) return false;
    if (String(m.id) === String(anchor.id)) return includeAnchor;
    return !m.has_own_live_invoice;
  });
}

// Pure: the verdict for a group whose GOVERNING invoice is settled (paid,
// prepaid, processing, or the void/refunded/canceled vocabulary).
//
// Deliberately NOT alerted: a paid (or processing) invoice whose covered
// members are all still active but merely diverged by date. Once the money
// is collected there is nothing left to split by hand, and the second-charge
// risk is closed at the source: findFirstApplicationInvoiceForEstimateService
// (estimate-first-application-invoice.js) now finds the combined invoice by
// the member's STAMP, not only by a shared scheduled_date, so completing or
// charging a moved sibling reuses/suppresses on the paid combined invoice
// instead of minting a second charge (Codex round 14 P1, PR #5021). Only a
// never-ran covered member (anchor included) needs a money-side alert.
function settledInvoiceVerdict(anchor, members, invoiceStatus) {
  const paid = isInvoicePaid(invoiceStatus);
  const pending = isInvoicePaymentPending(invoiceStatus);
  if (paid || pending) {
    const neverRanMembers = neverRanCoveredMembers(anchor, members, { includeAnchor: true });
    if (neverRanMembers.length) {
      return { action: 'alert', reason: paid ? 'paid_never_ran' : 'payment_pending_never_ran', diverging: neverRanMembers };
    }
  }
  return { action: 'clear', reason: 'invoice_settled' };
}

// The pure detection predicate: given the group's anchor row, every member
// row (each carrying has_own_live_invoice and status), and the shared
// invoice's current status, decide whether to alert, clear a standing
// alert, or do nothing. No DB access — the sweep and every unit test call
// this the same way.
function evaluateGroupDivergence({ anchor, members, invoiceStatus }) {
  if (!anchor || !Array.isArray(members) || members.length < 2) {
    return { action: 'clear', reason: 'no_group' };
  }
  if (isInvoiceSettled(invoiceStatus)) {
    // P1-C: a PAID (collected) governing invoice does not clear
    // unconditionally any more. If a stamped member that invoice's payment
    // covers will never run (cancelled/skipped/no-show) and hasn't been
    // split off with its own live invoice, the office already collected
    // money for work that will not happen — that needs a refund/credit
    // alert, distinct from the "split it by hand while still open" one
    // below. A 'processing' (payment in flight) invoice gets the "wait for the
    // payment to settle" variant instead. A voided/refunded/canceled/
    // cancelled invoice never collected outstanding money (or already gave
    // it back), so it keeps clearing unconditionally exactly as before.
    //
    // CONTRACT: a paid group whose ACTIVE members merely diverged by date
    // clears here (reason invoice_settled) — money is safe because the shared
    // lookup (findFirstApplicationInvoiceForEstimateService) finds the paid
    // combined invoice by stamp once a sibling moves, so completion / Charge
    // Now never mint a second charge for it. See settledInvoiceVerdict.
    return settledInvoiceVerdict(anchor, members, invoiceStatus);
  }
  const diverging = divergingSiblings(anchor, members);
  // A diverging sibling that has already picked up its OWN live invoice
  // has been split off by hand — the office completed the instructed
  // manual split for that visit, so it no longer needs an alert. A
  // NEVER-RAN diverging sibling (cancelled, skipped, or no-show) is
  // handled separately below (neverRanNeedingReview), never here — it
  // needs different alert copy and, unlike a plain diverging sibling,
  // needs review even when it never diverged by date at all.
  const unresolvedDiverging = diverging.filter((m) => !m.has_own_live_invoice && !neverRan(m.status));

  // Same membership question as the paid-invoice branch above (shared via
  // neverRanCoveredMembers), for the still-open invoice — anchor included
  // (Codex round 19 P2): voidOpenInvoicesForCancelledService is fired and
  // forgotten (job-status.js) when the anchor itself is cancelled/skipped/
  // no-shown, so its failure must never be the ONLY thing standing between
  // a never-ran anchor and a silently-cleared alert on an invoice that
  // still charges for it.
  const neverRanNeedingReview = neverRanCoveredMembers(anchor, members, { includeAnchor: true });

  const unresolved = [...unresolvedDiverging, ...neverRanNeedingReview];
  if (!unresolved.length) {
    // 'split_completed' whenever there was ever something here needing
    // hand resolution (a diverging or never-ran-and-covered sibling) that
    // has since been resolved — 'realigned' only when the group never had
    // anything beyond a plain date mismatch to begin with. Still excludes
    // the anchor: reaching this branch at all means neverRanNeedingReview
    // came back empty, and with includeAnchor:true (Codex round 19 P2) that
    // already guarantees the anchor is not CURRENTLY never-ran — a
    // never-ran anchor always keeps this verdict in the alert branch above,
    // never here — so checking the anchor's status here could never change
    // the answer; the exclusion is kept only because it made that
    // impossibility explicit at the one call site that could otherwise look
    // like an oversight.
    const everNeededResolution = diverging.length > 0
      || members.some((m) => String(m.id) !== String(anchor.id) && neverRan(m.status));
    return { action: 'clear', reason: everNeededResolution ? 'split_completed' : 'realigned' };
  }
  return { action: 'alert', reason: 'diverged', diverging: unresolved };
}

// Deterministic fingerprint of the live divergence state — the anchor's
// own date, each alerted sibling's own id+date+never-ran bucket (sorted,
// so member ORDER never matters), and the shared invoice's id+total. Used
// as notifyAdmin's dedupeVersion: NOT a fresh timestamp minted whenever
// the standing alert happens to be dismissed. Only a changed fingerprint
// reopens a dismissed alert; an unchanged fingerprint stays dismissed.
// Never-ran status is folded in as a coarse bucket, not the raw status
// string: an ACTIVE member's status churning through its normal lifecycle
// (confirmed → en_route → on_site) while still diverging is lifecycle
// noise, never a real change in the billing conflict, and must not reopen
// a dismissal.
function divergenceStateFingerprint({ anchor, diverging, invoiceId, invoiceTotal }) {
  const anchorDate = dateOnly(anchor.scheduled_date);
  const parts = diverging
    .map((d) => `${d.id}:${dateOnly(d.scheduled_date)}:${neverRan(d.status) ? 'never_ran' : 'active'}`)
    .sort();
  const total = invoiceTotal != null && Number.isFinite(Number(invoiceTotal)) ? Number(invoiceTotal).toFixed(2) : null;
  return JSON.stringify({
    anchorDate,
    diverging: parts,
    invoiceId: invoiceId != null ? String(invoiceId) : null,
    invoiceTotal: total,
  });
}

// Candidate discovery: a single, direct query over the durable stamp — no
// structural guessing, no anchor inference. Every scheduled_services row
// with first_application_invoice_id NOT NULL is, by construction (see
// estimate-converter.js stampCombinedFirstApplicationInvoiceCoverage and
// the backfill migration), a genuine member of a real combined invoice.
//
// Restricted to an OPEN invoice, OR one with a standing alert not yet
// confirmed resolved, OR one that has gone terminal (void/refunded/
// canceled/cancelled) while the anchor visit (i.scheduled_service_id) has
// picked up ANOTHER live invoice: once a combined invoice is voided and the
// anchor is rebilled (Charge Now / completion re-minting the combined
// amount on the SAME anchor visit), that live replacement is what actually
// charges the group now — the stamped row going terminal must never make
// this group invisible to every future sweep (owner ruling 2026-09-27,
// Codex round 7 P1 on the prior design: a cancelled/void sibling clearing
// the alert while a live invoice still charged both programs). This third
// clause is deliberately keyed off the STAMPED invoice's own id (never the
// eventual governing invoice's id) so it never depends on whether an alert
// was ever raised, or on which invoice a PRIOR sweep resolved as governing
// — evaluateEstimateCandidates re-resolves the current governing invoice
// fresh every time. It never inspects invoice title/notes text at all — nor
// does resolveGoverningInvoice any more (Codex round-9 P1): ANY live
// invoice on the anchor's own scheduled_service_id is durable enough
// evidence on its own for this advisory alert.
//
// The alert-recovery clause is keyed on the STAMPED invoice id — `i.id` in
// this query is always the stamped invoice (the join is on
// m.first_application_invoice_id), which is fixed for the life of the
// group and never rewritten. raiseDivergenceAlert writes BOTH
// metadata.stampedInvoiceId (this fixed id) and metadata.invoiceId (the
// GOVERNING invoice's id at raise time, which can shift to a replacement
// and then to a further replacement) — the recovery clause matches on
// EITHER, so it survives any number of governing-invoice hand-offs, not
// just one (Codex round-9 P2: keying on invoiceId alone stopped matching
// the instant a governing REPLACEMENT itself went terminal, since neither
// this recovery clause nor the third clause below — which needs a
// CURRENTLY LIVE replacement — could find the group any more, and its
// standing alert stayed open forever with no future sweep able to
// re-evaluate or clear it). The plain invoiceId match is kept only for
// alerts raised before stampedInvoiceId existed.
function applyCandidateScope(scope) {
  scope.whereNotIn('i.status', SETTLED_INVOICE_STATUSES)
    .orWhereExists(function standingUnresolvedAlertExists() {
      this.select(1).from('notifications as n')
        .where('n.recipient_type', 'admin')
        .whereRaw("n.metadata->>'dedupeKey' LIKE 'first_application_sibling_divergence:%'")
        .whereRaw("(n.metadata->>'stampedInvoiceId' = i.id::text OR n.metadata->>'invoiceId' = i.id::text)")
        .whereRaw("n.metadata->>'autoCleared' IS DISTINCT FROM 'true'");
    })
    .orWhere((terminalWithLiveReplacement) => {
      terminalWithLiveReplacement
        .whereIn('i.status', InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES)
        .whereExists(function liveReplacementOnAnchorExists() {
          this.select(1).from('invoices as r')
            .whereRaw('r.scheduled_service_id = i.scheduled_service_id')
            .whereRaw('r.id <> i.id')
            .whereNotIn('r.status', InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES);
        });
    })
    // P1-C: a PAID (collected) invoice is normally excluded by the
    // first clause above (it's in SETTLED_INVOICE_STATUSES) — but a
    // group whose payment covers a stamped member that will never run
    // (cancelled/skipped/no-show) and has no own live invoice needs a
    // fresh refund/credit alert (evaluateGroupDivergence's
    // paid_never_ran verdict) the FIRST time that member goes never-ran,
    // before any standing alert exists to be recovered by the clause
    // above. Scoped to the invoice's OWN stamped members via the
    // first_application_invoice_id linkage (never the whole estimate),
    // and only a member with no own live invoice — one already
    // hand-split off is excluded here exactly like everywhere else in
    // this module, so a resolved paid group never becomes a candidate
    // through this clause alone.
    //
    // Also a 'processing' (payment in flight) invoice — the same shape gets
    // the payment_pending_never_ran alert (Codex round 14 P1). And the
    // ANCHOR itself qualifies when never-ran, with NO own-live-invoice
    // exclusion (Codex round 14 P1): the combined invoice sits on the
    // anchor's own scheduled_service_id, so "own live invoice" would
    // always find the paid combined invoice itself and hide a cancelled
    // paid anchor forever; and a separate live invoice on the anchor is
    // never evidence the combined charge moved (neverRanCoveredMembers).
    .orWhere((paidWithNeverRanMember) => {
      paidWithNeverRanMember
        .whereIn('i.status', MONEY_REVIEW_INVOICE_STATUSES)
        // Discovery admits EVERY paid/processing group with a never-ran
        // stamped member; whether that member was already split off is
        // decided in evaluation by flagOwnLiveInvoices' base-application
        // check (invoiceBillsBaseApplication), never by "any live invoice
        // on the row" in SQL — an unrelated add-on or repair invoice used
        // to hide the whole group here before evaluation could run
        // (Codex r17 P1, PR #5021). A genuinely split member evaluates to
        // no alert, at the cost of one cheap evaluation.
        .whereExists(function neverRanMemberOnInvoiceExists() {
          this.select(1).from('scheduled_services as nr')
            .whereRaw('nr.first_application_invoice_id = i.id')
            .whereIn('nr.status', VISIT_NEVER_RAN_STATUSES);
        });
    });
}

// Keyset page of candidate invoice ids (Codex r14 P2 on #5021): the sweep
// pages invoice ids in SQL — invoice id ascending, strictly after `afterId`
// — BEFORE loading any member rows, so the cursor bounds the DB read and
// memory, not only the per-group transactions. Same candidate predicate as
// loadCandidates (applyCandidateScope); an invoice counts only while at
// least one visit is stamped to it. `atOrBeforeId` (the wrap-around page)
// restarts from the beginning up to and including the cursor.
async function loadCandidateInvoiceIdPage(conn, { afterId = null, atOrBeforeId = null, limit = SWEEP_BATCH_LIMIT } = {}) {
  const q = conn('invoices as i')
    .whereExists(function stampedMemberExists() {
      this.select(1).from('scheduled_services as m').whereRaw('m.first_application_invoice_id = i.id');
    })
    .where(applyCandidateScope);
  if (afterId != null) q.where('i.id', '>', afterId);
  if (atOrBeforeId != null) q.where('i.id', '<=', atOrBeforeId);
  return q.orderBy('i.id', 'asc').limit(limit).pluck('i.id');
}

// One tick's batch, a stable round-robin over every candidate invoice: the
// page after the cursor, then (short of `limit`) a wrap-around page from
// the start up to the cursor. Every candidate is visited within
// ceil(candidates / limit) ticks and never starved behind the head of the
// list; a batch never repeats an invoice.
async function loadSweepBatchInvoiceIds(conn, { cursor = null, limit = SWEEP_BATCH_LIMIT } = {}) {
  const page = await loadCandidateInvoiceIdPage(conn, { afterId: cursor, limit });
  if (page.length >= limit || cursor == null) return page;
  const wrap = await loadCandidateInvoiceIdPage(conn, { atOrBeforeId: cursor, limit: limit - page.length });
  return [...page, ...wrap];
}

async function loadCandidates(conn, { limit = SWEEP_LIMIT, invoiceIds = null } = {}) {
  const query = conn('scheduled_services as m')
    .join('invoices as i', 'i.id', 'm.first_application_invoice_id')
    .whereNotNull('m.first_application_invoice_id')
    .where(applyCandidateScope);
  if (invoiceIds) query.whereIn('m.first_application_invoice_id', invoiceIds);
  const rows = await query
    .orderBy('m.first_application_invoice_id', 'asc')
    .orderBy('m.id', 'asc')
    .select(
      'm.id', 'm.scheduled_date', 'm.completed_at', 'm.status',
      'm.customer_id', 'm.source_estimate_id',
      'm.first_application_invoice_id as invoice_id',
    );
  if (rows.length >= limit) {
    logger.warn(`[first-application-sibling-split] ${rows.length} stamped first-application visits under evaluation — past the ${limit}-row watch threshold; every one is still swept this tick, but the backlog itself is worth investigating`);
  }
  return rows;
}

// Groups candidate MEMBER rows by the invoice they are stamped with — the
// whole group IS the invoice's covered members, never an inferred or
// unioned set. A group of exactly ONE (a stray single stamp — should never
// happen given stampCombinedFirstApplicationInvoiceCoverage's own 2+-only
// guarantee at stamp time, but reachable afterward if an operator NULLs
// one member's stamp by hand) is KEPT, not dropped (Codex round-11 P2 on
// PR #5021: a group that already collapsed to one stamped member before
// loadCandidates even ran used to be filtered out here, so
// evaluateEstimateCandidates' own fresh-re-read "< 2 members -> clear"
// branch never got a turn to run and a standing alert for that estimate
// could never auto-clear). Every group loadCandidates returns is handed to
// evaluateEstimateCandidates, which re-reads the CURRENT member count fresh
// inside its own transaction and decides from there.
function groupCandidatesByInvoice(candidates) {
  const byInvoice = new Map();
  for (const candidate of candidates) {
    const key = candidate.invoice_id;
    if (!byInvoice.has(key)) byInvoice.set(key, []);
    byInvoice.get(key).push(candidate);
  }
  return [...byInvoice.values()];
}

// Marks read (with an autoCleared stamp) every standing alert for this
// stamped invoice group (the prefix is estimate + stamped invoice id, so
// another combined invoice under the same estimate is never touched)
// whose dedupeKey carries the given prefix — optionally excluding
// one key that is about to be raised/refreshed instead. Deliberately NOT
// scoped to whereNull('read_at'): an alert a human already DISMISSED while
// the group was still diverging must ALSO get the autoCleared stamp once
// the group genuinely resolves — otherwise raiseDivergenceAlert's
// wasAutoCleared check never sees the resolution, and an identical-dates
// recurrence after a plain dismissal + real realignment stays silently
// dismissed forever. COALESCE(read_at, NOW()) never disturbs an existing
// dismissal timestamp; it only sets read_at on a row that was still
// unread.
async function clearStandingAlerts(conn, prefix, { exceptKey = null } = {}) {
  let q = conn('notifications').where({ recipient_type: 'admin' })
    .whereRaw("metadata->>'dedupeKey' LIKE ?", [`${prefix}%`]);
  if (exceptKey) q = q.whereRaw("metadata->>'dedupeKey' <> ?", [exceptKey]);
  return q.update({
    read_at: conn.raw('COALESCE(read_at, NOW())'),
    metadata: conn.raw("COALESCE(metadata, '{}'::jsonb) || ?::jsonb", [JSON.stringify({ autoCleared: true })]),
  });
}

// The alert's invoice reference sentence. isReplacement (Codex round-9 P1):
// the original combined invoice went terminal and a DIFFERENT live invoice
// on the anchor now governs — say so explicitly so staff don't go looking
// for the charge on the (dead) original.
function alertInvoiceReference(invoice, estimateId) {
  if (!invoice) return `Check the first-application invoice for estimate #${estimateId}.`;
  const ref = invoice.invoice_number || invoice.invoice_id;
  return invoice.isReplacement
    ? `The original combined invoice is no longer live — the charge now sits on invoice ${ref}.`
    : `Invoice ${ref}.`;
}

// Pure: the alert's body copy (per-member detail lines, lead sentence,
// action sentence) for one diverging set — extracted out of
// raiseDivergenceAlert so that function's own complexity stays bounded and
// this copy logic is unit-testable on its own. Never-ran members
// (cancelled/skipped/no-show) get distinct copy from a plain moved member:
// the office action isn't "split it by hand" — the visit already isn't
// happening. A never-ran member can ALSO have moved off the anchor's date;
// the never-ran copy always wins for it since that's the actual remaining
// action, regardless of date. paid_never_ran (P1-C) narrows further: the
// combined invoice already COLLECTED money (paid/prepaid/processing), so
// the action is a refund/credit, never "remove its charge" from a
// still-open invoice. evaluateGroupDivergence only ever produces that
// verdict from neverRanCoveredMembers alone, so movedMembers is always
// empty for it — the branches below still cover it defensively rather than
// assuming that invariant holds forever.
//
// payment_pending_never_ran (Codex round 14 P1): the invoice's payment is
// still processing — an ACH debit, or a card / Terminal / saved-card attempt
// parked for reconciliation (Codex r17 P2 on #5021: the copy stays
// tender-neutral) — so nothing is collected yet and it may still
// bounce — the copy says to WAIT for it to resolve, never to refund or credit
// now. The alert clears on its own once the payment settles (the paid alert
// takes over) or fails.
const MONEY_ALERT_COPY = Object.freeze({
  paid_never_ran: {
    memberAction: 'refund or credit its share of the already-paid invoice',
    leadSentence: 'A same-trip visit from one estimate will not be serviced, and the combined invoice has already been paid',
    actionSentence: 'The combined first-application invoice already collected money for it — refund or credit that share.',
  },
  payment_pending_never_ran: {
    memberAction: 'its share is part of a payment that is still processing',
    leadSentence: 'A same-trip visit from one estimate will not be serviced, and the combined invoice\'s payment is still processing (not yet settled or reconciled)',
    actionSentence: 'Wait for that payment to settle, fail, or be reconciled before refunding or crediting that share — this alert updates when it resolves.',
  },
});
function buildDivergenceAlertCopy({ diverging, anchorDate, alertKind }) {
  const neverRanMembers = diverging.filter((d) => neverRan(d.status));
  const movedMembers = diverging.filter((d) => !neverRan(d.status));
  const moneyCopy = MONEY_ALERT_COPY[alertKind] || null;
  const detailParts = [
    ...movedMembers.map((d) => `visit ${d.id} now on ${dateOnly(d.scheduled_date)} (was ${anchorDate})`),
    ...neverRanMembers.map((d) => (moneyCopy
      ? `visit ${d.id} ${neverRanPhrase(d.status)} — ${moneyCopy.memberAction}`
      : `visit ${d.id} ${neverRanPhrase(d.status)} — remove its charge from the combined invoice`)),
  ];
  if (moneyCopy) {
    return { detail: detailParts.join('; '), leadSentence: moneyCopy.leadSentence, actionSentence: moneyCopy.actionSentence };
  }
  // A Postgres regression test asserts the exact "split it by hand"
  // substring survives whenever a moved member is present, so that phrase
  // is never rewritten for that case.
  const leadSentence = movedMembers.length
    ? 'Same-trip visits from one estimate landed on different days'
    : 'A same-trip visit from one estimate will not be serviced';
  const actionSentence = movedMembers.length
    ? 'The combined first-application invoice still charges for both — split it by hand.'
    : 'The combined first-application invoice still charges for it — remove that charge.';
  return { detail: detailParts.join('; '), leadSentence, actionSentence };
}

const ALERT_TITLES = Object.freeze({
  paid_never_ran: 'Paid first-application invoice covers a visit that will not run',
  payment_pending_never_ran: 'First-application payment still processing for a visit that will not run',
  diverged: 'First-application invoice may need to be split by hand',
});

// Raises (or refreshes) the durable admin alert for this exact diverging
// set. Takes the SAME advisory lock notifyAdmin's own dedupe path takes,
// and holds it through notifyAdmin's own write, so two concurrent sweep
// ticks racing the SAME dedupeKey can never land between each other's
// decision and write. That advisory lock is purely cooperative, though —
// it only excludes another caller that takes the SAME lock, and
// markReadAdmin (a human dismissal) never does — so it does nothing on its
// own to keep a dismissal from landing between this read and notifyAdmin's
// refresh write below (Codex round 21 P2). The `.forUpdate()` on the read
// is what actually closes that window: it takes a real row lock that
// notification-service.js's markReadAdmin, an ordinary UPDATE, always
// queues behind (Postgres locks every row an UPDATE touches, with or
// without an explicit FOR UPDATE on the writer's own side) — so a
// dismissal either commits and is visible in this very read (existing
// already reflects it), or is still queued when we get here and only
// proceeds once this whole transaction commits, at which point its own
// unconditional `read_at: new Date()` write lands on top of whatever this
// refresh wrote. Either way the LAST of the two to actually commit is what
// the row ends up holding — never a torn state where a dismissal that
// really did happen gets silently overwritten back to unread. Never
// touches the invoice or any visit row.
async function raiseDivergenceAlert(conn, {
  estimateId, anchor, diverging, invoice, customerId, dedupeKey, stampedInvoiceId = null, alertKind = 'diverged',
}) {
  await conn.raw('SELECT pg_advisory_xact_lock(hashtext(?))', [`admin:${dedupeKey}`]);
  const baseFingerprint = divergenceStateFingerprint({
    anchor, diverging, invoiceId: invoice?.invoice_id, invoiceTotal: invoice?.total,
  });
  // A standing alert the SWEEP ITSELF auto-cleared that is diverging again
  // is a genuinely NEW recurrence even when its fingerprint happens to
  // exactly match the pre-clear state — recurrenceGeneration is bumped
  // only on an auto-cleared recurrence, so repeated identical resolve/
  // recur cycles each still produce a distinct dedupeVersion. A PLAIN
  // human dismissal (read_at set, never autoCleared) keeps the
  // deterministic-fingerprint dedupe: unchanged state stays dismissed.
  const existing = await conn('notifications').where({ recipient_type: 'admin' })
    .whereRaw("metadata->>'dedupeKey' = ?", [dedupeKey]).forUpdate().first('read_at', 'metadata');
  let existingMeta = existing?.metadata;
  if (typeof existingMeta === 'string') { try { existingMeta = JSON.parse(existingMeta); } catch { existingMeta = null; } }
  const wasAutoCleared = Boolean(existing?.read_at) && existingMeta?.autoCleared === true;
  const priorGeneration = Number(existingMeta?.recurrenceGeneration) || 0;
  const generation = wasAutoCleared ? priorGeneration + 1 : priorGeneration;
  const dedupeVersion = `${baseFingerprint}::g${generation}`;
  const anchorDate = dateOnly(anchor.scheduled_date);
  const { detail, leadSentence, actionSentence } = buildDivergenceAlertCopy({ diverging, anchorDate, alertKind });
  const invoiceRef = alertInvoiceReference(invoice, estimateId);
  await require('./notification-service').notifyAdmin(
    'billing',
    ALERT_TITLES[alertKind] || ALERT_TITLES.diverged,
    `${leadSentence}: ${detail}. ${actionSentence} ${invoiceRef}`,
    {
      // Query form only — the admin app has no /admin/estimates/:id page
      // (tests/admin-notification-link-shapes.test.js).
      link: invoice ? `/admin/invoices?invoice=${invoice.invoice_id}` : `/admin/estimates?estimateId=${estimateId}`,
      bell: true,
      metadata: {
        estimateId: String(estimateId),
        anchorId: String(anchor.id),
        divergingSiblingIds: diverging.map((d) => String(d.id)),
        customerId: customerId ? String(customerId) : null,
        // Read back by loadCandidates' own recovery EXISTS clause (kept for
        // alerts raised before the stampedInvoiceId field below existed) —
        // the exact-match key that lets a settled invoice's still-standing,
        // not-yet-confirmed alert get one more evaluation instead of
        // disappearing from every future sweep.
        invoiceId: invoice ? String(invoice.invoice_id) : null,
        // The STAMPED invoice's own id — always written alongside
        // invoiceId above (Codex round-9 P2), and NEVER rewritten by a
        // later governing-invoice change: once a governing REPLACEMENT
        // itself later goes terminal (void/refunded/cancelled), neither
        // invoiceId (the old replacement's id) nor a plain stamped-invoice
        // lookup would match any future sweep's candidates, and the group
        // would vanish with its alert stuck open forever. Keying
        // loadCandidates' recovery EXISTS on this field too (in addition to
        // invoiceId, kept for pre-existing alerts) means the recovery
        // survives ANY number of governing-invoice hand-offs, not just one.
        stampedInvoiceId: stampedInvoiceId != null ? String(stampedInvoiceId) : null,
        // An alert we are (re)raising right now is by definition not in
        // the auto-cleared state any more — explicitly cleared here since
        // notifyAdmin's refresh merges onto the OLD metadata, which would
        // otherwise leave a stale autoCleared:true sitting on a reopened
        // alert forever.
        autoCleared: false,
        recurrenceGeneration: generation,
        // Which kind of alert this is (P1-C): 'paid_never_ran' when the
        // combined invoice already collected money and a covered member
        // will never run (refund/credit action),
        // 'payment_pending_never_ran' when that payment is still
        // processing (wait, then act), 'diverged' for the ordinary
        // still-open split-by-hand alert. Informational only — no read path
        // branches on it; the dedupeKey's own 'refund:' / 'pending:' marker
        // (see evaluateEstimateCandidates) is what actually keeps the alert
        // kinds from colliding.
        alertKind,
      },
      dedupeKey,
      dedupeVersion,
      refreshOnDedupe: true,
      trx: conn,
    },
  );
}

// Pure: which invoice actually GOVERNS this group's settlement/alerting
// right now. Normally the stamped invoice itself. But once the stamped
// invoice has gone terminal (void/refunded/canceled/cancelled), ANY live
// invoice on the anchor's own scheduled_service_id governs instead — by
// durable evidence (the linkage) alone, with NO text recognition (Codex
// round-9 P1: InvoiceService.update allows a live replacement's title/
// notes to be edited on an unpaid invoice, so a rename could make the old
// text-recognition test fall through to the dead stamped row and silently
// clear a still-live combined charge). liveAnchorInvoices is every OTHER
// live invoice sharing the anchor's scheduled_service_id. Which one governs
// (Codex round 14 P1): the OLDEST still-COLLECTIBLE one (not paid/prepaid/
// processing) if any — a newer, unrelated, already-paid invoice on the same
// visit must never hide an older combined replacement that still charges the
// group — else the NEWEST settled one. Ordered by created_at here (never by
// the caller's array order); rows without created_at keep their given
// newest-first order. This alert is advisory, not a
// charge: the pair is still genuinely diverged, with an unpriced sibling
// and no own live invoice, so the office needs to look regardless of what
// the anchor's live invoice actually is — even an UNRELATED hand invoice
// (a repair, a one-off charge) that happens to share the same
// scheduled_service_id still governs and still raises the alert, since
// failing toward alerting is this module's policy and failing toward
// silence is exactly the P1 this replaces. A terminal stamped invoice with
// NO live invoice on the anchor at all keeps today's behavior exactly: it
// governs itself, settled, and clears.
function createdAtMs(row) {
  const ms = row?.created_at != null ? new Date(row.created_at).getTime() : NaN;
  return Number.isFinite(ms) ? ms : null;
}
function newestFirst(rows) {
  return rows.map((row, index) => ({ row, index }))
    .sort((a, b) => {
      const at = createdAtMs(a.row);
      const bt = createdAtMs(b.row);
      if (at != null && bt != null && at !== bt) return bt - at;
      return a.index - b.index;
    })
    .map(({ row }) => row);
}
function resolveGoverningInvoice(stampedInvoice, liveAnchorInvoices) {
  if (!InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES.includes(stampedInvoice.status)) return stampedInvoice;
  // Codex r18 P1 (PR #5021): a live invoice on the anchor row governs — and
  // can drive refund / pending-payment instructions — only when it carries
  // DURABLE evidence that it bills the base application
  // (invoiceBillsBaseApplication: a positive line tagged client_id
  // `scheduled_<id>_primary`, which every service mint writes, or described
  // "First service application"). client_id is not among the fields
  // InvoiceService.update lets staff edit, so this is not the editable
  // title/notes text the round-9 ruling rejected. An unrelated paid repair or
  // add-on invoice on the anchor never becomes "the combined invoice" and
  // never earns a refund instruction; with no qualifying replacement the
  // terminal stamped invoice stays governing (void/refunded → clear).
  const { invoiceBillsBaseApplication } = require('./estimate-first-application-invoice');
  const ordered = newestFirst((liveAnchorInvoices || []).filter((inv) => invoiceBillsBaseApplication(inv)));
  const collectible = ordered.filter((inv) => !isInvoiceSettled(inv.status));
  if (collectible.length) return collectible[collectible.length - 1];
  return ordered[0] || stampedInvoice;
}

// Resolve the GOVERNING invoice before deciding anything: normally the
// stamped invoice itself. Only when the stamped invoice has gone terminal do
// we look for live invoices on the anchor's OWN scheduled_service_id — no
// title/notes recognition (Codex round-9 P1), but base-application line
// evidence is required (Codex r18 P1, see resolveGoverningInvoice) — locked
// FOR UPDATE right alongside it. resolveGoverningInvoice picks among them (oldest collectible,
// else newest settled — Codex round 14 P1), so created_at is selected too.
async function loadGoverningInvoice(conn, freshInvoice) {
  if (!InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES.includes(freshInvoice.status)) return freshInvoice;
  const liveAnchorInvoices = await conn('invoices')
    .where('scheduled_service_id', freshInvoice.scheduled_service_id)
    .whereNot('id', freshInvoice.id)
    .whereNotIn('status', InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES)
    .orderBy('created_at', 'desc')
    .forUpdate()
    .select('id', 'status', 'invoice_number', 'total', 'scheduled_service_id', 'created_at', 'line_items');
  return resolveGoverningInvoice(freshInvoice, liveAnchorInvoices);
}

// has_own_live_invoice per member: a LIVE invoice linked to that member's
// OWN scheduled_service_id — the real-data signal that the office has
// already hand-split that visit off the shared invoice. "Live" excludes the
// FULL canonical canceled vocabulary, not just void. For the ANCHOR, the
// stamped combined invoice and the governing invoice are excluded from that
// evidence — both sit on the anchor's own id by construction, so counting
// them would read "the anchor has its own invoice" for every group.
//
// Codex r16 P1 (PR #5021): "a live invoice on the sibling's row" is not, by
// itself, evidence that the sibling's share was split off — several invoices
// can share one visit (an add-on, a repair, a hand invoice for something
// else). The split evidence is the ONE shared base-application identity the
// whole codebase uses (invoiceBillsBaseApplication -> InvoiceService.
// lineIsBaseApplication: a positive line tagged client_id
// `scheduled_<id>_primary`, which "create invoice from service" writes, or
// described "First service application"). An own live invoice that does not
// bill the base application leaves the member UNresolved: the alert stands
// and the office confirms by hand. Fails toward alerting, never toward a
// silent clear.
async function flagOwnLiveInvoices(conn, freshMembers, { anchorId, anchorExcludedInvoiceIds }) {
  const { invoiceBillsBaseApplication } = require('./estimate-first-application-invoice');
  const ownInvoices = await conn('invoices')
    .whereIn('scheduled_service_id', freshMembers.map((m) => m.id))
    .whereNotIn('status', InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES)
    .select('id', 'scheduled_service_id', 'line_items');
  const excluded = new Set(anchorExcludedInvoiceIds.filter((id) => id != null).map(String));
  const ownInvoiceSet = new Set(ownInvoices
    .filter((inv) => String(inv.scheduled_service_id) !== String(anchorId) || !excluded.has(String(inv.id)))
    .filter((inv) => invoiceBillsBaseApplication(inv))
    .map((inv) => String(inv.scheduled_service_id)));
  return freshMembers.map((m) => ({ ...m, has_own_live_invoice: ownInvoiceSet.has(String(m.id)) }));
}

// Alert kind per verdict reason, and the dedupe-key marker each kind carries
