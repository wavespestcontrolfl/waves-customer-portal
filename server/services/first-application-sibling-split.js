// Same-trip first-application billing ALERT — periodic SWEEP design
// (owner ruling, 2026-09-27; supersedes the #5021 round-3..9 "alert from
// every writer" design — see the PR body for the full ruling history). A
// reserved-accept slot that sells MORE than one recurring program mints ONE
// combined "First service application" invoice, linked to the RESERVED
// row (invoices.scheduled_service_id). Every OTHER program's promoted
// parent is left with estimated_price NULL on purpose — treated as covered
// by that shared invoice while both visits share a date (see
// estimate-converter.js reservedAcceptPerVisitSplit and
// estimate-first-application-invoice.js
// findFirstApplicationInvoiceForEstimateService, whose own date-keyed match
// simply stops matching once a member's date diverges — no code change
// needed there).
//
// PRIOR DESIGNS (superseded, see PR #5021's body for the full history):
// round 1-2 auto-split the shared invoice's money at move time. Round 3-7
// replaced that with a durable, invoice-row hold. Round 8-9 replaced the
// hold with an in-transaction admin alert fired from every date-changing
// writer (admin-schedule.js, visit-groups.js, rebooker.js,
// intelligence-bar/schedule-tools.js + tools.js) — but Codex round 5 found
// that shape structurally leaky: a grouped move judged mid-batch raised a
// false alarm on an interim state (bulk-reschedule landing both siblings on
// the SAME new day), a sibling that picked up ANY price was excluded from
// ever alerting even though the shared invoice still charged for it, and
// the dedupe-reopen decision raced the alert's own advisory lock. Fixing
// each writer's own view of "did this move actually diverge the group" was
// the wrong shape — every writer would need its own final-state
// reconciliation forever.
//
// OWNER RULING (this design): stop alerting from the movers entirely. A
// periodic SWEEP (every 10-15 minutes, see server/services/scheduler.js)
// finds every OPEN (non-settled) first-application invoice, re-derives its
// estimate group fresh from current data, and opens/refreshes or clears
// ONE durable admin alert per estimate — judged on live state, never on
// which write just happened. No auto-split, no invoice hold: the office
// splits the invoice by hand.
//
// Candidate discovery (loadCandidates): bounded by invoices.status NOT IN
// the settled vocabulary (indexed column) joined to its anchor row via
// invoices.scheduled_service_id (also indexed) — the two columns every
// non-settled first-application invoice is cheap to find by.
//
// Candidacy is STRUCTURAL, not text-matched (PR #5021 Codex r6, head
// 2168cb0877): the prior gate, isAutoGeneratedPayPerApplicationInvoice's
// title/notes shape check, is a text match against invoices.title/.notes —
// columns InvoiceService.update lets staff freely edit on any unpaid
// invoice. A copy edit made before the FIRST sweep ever ran (so no standing
// alert yet names the invoice) silently and permanently dropped that
// invoice out of every future candidate scan, with no fallback to recover
// it. The durable, relational marker of a reserved-accept split instead
// (see the top of this header): the anchor is PRICED (estimated_price NOT
// NULL) and IS a recurring program, and it has at least one live, TOP-LEVEL
// (recurring_parent_id IS NULL) sibling under the SAME customer + estimate
// that is ALSO a recurring program but was deliberately left UNPRICED
// (estimated_price IS NULL) — the promoted parent the acceptance flow never
// prices because it is treated as covered by the anchor's own combined
// invoice. invoices has no estimate_id column to link through directly, so
// this still goes through scheduled_services.source_estimate_id via the
// anchor join, same as every other lookup in this area. A normal
// single-program estimate produces no such sibling at all (there is only
// ever the one top-level row), so it is never a candidate. Invoice
// title/notes text is NOT consulted at all any more — it stayed a gate for
// one estimate-side caller too many; this module needs none of it.
//
// Divergence identification (evaluateGroupDivergence/divergingSiblings) is
// keyed ONLY on estimate + visit ids — customer_id + source_estimate_id +
// recurring_parent_id IS NULL, never on invoice text. A sibling now diverges
// whether or not it has picked up its own estimated_price (Codex P1: a
// priced sibling still shares the same combined charge) and whether or not
// it has since COMPLETED (PR #5021 Codex r6, head 2168cb0877: completing a
// visit never settles or rewrites the still-open combined invoice — only a
// CANCELLED top-level visit is excluded, at the loadGroupMembers query
// level, since it was never going to be serviced).
//
// Settlement is judged from the invoice's OWN status only (paid, prepaid,
// or the canonical cancelled/refunded/void vocabulary
// InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES already defines) —
// never from the visits' estimated_price.
//
// Durable record: the admin notification itself (notification-service.
// notifyAdmin, category 'billing'), keyed on estimate id + the sorted
// diverging visit ids — no invoice column, no separate "resolved" table.
// When the condition no longer holds (dates realigned, or the invoice
// settles/voids), the standing alert for that estimate is marked read with
// an `autoCleared` stamp (same convention as supplies-consumption.js's
// clearMissedDeductionBells / ops-digest.js's resolved stamp) — the closest
// "resolve" mechanism notifications already support; there is no bespoke
// clear route to build here.
//
// Race safety (Codex P2): the reopen-after-dismissal decision takes the
// SAME advisory lock notifyAdmin's own dedupe path takes, and holds it
// continuously (same session, same transaction) through notifyAdmin's own
// write, so a concurrent dismissal can never land between the decision and
// the write.
//
// Dedupe version (pre-push P1 fix): dedupeVersion is built from a
// DETERMINISTIC fingerprint of the live state — anchor date, each
// unresolved diverging sibling's own id+date, and the invoice's id+total
// (divergenceStateFingerprint) — never a fresh timestamp minted just
// because the standing alert happens to be dismissed. A PLAIN human
// dismissal (read_at set, no autoCleared stamp) whose fingerprint is
// unchanged on the next tick stays dismissed; only a fingerprint change
// (a different dates tuple, or a different invoice id/total) re-opens it.
// A standing alert the SWEEP ITSELF auto-cleared (autoCleared:true —
// dates realigned or the group resolved) is different: its return is
// always a genuinely new recurrence, even when the fingerprint happens to
// exactly match the pre-clear state (realign, then diverge back onto the
// SAME date) — so raiseDivergenceAlert bumps a recurrenceGeneration
// counter on every auto-cleared recurrence and folds it into
// dedupeVersion, guaranteeing a fresh value each cycle without ever using
// a non-deterministic timestamp (Codex round-1 P1 on this fix).
//
// Manual-split resolution (pre-push P1 fix): once the office completes the
// instructed manual split, the sweep must stop alerting for the resolved
// sibling(s) without relying on invoice text. Signal chosen: a diverging
// sibling counts as split off once it has picked up its OWN LIVE invoice
// linked to its own scheduled_service_id (has_own_live_invoice, computed
// in loadGroupMembers) — the same invoices.scheduled_service_id linkage
// every other caller in this area (findFirstApplicationInvoiceForEstimateService)
// uses to resolve a visit's invoice, so a hand-split invoice is found the
// same way a minted one would be. "Live" excludes the full canonical
// canceled vocabulary (void, refunded, canceled, cancelled — Codex
// round-1 P1: void alone let a canceled "split" invoice falsely clear the
// alert), not just void.
//
// has_own_live_invoice is signal (a) ALONE, by deliberate choice, not an
// oversight (round-4..7 history): pre-push round 4 tried requiring the
// combined invoice's total to also go down; round 5 showed a group-wide
// "some reduction" check can't be attributed to a SPECIFIC sibling in a 3+
// program group; round 6 showed the combined invoice's raw total can carry
// a bundled setup fee, so comparing it against an application-only anchor
// price is the wrong basis; round 7 showed anchor.estimated_price is
// itself NET of accepted plan credits while the invoice's line items are
// GROSS (estimate-public.js grosses up the line and records the credit
// separately) — a different basis mismatch again. Every fix closed one gap
// and opened the next, because the invoice's composition (setup fees,
// rodent-bait fees, plan-credit slices, taxes, and whatever a future
// billing feature adds) is open-ended, and this module has no durable,
// always-available figure to reconcile a dollar amount against without
// re-deriving pricing logic that lives in estimate-converter.js /
// routes/estimate-public.js, not here (rule 15: there is no existing
// mechanism that survives to sweep time). This is exactly the contingency
// the task's own instructions anticipated: "fall back to (a) if (b) is not
// reliable" — three independent rounds proved (b) is not reliable here.
// has_own_live_invoice alone never inspects an amount, so it is immune to
// all of the above; the accepted trade-off is that a sibling invoice
// created while the combined invoice is technically left untouched (round
// 4's original concern) still clears the alert without dollar proof.
//
// EVERY live candidate anchor for an estimate is evaluated TOGETHER, never
// picked by a heuristic (pre-push history on head daf724131f and its
// predecessors): loadCandidates can return MORE THAN ONE invoice row for
// the same estimate — not just a stale/live pair for the SAME anchor
// (a voided-and-reissued invoice), but genuinely DIFFERENT anchors once a
// 3+ program group is partially split (a split-off sibling's own new
// invoice can independently satisfy the structural "still covered
// sibling" check on account of some OTHER, still-unresolved sibling).
// Three heuristics were tried and each failed on a real scenario: "prefer
// live over settled, newest wins" let a split sibling's newer invoice
// silently outrank the true anchor; "only the group's earliest live
// invoice may be a candidate" then excluded a split sibling correctly but
// ALSO excluded a legitimate reissue of the true anchor's own invoice
// (younger, by construction, than a split sibling invoiced BEFORE the
// reissue). No current-state-only heuristic can reliably tell "the true
// combined invoice, reissued" apart from "a split-off sibling's own
// separate invoice" — both are, symmetrically, a live invoice for a
// priced, recurring, top-level visit with at least one other still-needy
// sibling somewhere in the same estimate.
//
// So groupCandidatesByEstimate does NOT choose — it only groups raw rows
// by source_estimate_id. evaluateEstimateCandidates (the per-estimate
// transaction unit) then evaluates EVERY row in that group independently
// against the SAME shared members list, and takes the UNION: any row that
// finds a genuine divergence wins (its diverging set is added to the
// alert), and the estimate clears ONLY when EVERY row agrees nothing is
// wrong. This is safe in both directions: a split-off sibling's own
// invoice can only ever say 'clear' from its own narrow view (the true
// anchor always already "has its own invoice" — the shared one — from
// that narrow perspective, so it can never itself manufacture a false
// alert), while a stale/settled duplicate for the same anchor trivially
// says 'clear' too and simply contributes nothing to the union. The true
// anchor's own row, whenever it is live, always still says 'alert' for a
// genuinely uncovered sibling — and one 'alert' is enough.
//
// Durability: each candidate ESTIMATE (every row for it together) is
// evaluated in its OWN transaction. A failure on one estimate is logged
// and left for the next tick to retry — it never blocks or rolls back any
// other estimate's evaluation in the same run.

const db = require('../models/db');
const logger = require('./logger');
const InvoiceService = require('./invoice');

const SETTLED_INVOICE_STATUSES = Object.freeze(['paid', 'prepaid', ...InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES]);
const SWEEP_LIMIT = 500;
const DEDUPE_PREFIX = (estimateId) => `first_application_sibling_divergence:${estimateId}:`;

function dateOnly(value) {
  if (!value) return null;
  if (value instanceof Date) return value.toISOString().slice(0, 10);
  return String(value).split('T')[0].slice(0, 10);
}

function isInvoiceSettled(status) {
  return SETTLED_INVOICE_STATUSES.includes(String(status));
}

// Members currently diverging from the anchor's date: not the anchor
// itself — deliberately NOT filtered on estimated_price (Codex P1: a
// sibling that has picked up its own price still shares the same combined
// charge on the invoice until someone actually splits it), and
// deliberately NOT filtered on completed_at either (Codex round-6 P1 at
// head 2168cb0877: a moved sibling that COMPLETES before the next sweep
// used to be excluded here, so the group read as "realigned" even though
// completing a visit never settles or rewrites the still-open COMBINED
// invoice — the office lost the alert entirely). Only cancelled top-level
// visits are excluded, and that exclusion lives in loadGroupMembers's own
// query (a cancelled visit was never going to be serviced, so it is never
// a real billing conflict to resolve) — never here, since divergingSiblings
// is a pure function over whatever loadGroupMembers already decided counts
// as a member. Also deliberately NOT filtered on has_own_live_invoice here
// — this is the RAW divergence (dates disagree); evaluateGroupDivergence is
// the one that decides which of these still need an alert.
function divergingSiblings(anchor, members) {
  const anchorDate = dateOnly(anchor.scheduled_date);
  return members.filter((m) => String(m.id) !== String(anchor.id)
    && dateOnly(m.scheduled_date) !== anchorDate);
}

// The pure detection predicate: given the group's anchor row, every member
// row (each optionally carrying has_own_live_invoice — loadGroupMembers
// stamps this from a real invoices.scheduled_service_id lookup), and the
// shared invoice's current status, decide whether to alert, clear a
// standing alert, or do nothing. No DB access — the sweep and every unit
// test call this the same way. See the module header ("has_own_live_invoice
// is signal (a) ALONE") for why this is signal (a) alone, deliberately,
// and not a dollar comparison against the combined invoice.
function evaluateGroupDivergence({ anchor, members, invoiceStatus }) {
  if (!anchor || !Array.isArray(members) || members.length < 2) {
    return { action: 'clear', reason: 'no_group' };
  }
  if (isInvoiceSettled(invoiceStatus)) {
    return { action: 'clear', reason: 'invoice_settled' };
  }
  const diverging = divergingSiblings(anchor, members);
  if (!diverging.length) {
    return { action: 'clear', reason: 'realigned' };
  }
  // A diverging sibling that has already picked up its OWN live invoice
  // (linked to its own scheduled_service_id) has been split off by hand —
  // the office completed the instructed manual split for that visit, so it
  // no longer needs an alert. Only the still-unresolved diverging siblings
  // are reported/alerted on.
  const unresolved = diverging.filter((m) => !m.has_own_live_invoice);
  if (!unresolved.length) {
    return { action: 'clear', reason: 'split_completed' };
  }
  return { action: 'alert', reason: 'diverged', diverging: unresolved };
}

// Deterministic fingerprint of the live divergence state — the anchor's own
// date, each alerted sibling's own id+date (sorted, so member ORDER never
// matters), and the shared invoice's id+total. Used as notifyAdmin's
// dedupeVersion (pre-push P1 fix): NOT a fresh timestamp minted whenever the
// standing alert happens to be dismissed — that would reopen a dismissed
// alert on every sweep tick even with nothing materially different. Only a
// changed fingerprint (a different dates tuple, or a different invoice id
// or total) reopens a dismissed alert; an unchanged fingerprint stays
// dismissed.
function divergenceStateFingerprint({ anchor, diverging, invoiceId, invoiceTotal }) {
  const anchorDate = dateOnly(anchor.scheduled_date);
  const parts = diverging.map((d) => `${d.id}:${dateOnly(d.scheduled_date)}`).sort();
  const total = invoiceTotal != null && Number.isFinite(Number(invoiceTotal)) ? Number(invoiceTotal).toFixed(2) : null;
  return JSON.stringify({
    anchorDate,
    diverging: parts,
    invoiceId: invoiceId != null ? String(invoiceId) : null,
    invoiceTotal: total,
  });
}

// No title/notes here (PR #5021 Codex r6, head 2168cb0877): candidacy is
// structural now, and invoice text is never consulted for anything else in
// this module — see loadCandidates.
const CANDIDATE_COLUMNS = [
  'i.id as invoice_id', 'i.status as invoice_status', 'i.invoice_number',
  'i.total as invoice_total', 'i.created_at as invoice_created_at',
  'anchor.id as anchor_id', 'anchor.customer_id', 'anchor.source_estimate_id',
  'anchor.scheduled_date as anchor_scheduled_date', 'anchor.completed_at as anchor_completed_at',
];

// Groups candidate INVOICE rows by estimate — a plain grouping, never a
// pick-one-representative filter (see the module header for why: no
// current-state heuristic reliably tells "the true combined invoice,
// reissued" apart from "a split-off sibling's own separate invoice", so
// evaluateEstimateCandidates evaluates every row in each group together
// instead of this function choosing one). Preserves loadCandidates' own
// order within each group (oldest invoice first — no significance beyond
// determinism).
function groupCandidatesByEstimate(candidates) {
  const byEstimate = new Map();
  for (const candidate of candidates) {
    const key = candidate.source_estimate_id;
    if (!byEstimate.has(key)) byEstimate.set(key, []);
    byEstimate.get(key).push(candidate);
  }
  return [...byEstimate.values()];
}

// invoiceId values every currently-UNREAD sibling-divergence alert names in
// its own metadata (stamped there when raised — see raiseDivergenceAlert).
// Small and cheap by construction: bounded by however many such alerts are
// presently unread, never by total invoice history.
async function loadStaleAlertInvoiceIds(conn) {
  const alerts = await conn('notifications')
    .where({ recipient_type: 'admin' })
    .whereNull('read_at')
    .whereRaw("metadata->>'dedupeKey' LIKE 'first_application_sibling_divergence:%'")
    .select('metadata');
  const ids = new Set();
  for (const row of alerts) {
    let meta = row.metadata;
    if (typeof meta === 'string') { try { meta = JSON.parse(meta); } catch { meta = null; } }
    if (meta && meta.invoiceId) ids.add(meta.invoiceId);
  }
  return [...ids];
}

// Every currently OPEN (non-settled) first-application invoice, joined to
// its anchor (reserved/priced) scheduled_services row — bounded by two
// indexed columns (invoices.status, invoices.scheduled_service_id) — PLUS
// any invoice a currently-unread standing alert still names even though it
// no longer qualifies above (settled since the alert was raised — a PK
// lookup, bounded by the small unread-alert set above): without this
// second half, an invoice that settles between ticks would silently drop
// out of every future sweep and its alert would never auto-clear.
//
// Candidacy (PR #5021 Codex r6, head 2168cb0877 — see the module header
// for the full "why not text" rationale): the anchor must be PRICED
// (estimated_price NOT NULL) and a recurring program, and it must have at
// least one live, top-level, ALSO-recurring sibling under the same
// customer + estimate that is STILL COVERED by the anchor's shared invoice
// — either it was deliberately left UNPRICED (estimated_price IS NULL, the
// acceptance-time marker), OR it has no LIVE invoice of its own yet
// (checked against the same InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES
// vocabulary has_own_live_invoice uses). The OR matters: a sibling that
// picks up its own estimated_price BEFORE ever getting split off — the
// exact "a priced sibling still diverges" scenario this module's own P1
// fix already guarantees — would otherwise silently fall out of candidate
// discovery on its very first tick, before any standing alert exists to
// carry it through the stale-invoice fallback below. Checked with a
// correlated EXISTS against scheduled_services (bounded by the same
// customer_id/source_estimate_id shape loadGroupMembers already queries
// by, on the existing idx_scheduled_services_source_estimate index) plus a
// nested EXISTS/NOT EXISTS against invoices on its own indexed
// scheduled_service_id column. This also still rules out a normal
// single-program estimate (no sibling row exists at all) and a normal
// multi-program estimate where every program was independently priced AND
// invoiced from day one (neither OR branch matches for such a sibling).
// Invoice title/notes text is never consulted — a copy edit on the invoice
// can no longer drop a candidate out of every future scan. This CAN return
// more than one row for the same estimate — a split-off sibling's own new
// invoice can independently satisfy the "still covered sibling" check on
// account of some OTHER, still-unresolved sibling, same as the true
// anchor's own row can. That is deliberately NOT resolved here with a
// heuristic (age or otherwise — see the module header for why every one
// tried broke on a real scenario); evaluateEstimateCandidates evaluates
// every row for an estimate together instead. The second-half "stale"
// re-fetch below intentionally skips ALL of this structural re-checking:
// those invoice ids are already known relevant from a standing alert's own
// metadata, and re-deriving structural eligibility on every tick would
// risk dropping one the moment every sibling finally gets its own invoice.
//
// Deliberately UNBOUNDED by row count (Codex P1): the set this query
// selects is already bounded by "currently non-settled" — operationally
// small — so an ORDER BY + LIMIT here would silently starve every
// candidate past the cutoff forever (the same oldest N rows every tick,
// with nothing ever aging the newer ones in). `limit` is a WARNING
// threshold only — crossing it means the open backlog has grown large
// enough to be its own problem, worth an ops signal, never a reason to
// evaluate fewer of them.
async function loadCandidates(conn, { limit = SWEEP_LIMIT } = {}) {
  const candidates = await conn('invoices as i')
    .join('scheduled_services as anchor', 'anchor.id', 'i.scheduled_service_id')
    .whereNotIn('i.status', SETTLED_INVOICE_STATUSES)
    .whereNotNull('anchor.source_estimate_id')
    .whereNull('anchor.recurring_parent_id')
    .whereNotNull('anchor.estimated_price')
    .where('anchor.is_recurring', true)
    .whereExists(function stillCoveredTopLevelSiblingExists() {
      this.select(1)
        .from('scheduled_services as sib')
        .whereRaw('sib.customer_id = anchor.customer_id')
        .whereRaw('sib.source_estimate_id = anchor.source_estimate_id')
        .whereRaw('sib.id <> anchor.id')
        .whereNull('sib.recurring_parent_id')
        .where('sib.is_recurring', true)
        .where((stillCovered) => {
          stillCovered.whereNull('sib.estimated_price')
            .orWhereNotExists(function siblingOwnLiveInvoiceExists() {
              this.select(1)
                .from('invoices as sib_invoice')
                .whereRaw('sib_invoice.scheduled_service_id = sib.id')
                .whereNotIn('sib_invoice.status', InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES);
            });
        });
    })
    .orderBy('i.created_at', 'asc')
    .select(CANDIDATE_COLUMNS);
  if (candidates.length >= limit) {
    logger.warn(`[first-application-sibling-split] ${candidates.length} open first-application invoices — past the ${limit}-row watch threshold; every one is still swept this tick, but the backlog itself is worth investigating`);
  }

  const staleInvoiceIds = await loadStaleAlertInvoiceIds(conn);
  const covered = new Set(candidates.map((r) => r.invoice_id));
  const missing = staleInvoiceIds.filter((id) => !covered.has(id));
  if (!missing.length) return candidates;
  const staleRows = await conn('invoices as i')
    .join('scheduled_services as anchor', 'anchor.id', 'i.scheduled_service_id')
    .whereIn('i.id', missing)
    .select(CANDIDATE_COLUMNS);
  return [...candidates, ...staleRows];
}

// Every LIVE member of the estimate group, each stamped with
// has_own_live_invoice: true when a LIVE invoice is linked to that member's
// OWN scheduled_service_id — the real-data signal that the office has
// already hand-split that visit off the shared invoice (see the module
// header). "Live" excludes the FULL canonical canceled vocabulary
// (InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES: void, refunded,
// canceled, cancelled — pre-push P1: void alone let a canceled "split"
// invoice falsely clear the alert while the sibling still has no real
// replacement charge), not just 'void'.
//
// A CANCELLED top-level visit is excluded from the group here, at the
// query level (PR #5021 Codex r6, head 2168cb0877): it was never going to
// be serviced, so it is never a real billing conflict for the office to
// resolve, and its date is irrelevant. This is the ONLY status excluded —
// a COMPLETED sibling stays a member (divergingSiblings no longer excludes
// it either; see its own comment) because completing a visit never settles
// or rewrites the still-open combined invoice. Cheap and bounded: one
// extra query keyed on this small group's own ids.
async function loadGroupMembers(conn, { customerId, sourceEstimateId }) {
  const members = await conn('scheduled_services')
    .where({ customer_id: customerId, source_estimate_id: sourceEstimateId })
    .whereNull('recurring_parent_id')
    .whereNot('status', 'cancelled')
    .orderBy('id')
    .select('id', 'scheduled_date', 'completed_at');
  if (!members.length) return members;
  const ownInvoiceIds = await conn('invoices')
    .whereIn('scheduled_service_id', members.map((m) => m.id))
    .whereNotIn('status', InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES)
    .pluck('scheduled_service_id');
  const ownInvoiceSet = new Set(ownInvoiceIds.map(String));
  return members.map((m) => ({ ...m, has_own_live_invoice: ownInvoiceSet.has(String(m.id)) }));
}

// Marks read (with an autoCleared stamp) every standing alert for this
// estimate whose dedupeKey carries the given prefix — optionally excluding
// one key that is about to be raised/refreshed instead. Same "plain
// update, best-effort" shape as supplies-consumption.js's
// clearMissedDeductionBells / ops-digest.js's resolved stamp — the closest
// existing "resolve a dedupe-keyed notification" convention; there is no
// larger resolve mechanism to build here.
//
// Deliberately NOT scoped to whereNull('read_at') (Codex round-1 P1 on the
// pre-push fix): an alert a human already DISMISSED while the group was
// still diverging must ALSO get the autoCleared stamp once the group
// genuinely resolves — otherwise raiseDivergenceAlert's wasAutoCleared
// check never sees the resolution, and an identical-dates recurrence after
// a plain dismissal + real realignment stays silently dismissed forever.
// COALESCE(read_at, NOW()) never disturbs an existing dismissal timestamp;
// it only sets read_at on a row that was still unread.
async function clearStandingAlerts(conn, prefix, { exceptKey = null } = {}) {
  let q = conn('notifications').where({ recipient_type: 'admin' })
    .whereRaw("metadata->>'dedupeKey' LIKE ?", [`${prefix}%`]);
  if (exceptKey) q = q.whereRaw("metadata->>'dedupeKey' <> ?", [exceptKey]);
  return q.update({
    read_at: conn.raw('COALESCE(read_at, NOW())'),
    metadata: conn.raw("COALESCE(metadata, '{}'::jsonb) || ?::jsonb", [JSON.stringify({ autoCleared: true })]),
  });
}

// Raises (or refreshes) the durable admin alert for this exact diverging
// set — see the module header for the race-safety note. Never touches the
// invoice or any visit row.
async function raiseDivergenceAlert(conn, {
  estimateId, anchor, diverging, invoice, customerId, dedupeKey,
}) {
  // Takes the SAME advisory lock notifyAdmin's own dedupe path takes, and
  // holds it (same connection/transaction) through notifyAdmin's write
  // below — the read and the write below can never straddle a concurrent
  // dismissal (Codex P2).
  await conn.raw('SELECT pg_advisory_xact_lock(hashtext(?))', [`admin:${dedupeKey}`]);
  const baseFingerprint = divergenceStateFingerprint({
    anchor, diverging, invoiceId: invoice?.invoice_id, invoiceTotal: invoice?.total,
  });
  // A standing alert the SWEEP ITSELF auto-cleared (the group looked
  // resolved on a prior tick — clearStandingAlerts' autoCleared stamp) that
  // is diverging again is a genuinely NEW recurrence even when its
  // fingerprint happens to exactly match the pre-clear state (Codex P1:
  // realign, then diverge back onto the SAME date — same fingerprint,
  // same notification content, so plain fingerprint dedupe would silently
  // stay cleared). The resolution stated the problem was gone; its return
  // is new information, never a no-op re-alert. A PLAIN human dismissal
  // (read_at set, never autoCleared) instead keeps the deterministic-
  // fingerprint dedupe: unchanged state stays dismissed. recurrenceGeneration
  // is bumped only on an auto-cleared recurrence, so repeated identical
  // resolve/recur cycles each still produce a distinct dedupeVersion.
  const existing = await conn('notifications').where({ recipient_type: 'admin' })
    .whereRaw("metadata->>'dedupeKey' = ?", [dedupeKey]).first('read_at', 'metadata');
  let existingMeta = existing?.metadata;
  if (typeof existingMeta === 'string') { try { existingMeta = JSON.parse(existingMeta); } catch { existingMeta = null; } }
  const wasAutoCleared = Boolean(existing?.read_at) && existingMeta?.autoCleared === true;
  const priorGeneration = Number(existingMeta?.recurrenceGeneration) || 0;
  const generation = wasAutoCleared ? priorGeneration + 1 : priorGeneration;
  const dedupeVersion = `${baseFingerprint}::g${generation}`;
  const anchorDate = dateOnly(anchor.scheduled_date);
  const detail = diverging.map((d) => `visit ${d.id} now on ${dateOnly(d.scheduled_date)} (was ${anchorDate})`).join('; ');
  const invoiceRef = invoice
    ? `Invoice ${invoice.invoice_number || invoice.invoice_id}.`
    : `Check the first-application invoice for estimate #${estimateId}.`;
  await require('./notification-service').notifyAdmin(
    'billing',
    'First-application invoice may need to be split by hand',
    `Same-trip visits from one estimate landed on different days: ${detail}. The combined first-application invoice still charges for both — split it by hand. ${invoiceRef}`,
    {
      link: invoice ? `/admin/invoices?invoice=${invoice.invoice_id}` : `/admin/estimates/${estimateId}`,
      bell: true,
      metadata: {
        estimateId: String(estimateId),
        divergingSiblingIds: diverging.map((d) => String(d.id)),
        customerId: customerId ? String(customerId) : null,
        // Read back by loadStaleAlertInvoiceIds so an invoice that settles
        // between sweep ticks (and so drops out of loadCandidates' own
        // non-settled scan) is still found and its alert auto-cleared.
        invoiceId: invoice ? String(invoice.invoice_id) : null,
        // An alert we are (re)raising right now is by definition not in the
        // auto-cleared state any more — explicitly cleared here since
        // notifyAdmin's refresh merges onto the OLD metadata, which would
        // otherwise leave a stale autoCleared:true sitting on a reopened
        // alert forever.
        autoCleared: false,
        recurrenceGeneration: generation,
      },
      dedupeKey,
      dedupeVersion,
      refreshOnDedupe: true,
      trx: conn,
    },
  );
}

// Re-derives one estimate's group fresh and acts on the COMBINED verdict
// across every candidate row for it — the whole unit a single transaction
// covers. See the module header for why this evaluates every row rather
// than picking one: any row finding a genuine divergence is enough to
// alert (their diverging sets are unioned); the estimate clears only when
// EVERY row agrees nothing is wrong.
async function evaluateEstimateCandidates(conn, candidatesForEstimate) {
  const { customer_id: customerId, source_estimate_id: estimateId } = candidatesForEstimate[0];
  const members = await loadGroupMembers(conn, { customerId, sourceEstimateId: estimateId });
  const prefix = DEDUPE_PREFIX(estimateId);

  const perAnchor = candidatesForEstimate.map((candidate) => {
    const {
      anchor_id: anchorId, invoice_id: invoiceId, invoice_status: invoiceStatus,
      invoice_number: invoiceNumber, invoice_total: invoiceTotal,
      anchor_scheduled_date: anchorScheduledDate, anchor_completed_at: anchorCompletedAt,
    } = candidate;
    const anchor = members.find((m) => String(m.id) === String(anchorId))
      || { id: anchorId, scheduled_date: anchorScheduledDate, completed_at: anchorCompletedAt };
    return {
      anchor,
      verdict: evaluateGroupDivergence({ anchor, members, invoiceStatus }),
      invoice: invoiceId ? { invoice_id: invoiceId, invoice_number: invoiceNumber, total: invoiceTotal } : null,
    };
  });

  const alerting = perAnchor.filter((p) => p.verdict.action === 'alert');
  if (!alerting.length) {
    const cleared = await clearStandingAlerts(conn, prefix);
    return {
      estimateId, action: 'cleared', reason: perAnchor[0].verdict.reason, cleared,
    };
  }

  // Union every alerting anchor's own unresolved diverging set — the same
  // member row, if flagged from more than one anchor's perspective, is
  // deduped by id (the row objects are identical either way, since every
  // anchor evaluates against the SAME shared `members` list).
  const unresolvedUnion = new Map();
  for (const p of alerting) {
    for (const d of p.verdict.diverging) unresolvedUnion.set(String(d.id), d);
  }
  const diverging = [...unresolvedUnion.values()];
  const sortedIds = [...new Set(diverging.map((d) => String(d.id)))].sort();
  const dedupeKey = `${prefix}${sortedIds.join(',')}`;
  const { anchor, invoice } = alerting[0];
  // Any OTHER standing alert for this estimate (a different diverging set
  // than the one we're about to raise/refresh) is stale — clear it first.
  await clearStandingAlerts(conn, prefix, { exceptKey: dedupeKey });
  await raiseDivergenceAlert(conn, {
    estimateId, anchor, diverging, customerId, invoice, dedupeKey,
  });
  return { estimateId, action: 'alerted', divergingSiblingIds: sortedIds };
}

async function runSweepInner() {
  const candidates = await loadCandidates(db);
  // Every row for an estimate is evaluated TOGETHER (see the module
  // header) — never a picked-by-heuristic representative.
  const groups = groupCandidatesByEstimate(candidates);
  let alerted = 0;
  let cleared = 0;
  let failed = 0;
  for (const group of groups) {
    try {
      const result = await db.transaction((trx) => evaluateEstimateCandidates(trx, group));
      if (result.action === 'alerted') alerted += 1;
      else if (result.action === 'cleared' && result.cleared) cleared += 1;
    } catch (err) {
      failed += 1;
      logger.error(`[first-application-sibling-split] sweep failed for estimate ${group[0].source_estimate_id}: ${err.message}`);
    }
  }
  if (failed) {
    throw new Error(`${failed} of ${groups.length} first-application sibling-split group(s) failed this tick — left for the next run`);
  }
  return {
    scanned: candidates.length, alerted, cleared, failed,
  };
}

async function runFirstApplicationSiblingSplitSweep() {
  const { runExclusive } = require('../utils/cron-lock');
  return runExclusive('first-application-sibling-split-sweep', runSweepInner);
}

