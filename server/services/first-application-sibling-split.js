const ALERT_DEDUPE_MARKER = Object.freeze({
  paid_never_ran: 'refund:',
  payment_pending_never_ran: 'pending:',
  diverged: '',
});

// Re-derives one invoice group's state fresh and acts on it — the whole
// unit a single transaction covers. membersForInvoice is EXACTLY the
// invoice's stamped covered members AS OF loadCandidates' snapshot — 1 or
// more (groupCandidatesByInvoice no longer drops a singleton, Codex
// round-11 P2); the anchor is simply whichever member the invoice's own
// scheduled_service_id points at. This function re-reads the CURRENT
// member count fresh below and that fresh count, never this snapshot's,
// decides whether the group is still a genuine pair.
async function evaluateEstimateCandidates(conn, membersForInvoice) {
  // Only the empty/non-array shape is skipped without evaluation — there is
  // no invoice id to re-read. A genuine singleton group (length 1) is NOT
  // skipped here any more (Codex round-11 P2): it is evaluated exactly like
  // any other group, and the freshMembers.length < 2 branch below — reading
  // CURRENT membership inside this transaction, not this possibly-stale
  // snapshot — is what decides whether it clears a standing alert.
  if (!Array.isArray(membersForInvoice) || membersForInvoice.length === 0) {
    return { estimateId: membersForInvoice?.[0]?.source_estimate_id ?? null, action: 'skipped', reason: 'not_a_pair' };
  }
  const { source_estimate_id: estimateId, customer_id: customerId, invoice_id: invoiceId } = membersForInvoice[0];
  // invoiceId here is the STAMPED invoice id (m.first_application_invoice_id)
  // — fixed for the life of this group — so the prefix is scoped to this
  // exact stamped invoice group, never shared with any other stamped group
  // under the same estimate.
  const prefix = DEDUPE_PREFIX(estimateId, invoiceId);

  // Re-read the invoice fresh under FOR UPDATE inside this transaction —
  // loadCandidates' own invoice status is read outside any per-estimate
  // transaction and could already be stale by the time this runs.
  const freshInvoice = await conn('invoices').where({ id: invoiceId }).forUpdate()
    .first('id', 'status', 'invoice_number', 'total', 'scheduled_service_id');
  if (!freshInvoice) {
    // The invoice row is gone from under the stamp (ON DELETE SET NULL
    // means this should be unreachable in practice — a deleted invoice
    // clears the stamp itself — but fail safe rather than throw).
    const cleared = await clearStandingAlerts(conn, prefix);
    return {
      estimateId, action: 'cleared', reason: 'invoice_missing', cleared,
    };
  }
  // Re-read the STAMPED MEMBER rows fresh too, inside this same
  // transaction — membersForInvoice's own dates/statuses/stamp membership
  // are exactly the snapshot loadCandidates took OUTSIDE any per-group
  // transaction (Codex round-10 P2). A schedule edit (or a status change)
  // committing after that snapshot but before this group's own turn in the
  // sweep would otherwise make this evaluation clear a divergence that has
  // since gotten worse, or raise a stale alert for one that has since
  // resolved, until the next tick catches up. Selected columns mirror
  // loadCandidates' own selection exactly. Deliberately NOT locked FOR
  // UPDATE: this module never writes scheduled_services, only reads it to
  // decide on an advisory alert, so a plain fresh read inside the
  // transaction is enough to fix the staleness — locking every member row
  // here would add contention against the many unrelated writers
  // (reschedule, dispatch, tech assignment, completion) that touch
  // scheduled_services, for no correctness benefit to this read-only
  // decision. (The invoice row above IS locked FOR UPDATE — its status is
  // what actually gets compared and acted on for settlement.)
  const freshMembers = await conn('scheduled_services as m')
    .where('m.first_application_invoice_id', invoiceId)
    .select(
      'm.id', 'm.scheduled_date', 'm.completed_at', 'm.status',
      'm.customer_id', 'm.source_estimate_id',
      'm.first_application_invoice_id as invoice_id',
    );
  if (freshMembers.length < 2) {
    // Fewer than 2 CURRENT members — either this group was already a
    // singleton when groupCandidatesByInvoice handed it over (an operator
    // NULLed a partner's stamp before this sweep ever ran), or the stamp
    // dissolved between loadCandidates' snapshot and this transaction's own
    // fresh read (the stamp is never rewritten by any real write path today
    // — owner ruling: accept-time-only — so that's necessarily a manual
    // NULL edit, not a normal writer). Either way the group is no longer a
    // genuine pair: clear any standing alert for this estimate rather than
    // leave it open with no group left to ever re-evaluate it.
    const cleared = await clearStandingAlerts(conn, prefix);
    return {
      estimateId, action: 'cleared', reason: 'not_a_pair', cleared,
    };
  }

  const anchor = freshMembers.find((m) => String(m.id) === String(freshInvoice.scheduled_service_id));
  if (!anchor) {
    // The invoice's own scheduled_service_id isn't among the stamped
    // members — stampCombinedFirstApplicationInvoiceCoverage always
    // includes the anchor, so this should be unreachable; fail safe.
    const cleared = await clearStandingAlerts(conn, prefix);
    return {
      estimateId, action: 'cleared', reason: 'no_anchor', cleared,
    };
  }

  const governingInvoice = await loadGoverningInvoice(conn, freshInvoice);
  const members = await flagOwnLiveInvoices(conn, freshMembers, {
    anchorId: anchor.id,
    // The combined invoice sits on the anchor's own scheduled_service_id, so
    // it (and a governing replacement) is never "the anchor's own separate
    // invoice" (Codex round 14 P1).
    anchorExcludedInvoiceIds: [freshInvoice.id, governingInvoice.id],
  });
  const anchorWithFlag = members.find((m) => String(m.id) === String(anchor.id));

  const verdict = evaluateGroupDivergence({ anchor: anchorWithFlag, members, invoiceStatus: governingInvoice.status });
  if (verdict.action === 'clear') {
    const cleared = await clearStandingAlerts(conn, prefix);
    return {
      estimateId, action: 'cleared', reason: verdict.reason, cleared,
    };
  }

  const diverging = verdict.diverging;
  const sortedIds = [...new Set(diverging.map((d) => String(d.id)))].sort();
  const alertKind = ALERT_KIND_BY_REASON[verdict.reason] || 'diverged';
  const dedupeKey = `${prefix}${ALERT_DEDUPE_MARKER[alertKind]}${sortedIds.join(',')}`;
  // The alert's invoice reference — number, total, and the id read back by
  // loadCandidates' own alert-recovery EXISTS — is always the GOVERNING
  // invoice, never the dead stamped row, so office staff are pointed at the
  // invoice that actually still charges the group. isReplacement flags the
  // "stamped invoice went terminal, a different live invoice governs now"
  // case so raiseDivergenceAlert can say so in the alert copy.
  const invoice = {
    invoice_id: governingInvoice.id,
    invoice_number: governingInvoice.invoice_number,
    total: governingInvoice.total,
    isReplacement: String(governingInvoice.id) !== String(freshInvoice.id),
  };
  // Any OTHER standing alert for this estimate (a different diverging set
  // than the one we're about to raise/refresh) is stale — clear it first.
  await clearStandingAlerts(conn, prefix, { exceptKey: dedupeKey });
  await raiseDivergenceAlert(conn, {
    estimateId, anchor: anchorWithFlag, diverging, customerId, invoice, dedupeKey, stampedInvoiceId: invoiceId, alertKind,
  });
  return { estimateId, action: 'alerted', divergingSiblingIds: sortedIds };
}

const SWEEP_CURSOR_TABLE = 'first_application_sibling_split_sweep_cursor';
const SWEEP_BATCH_LIMIT = 200;

// The one persisted row's last-visited invoice id — see the cursor
// table's own migration comment for why the column is still named
// last_estimate_id (it now holds a first_application_invoice_id; the
// migration that created the table is already pushed and frozen, and the
// pagination logic below never inspects which kind of uuid it holds, so
// renaming the column was not worth a whole extra migration). Best-effort:
// a missing row (pre-migration, or a deleted row) is treated as "start
// from the beginning", never a sweep failure.
async function loadSweepCursor(conn) {
  const row = await conn(SWEEP_CURSOR_TABLE).where({ id: 1 }).first('last_estimate_id');
  return row ? row.last_estimate_id : null;
}

// Upsert, not a plain UPDATE (Codex round-11 P2): loadSweepCursor already
// treats a missing singleton row as recoverable ("start from the
// beginning"), but a plain UPDATE of id=1 is a silent no-op once that row
// is gone — every tick would then restart from a null cursor and, past
// SWEEP_BATCH_LIMIT groups, later groups would starve behind an
// always-same head of the list forever. Upserting keeps the singleton
// self-healing exactly the way loadCandidates' own read already assumes.
async function saveSweepCursor(conn, lastInvoiceId) {
  await conn(SWEEP_CURSOR_TABLE)
    .insert({ id: 1, last_estimate_id: lastInvoiceId, updated_at: conn.fn.now() })
    .onConflict('id')
    .merge({ last_estimate_id: lastInvoiceId, updated_at: conn.fn.now() });
}

// Per tick: a keyset page of candidate invoice ids after the persisted
// cursor (loadSweepBatchInvoiceIds — paged in SQL, Codex r14 P2 on #5021),
// then member rows for exactly those invoices. The read and memory are
// bounded by SWEEP_BATCH_LIMIT invoices, however many candidates exist.
async function runSweepInner() {
  let cursor = null;
  try { cursor = await loadSweepCursor(db); } catch (err) {
    logger.warn(`[first-application-sibling-split] sweep cursor read failed (starting from the beginning): ${err.message}`);
  }
  const batchIds = await loadSweepBatchInvoiceIds(db, { cursor });
  const candidates = batchIds.length ? await loadCandidates(db, { invoiceIds: batchIds }) : [];
  const groups = groupCandidatesByInvoice(candidates);

  let alerted = 0;
  let cleared = 0;
  let failed = 0;
  for (const group of groups) {
    try {
      const result = await db.transaction((trx) => evaluateEstimateCandidates(trx, group));
      if (result.action === 'alerted') alerted += 1;
      else if (result.action === 'cleared' && result.cleared) cleared += 1;
    } catch (err) {
      failed += 1;
      logger.error(`[first-application-sibling-split] sweep failed for invoice group ${group[0].invoice_id}: ${err.message}`);
    }
  }
  // Advance the cursor to the LAST invoice of this tick's batch in rotation
  // order, so the next tick resumes right after it — even a batch that
  // included a failure still advances (the failed group is retried on its
  // next natural pass; it never blocks everyone behind it).
  if (batchIds.length) {
    try { await saveSweepCursor(db, batchIds[batchIds.length - 1]); } catch (err) {
      logger.warn(`[first-application-sibling-split] sweep cursor save failed (non-fatal): ${err.message}`);
    }
  }
  if (failed) {
    throw new Error(`${failed} of ${groups.length} first-application sibling-split group(s) failed this tick — left for the next run`);
  }
  return {
    scanned: candidates.length, alerted, cleared, failed, groupsThisTick: groups.length,
  };
}

// Runtime reconciliation for accepts nobody stamped (Codex r15 P1 on PR
// #5021): the stamp migrations run in Railway's pre-deploy phase while the
// previous app version still serves, so a multi-program accept on an old
// pod after the rerun finished has no first_application_invoice_id and
// would be invisible to this sweep AND to the stamped completion lookup
// forever. Every tick therefore first re-runs the exact, never-overwriting
// backfill over recent invoices. Bounded (RECENT_STAMP_RECONCILE_DAYS) so it
// stays cheap; logs only when it actually stamps; a failure here never
// blocks the sweep itself (the sweep still evaluates every already-stamped
// group), it is logged and retried next tick.
const RECENT_STAMP_RECONCILE_DAYS = 14;
async function reconcileRecentUnstampedAccepts(conn = db) {
  try {
    const { backfillFirstApplicationInvoiceStamps } = require('./estimate-first-application-invoice');
    const result = await backfillFirstApplicationInvoiceStamps(conn, { sinceDays: RECENT_STAMP_RECONCILE_DAYS });
    if (result?.stamped) {
      logger.info(`[first-application-sibling-split] reconciliation stamped ${result.stamped} recent combined-invoice member row(s) that no accept path had stamped (${result.ambiguous || 0} ambiguous left for hand review)`);
    }
    return result;
  } catch (err) {
    logger.warn(`[first-application-sibling-split] recent-accept stamp reconciliation failed (sweep continues): ${err?.message || err}`);
    return null;
  }
}

async function runFirstApplicationSiblingSplitSweep() {
  const { runExclusive } = require('../utils/cron-lock');
  return runExclusive('first-application-sibling-split-sweep', async () => {
    await reconcileRecentUnstampedAccepts();
    return runSweepInner();
  });
}

