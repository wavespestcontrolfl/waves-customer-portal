// The canonical "this invoice will never collect any more money" vocabulary
// (Codex P2, this fix): was a locally-duplicated ['paid', 'prepaid', ...
// CANCELLED_SERVICE_RESOLVED_STATUSES] list that silently drifted from
// invoice-helpers.js's own list by missing 'processing' — a card charge
// mid-settlement read as still "open" here and could raise a live alert for
// an invoice that is, for every other purpose in the app, already settled.
// Reusing the shared constant means this module can never drift from it
// again.
const SETTLED_INVOICE_STATUSES = INVOICE_UNCOLLECTIBLE_STATUSES;
const SWEEP_LIMIT = 500;
const DEDUPE_PREFIX = (estimateId) => `first_application_sibling_divergence:${estimateId}:`;

function dateOnly(value) {
  if (!value) return null;
  if (value instanceof Date) return value.toISOString().slice(0, 10);
  return String(value).split('T')[0].slice(0, 10);
}

function isInvoiceSettled(status) {
  return SETTLED_INVOICE_STATUSES.includes(String(status));
}

// Members currently diverging from the anchor's date: not the anchor
// itself — deliberately NOT filtered on estimated_price (Codex P1: a
// sibling that has picked up its own price still shares the same combined
// charge on the invoice until someone actually splits it), and
// deliberately NOT filtered on completed_at (Codex round-6 P1 at head
// 2168cb0877: a moved sibling that COMPLETES before the next sweep used to
// be excluded here, so the group read as "realigned" even though
// completing a visit never settles or rewrites the still-open COMBINED
// invoice — the office lost the alert entirely) or on status at all — a
// cancelled member can still appear here if it also happens to have moved
// off the anchor's date; evaluateGroupDivergence's own cancelledNeedingReview
// is what actually decides a cancelled member's fate, date-diverged or not.
// Also deliberately NOT filtered on has_own_live_invoice here — this is the
// RAW divergence (dates disagree); evaluateGroupDivergence is the one that
// decides which of these still need an alert.
function divergingSiblings(anchor, members) {
  const anchorDate = dateOnly(anchor.scheduled_date);
  return members.filter((m) => String(m.id) !== String(anchor.id)
    && dateOnly(m.scheduled_date) !== anchorDate);
}

// The pure detection predicate: given the group's anchor row, every member
// row (each optionally carrying has_own_live_invoice — loadGroupMembers
// stamps this from a real invoices.scheduled_service_id lookup — and
// status), and the shared invoice's current status, decide whether to
// alert, clear a standing alert, or do nothing. No DB access — the sweep
// and every unit test call this the same way. See the module header
// ("has_own_live_invoice is signal (a) ALONE") for why has_own_live_invoice
// is the resolution signal, deliberately, and not a dollar comparison
// against the combined invoice.
function evaluateGroupDivergence({ anchor, members, invoiceStatus }) {
  if (!anchor || !Array.isArray(members) || members.length < 2) {
    return { action: 'clear', reason: 'no_group' };
  }
  if (isInvoiceSettled(invoiceStatus)) {
    return { action: 'clear', reason: 'invoice_settled' };
  }
  const diverging = divergingSiblings(anchor, members);
  // A diverging sibling that has already picked up its OWN live invoice
  // (linked to its own scheduled_service_id) has been split off by hand —
  // the office completed the instructed manual split for that visit, so it
  // no longer needs an alert. A CANCELLED diverging sibling is handled
  // separately below (cancelledNeedingReview), never here — it needs
  // different alert copy and, unlike a plain diverging sibling, needs
  // review even when it never diverged by date at all.
  const unresolvedDiverging = diverging.filter((m) => !m.has_own_live_invoice && m.status !== 'cancelled');

  // A CANCELLED top-level sibling still covered by the combined invoice
  // (Codex P1 on this fix): cancelling a visit never removes its share of
  // the combined charge — voidOpenInvoicesForCancelledService only voids
  // an invoice linked to the CANCELLED service's OWN scheduled_service_id,
  // never the anchor's shared one — so it leaves a stale charge whether or
  // not its date ever diverged from the anchor's (a same-day cancellation
  // is just as stale a charge as one that also moved). "Covered" mirrors
  // has_own_live_invoice's own scope: once the sibling has its own live
  // invoice (its charge has genuinely been moved off the combined one), it
  // no longer needs review here.
  const cancelledNeedingReview = members.filter((m) => String(m.id) !== String(anchor.id)
    && m.status === 'cancelled' && !m.has_own_live_invoice);

  const unresolved = [...unresolvedDiverging, ...cancelledNeedingReview];
  if (!unresolved.length) {
    // 'split_completed' whenever there was ever something here needing
    // hand resolution (a diverging or cancelled-covered sibling) that has
    // since been resolved — 'realigned' only when the group never had
    // anything beyond a plain date mismatch to begin with.
    const everNeededResolution = diverging.length > 0
      || members.some((m) => String(m.id) !== String(anchor.id) && m.status === 'cancelled');
    return { action: 'clear', reason: everNeededResolution ? 'split_completed' : 'realigned' };
  }
  return { action: 'alert', reason: 'diverged', diverging: unresolved };
}

// Deterministic fingerprint of the live divergence state — the anchor's own
// date, each alerted sibling's own id+date (sorted, so member ORDER never
// matters), and the shared invoice's id+total. Used as notifyAdmin's
// dedupeVersion (pre-push P1 fix): NOT a fresh timestamp minted whenever the
// standing alert happens to be dismissed — that would reopen a dismissed
// alert on every sweep tick even with nothing materially different. Only a
// changed fingerprint (a different dates tuple, or a different invoice id
// or total) reopens a dismissed alert; an unchanged fingerprint stays
// dismissed.
function divergenceStateFingerprint({ anchor, diverging, invoiceId, invoiceTotal }) {
  const anchorDate = dateOnly(anchor.scheduled_date);
  // Cancellation status is folded in explicitly (Codex P1 on the
  // cancelled-sibling-review fix) rather than relying on the incidental
  // body-text diff to trigger a refresh: a sibling going diverged→cancelled,
  // or gaining its own live invoice while cancelled (resolved), is a
  // genuine state change and must reopen a dismissed alert on its own.
  const parts = diverging
    .map((d) => `${d.id}:${dateOnly(d.scheduled_date)}:${d.status === 'cancelled' ? 'cancelled' : 'active'}`)
    .sort();
  const total = invoiceTotal != null && Number.isFinite(Number(invoiceTotal)) ? Number(invoiceTotal).toFixed(2) : null;
  return JSON.stringify({
    anchorDate,
    diverging: parts,
    invoiceId: invoiceId != null ? String(invoiceId) : null,
    invoiceTotal: total,
  });
}

// No title/notes here (PR #5021 Codex r6, head 2168cb0877): candidacy is
// structural now, and invoice text is never consulted for anything else in
// this module — see loadCandidates.
const CANDIDATE_COLUMNS = [
  'i.id as invoice_id', 'i.status as invoice_status', 'i.invoice_number',
  'i.total as invoice_total', 'i.created_at as invoice_created_at',
  'anchor.id as anchor_id', 'anchor.customer_id', 'anchor.source_estimate_id',
  'anchor.scheduled_date as anchor_scheduled_date', 'anchor.completed_at as anchor_completed_at',
];

// Groups candidate INVOICE rows by estimate — a plain grouping, never a
// pick-one-representative filter (see the module header for why: no
// current-state heuristic reliably tells "the true combined invoice,
// reissued" apart from "a split-off sibling's own separate invoice", so
// evaluateEstimateCandidates evaluates every row in each group together
// instead of this function choosing one). Preserves loadCandidates' own
// order within each group (oldest invoice first — no significance beyond
// determinism).
function groupCandidatesByEstimate(candidates) {
  const byEstimate = new Map();
  for (const candidate of candidates) {
    const key = candidate.source_estimate_id;
    if (!byEstimate.has(key)) byEstimate.set(key, []);
    byEstimate.get(key).push(candidate);
  }
  return [...byEstimate.values()];
}

// The ONE anchor scheduled_service id each of the given estimates' standing
// alert HISTORY already names, keyed by estimateId (stamped in
// metadata.anchorId when raised — see raiseDivergenceAlert). Once
// established, this identity is THE authoritative anchor/reference frame
// for that estimate FOREVER, not only while an alert is unread — never
// re-derived via the structural scan below, which can no longer tell "the
// true combined invoice, reissued" apart from "a split-off sibling's own
// separate invoice" once a split exists (see the module header).
//
// Deliberately NOT scoped to ONLY whereNull('read_at') (Codex P1, two
// rounds on this fix): scoping to unread alerts alone made the estimate
// FORGET its own established anchor the instant the group genuinely
// resolved and the alert was marked read/autoCleared — resurrecting the
// same ambiguity later (an unrelated sibling can remain permanently
// unpriced with no real billing problem, e.g. one perfectly aligned with
// the true anchor, keeping the estimate structurally "in play" forever).
// The FIRST fix widened the bound to "unread OR structurally current" —
// but a PLAIN human dismissal (read_at set, autoCleared never stamped
// true) whose estimate ALSO happens to drop out of structural discovery
// at that exact moment (both siblings get their own invoice, satisfying
// each other) matched NEITHER branch: the sweep never got a chance to run
// evaluateEstimateCandidates for it at all, so it could never stamp
// autoCleared — the ONE piece of state raiseDivergenceAlert's
// wasAutoCleared check needs to recognize a LATER, genuinely NEW
// recurrence (e.g. the completed split invoice gets voided again) as new
// information rather than "unchanged, stays dismissed".
//
// So the real bound is not read_at at all — it's whether the sweep has
// ever CONFIRMED resolution: metadata.autoCleared is 'true' only when
// clearStandingAlerts has actually run for this exact dedupeKey (raising
// or refreshing an alert always stamps autoCleared:false in the same
// write — see raiseDivergenceAlert). "Not yet confirmed resolved" is a
// STRICT SUPERSET of "unread" (it also covers a plain dismissal the sweep
// hasn't reconciled yet) while remaining just as bounded and self-
// draining: every alert in it leaves the moment a sweep actually runs
// evaluateEstimateCandidates for its estimate and settles the question
// either way. Unioned, as before, with any alert (any state at all) for an
// estimate the structural scan ALSO currently finds (`estimateIds` —
// already "bounded by currently non-settled — operationally small") so a
// fully-confirmed-resolved identity is still remembered for as long as the
// estimate stays structurally relevant for an unrelated reason.
async function loadEstablishedAnchorsByEstimate(conn, estimateIds) {
  const alerts = await conn('notifications')
    .where({ recipient_type: 'admin' })
    .whereRaw("metadata->>'dedupeKey' LIKE 'first_application_sibling_divergence:%'")
    .where((scope) => {
      scope.whereRaw("metadata->>'autoCleared' IS DISTINCT FROM 'true'");
      if (estimateIds.length) scope.orWhereIn(conn.raw("metadata->>'estimateId'"), estimateIds);
    })
    .select('metadata');
  const byEstimate = new Map();
  for (const row of alerts) {
    let meta = row.metadata;
    if (typeof meta === 'string') { try { meta = JSON.parse(meta); } catch { meta = null; } }
    if (meta?.estimateId && meta?.anchorId && !byEstimate.has(String(meta.estimateId))) {
      byEstimate.set(String(meta.estimateId), String(meta.anchorId));
    }
  }
  return byEstimate;
}

// Candidate discovery, per estimate: an ESTABLISHED anchor (above) is
// re-derived DIRECTLY — its own most-recent invoice, live or settled,
// original or reissued, no structural re-check at all — while every OTHER
// estimate (no established anchor yet) goes through the STRUCTURAL scan
// (see the module header for candidacy and why it's fresh-discovery-only).
//
// Candidacy, for the structural scan: the anchor must be PRICED
// (estimated_price NOT NULL) and a recurring program, and it must have at
// least one live, top-level, ALSO-recurring sibling under the same
// customer + estimate that is STILL COVERED by the anchor's shared invoice
// — either it was deliberately left UNPRICED (estimated_price IS NULL, the
// acceptance-time marker), OR it has no LIVE invoice of its own yet
// (checked against the same InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES
// vocabulary has_own_live_invoice uses). The OR matters: a sibling that
// picks up its own estimated_price BEFORE ever getting split off — the
// exact "a priced sibling still diverges" scenario this module's own P1
// fix already guarantees — would otherwise silently fall out of candidate
// discovery on its very first tick. Checked with a correlated EXISTS
// against scheduled_services (bounded by the same
// customer_id/source_estimate_id shape loadGroupMembers already queries
// by, on the existing idx_scheduled_services_source_estimate index) plus a
// nested EXISTS/NOT EXISTS against invoices on its own indexed
// scheduled_service_id column. This also still rules out a normal
// single-program estimate (no sibling row exists at all) and a normal
// multi-program estimate where every program was independently priced AND
// invoiced from day one (neither OR branch matches for such a sibling).
// Invoice title/notes text is never consulted.
//
// Deliberately UNBOUNDED by row count (Codex P1): the set this query
// selects is already bounded by "currently non-settled" — operationally
// small — so an ORDER BY + LIMIT here would silently starve every
// candidate past the cutoff forever (the same oldest N rows every tick,
// with nothing ever aging the newer ones in). `limit` is a WARNING
// threshold only — crossing it means the open backlog has grown large
// enough to be its own problem, worth an ops signal, never a reason to
// evaluate fewer of them.
async function loadCandidates(conn, { limit = SWEEP_LIMIT } = {}) {
  const structuralRows = await conn('invoices as i')
    .join('scheduled_services as anchor', 'anchor.id', 'i.scheduled_service_id')
    .whereNotIn('i.status', SETTLED_INVOICE_STATUSES)
    .whereNotNull('anchor.source_estimate_id')
    .whereNull('anchor.recurring_parent_id')
    .whereNotNull('anchor.estimated_price')
    .where('anchor.is_recurring', true)
    .whereExists(function stillCoveredTopLevelSiblingExists() {
      this.select(1)
        .from('scheduled_services as sib')
        .whereRaw('sib.customer_id = anchor.customer_id')
        .whereRaw('sib.source_estimate_id = anchor.source_estimate_id')
        .whereRaw('sib.id <> anchor.id')
        .whereNull('sib.recurring_parent_id')
        .where('sib.is_recurring', true)
        .where((stillCovered) => {
          stillCovered.whereNull('sib.estimated_price')
            .orWhereNotExists(function siblingOwnLiveInvoiceExists() {
              this.select(1)
                .from('invoices as sib_invoice')
                .whereRaw('sib_invoice.scheduled_service_id = sib.id')
                .whereNotIn('sib_invoice.status', InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES);
            });
        })
        // Cheap exclusion of ALIGNED groups (Codex P2, this fix): the
        // check above alone matches every ordinary same-day multi-program
        // estimate from its very first tick — a sibling deliberately left
        // estimated_price NULL is "still covered" forever until the
        // invoice is paid, aligned or not. That is exactly the historical
        // backlog of accepted-but-unpaid (sent/viewed/overdue) invoices
        // the load concern is about, and evaluateGroupDivergence would
        // clear every one of them as 'realigned' anyway. Mirror its own
        // gate here: a sibling only needs review once it has actually
        // diverged by date OR been cancelled — the same two conditions
        // evaluateGroupDivergence's unresolvedDiverging/
        // cancelledNeedingReview check.
        .andWhere((needsReview) => {
          needsReview.whereRaw('sib.scheduled_date::date <> anchor.scheduled_date::date')
            .orWhere('sib.status', 'cancelled');
        });
    })
    .orderBy('anchor.source_estimate_id', 'asc')
    .select([...CANDIDATE_COLUMNS, conn.raw("'fresh' as candidate_source")]);

  // Scoped to exactly the estimates the structural scan above found —
  // keeps loadEstablishedAnchorsByEstimate's own history lookup bounded by
  // that same small, "currently non-settled" set instead of a read_at
  // filter (see its own comment for why read_at can't be the bound here).
  const structuralEstimateIds = [...new Set(structuralRows.map((row) => String(row.source_estimate_id)))];
  const establishedByEstimate = await loadEstablishedAnchorsByEstimate(conn, structuralEstimateIds);

  // Estimates with an established anchor are re-derived directly below —
  // never through this (now ambiguous, once a split exists) structural
  // scan, even if it also happens to find a row for them.
  const fresh = structuralRows.filter((row) => !establishedByEstimate.has(String(row.source_estimate_id)));

  const anchorIds = [...establishedByEstimate.values()];
  let establishedRows = [];
  if (anchorIds.length) {
    const anchorInvoiceRows = await conn('invoices as i')
      .join('scheduled_services as anchor', 'anchor.id', 'i.scheduled_service_id')
      .whereIn('anchor.id', anchorIds)
      .select(CANDIDATE_COLUMNS);
    // The BEST invoice per established anchor: live over settled first,
    // then most recent — never re-derived across DIFFERENT anchors (the
    // comparison that broke on heads 3681fe5c5e/daf724131f), only among
    // the ONE already-known anchor's own invoice history, where "prefer
    // live, then newest" is unambiguous and safe. This is what resolves a
    // voided-then-reissued invoice to the reissue, never the stale voided
    // one, even if both happen to share a created_at (the same DB
    // transaction minted both).
    const byAnchor = new Map();
    for (const row of anchorInvoiceRows) {
      const current = byAnchor.get(row.anchor_id);
      if (!current) { byAnchor.set(row.anchor_id, row); continue; }
      const currentLive = !isInvoiceSettled(current.invoice_status);
      const rowLive = !isInvoiceSettled(row.invoice_status);
      if (rowLive && !currentLive) {
        byAnchor.set(row.anchor_id, row);
      } else if (rowLive === currentLive) {
        const currentCreated = current.invoice_created_at ? new Date(current.invoice_created_at).getTime() : 0;
        const rowCreated = row.invoice_created_at ? new Date(row.invoice_created_at).getTime() : 0;
        if (rowCreated > currentCreated) byAnchor.set(row.anchor_id, row);
      }
    }
    // Tagged 'established' (never 'fresh'): this is the stale-alert
    // recovery path (a standing alert whose invoice has since settled, or
    // whose group has since realigned/split) and runs in FULL every tick,
    // never subject to the fresh-only sweep cursor below (Codex P2).
    establishedRows = [...byAnchor.values()].map((row) => ({ ...row, candidate_source: 'established' }));
  }

  const candidates = [...fresh, ...establishedRows];
  if (candidates.length >= limit) {
    logger.warn(`[first-application-sibling-split] ${candidates.length} open first-application invoices — past the ${limit}-row watch threshold; every one is still swept this tick, but the backlog itself is worth investigating`);
  }
  return candidates;
}

// Every member of the estimate group, each stamped with has_own_live_invoice:
// true when a LIVE invoice is linked to that member's OWN
// scheduled_service_id — the real-data signal that the office has
// already hand-split that visit off the shared invoice (see the module
// header). "Live" excludes the FULL canonical canceled vocabulary
// (InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES: void, refunded,
// canceled, cancelled — pre-push P1: void alone let a canceled "split"
// invoice falsely clear the alert while the sibling still has no real
// replacement charge), not just 'void'.
//
// A CANCELLED top-level visit is no longer excluded here (Codex P1 on this
// fix): cancelling a sibling still covered by the combined invoice never
// removes its charge — voidOpenInvoicesForCancelledService only voids an
// invoice linked to the CANCELLED service's OWN scheduled_service_id,
// never the anchor's shared one — so a cancelled-but-covered sibling stays
// a real billing conflict, not a settled fact (see the module header and
// evaluateGroupDivergence's cancelledNeedingReview). A COMPLETED sibling
// likewise stays a member (divergingSiblings no longer excludes it either;
// see its own comment) because completing a visit never settles or
// rewrites the still-open combined invoice. `status` is selected so
// callers can classify a cancelled member distinctly. Cheap and bounded:
// one extra query keyed on this small group's own ids.
async function loadGroupMembers(conn, { customerId, sourceEstimateId }) {
  const members = await conn('scheduled_services')
    .where({ customer_id: customerId, source_estimate_id: sourceEstimateId })
    .whereNull('recurring_parent_id')
    .orderBy('id')
    .select('id', 'scheduled_date', 'completed_at', 'status');
  if (!members.length) return members;
  const ownInvoiceIds = await conn('invoices')
    .whereIn('scheduled_service_id', members.map((m) => m.id))
    .whereNotIn('status', InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES)
    .pluck('scheduled_service_id');
  const ownInvoiceSet = new Set(ownInvoiceIds.map(String));
  return members.map((m) => ({ ...m, has_own_live_invoice: ownInvoiceSet.has(String(m.id)) }));
}

// Marks read (with an autoCleared stamp) every standing alert for this
// estimate whose dedupeKey carries the given prefix — optionally excluding
// one key that is about to be raised/refreshed instead. Same "plain
// update, best-effort" shape as supplies-consumption.js's
// clearMissedDeductionBells / ops-digest.js's resolved stamp — the closest
// existing "resolve a dedupe-keyed notification" convention; there is no
// larger resolve mechanism to build here.
//
// Deliberately NOT scoped to whereNull('read_at') (Codex round-1 P1 on the
// pre-push fix): an alert a human already DISMISSED while the group was
// still diverging must ALSO get the autoCleared stamp once the group
// genuinely resolves — otherwise raiseDivergenceAlert's wasAutoCleared
// check never sees the resolution, and an identical-dates recurrence after
// a plain dismissal + real realignment stays silently dismissed forever.
// COALESCE(read_at, NOW()) never disturbs an existing dismissal timestamp;
// it only sets read_at on a row that was still unread.
async function clearStandingAlerts(conn, prefix, { exceptKey = null } = {}) {
  let q = conn('notifications').where({ recipient_type: 'admin' })
    .whereRaw("metadata->>'dedupeKey' LIKE ?", [`${prefix}%`]);
  if (exceptKey) q = q.whereRaw("metadata->>'dedupeKey' <> ?", [exceptKey]);
  return q.update({
    read_at: conn.raw('COALESCE(read_at, NOW())'),
    metadata: conn.raw("COALESCE(metadata, '{}'::jsonb) || ?::jsonb", [JSON.stringify({ autoCleared: true })]),
  });
}

// Raises (or refreshes) the durable admin alert for this exact diverging
// set — see the module header for the race-safety note. Never touches the
// invoice or any visit row.
async function raiseDivergenceAlert(conn, {
  estimateId, anchor, diverging, invoice, customerId, dedupeKey,
}) {
  // Takes the SAME advisory lock notifyAdmin's own dedupe path takes, and
  // holds it (same connection/transaction) through notifyAdmin's write
  // below — the read and the write below can never straddle a concurrent
  // dismissal (Codex P2).
  await conn.raw('SELECT pg_advisory_xact_lock(hashtext(?))', [`admin:${dedupeKey}`]);
  const baseFingerprint = divergenceStateFingerprint({
    anchor, diverging, invoiceId: invoice?.invoice_id, invoiceTotal: invoice?.total,
  });
  // A standing alert the SWEEP ITSELF auto-cleared (the group looked
  // resolved on a prior tick — clearStandingAlerts' autoCleared stamp) that
  // is diverging again is a genuinely NEW recurrence even when its
  // fingerprint happens to exactly match the pre-clear state (Codex P1:
  // realign, then diverge back onto the SAME date — same fingerprint,
  // same notification content, so plain fingerprint dedupe would silently
  // stay cleared). The resolution stated the problem was gone; its return
  // is new information, never a no-op re-alert. A PLAIN human dismissal
  // (read_at set, never autoCleared) instead keeps the deterministic-
  // fingerprint dedupe: unchanged state stays dismissed. recurrenceGeneration
  // is bumped only on an auto-cleared recurrence, so repeated identical
  // resolve/recur cycles each still produce a distinct dedupeVersion.
  const existing = await conn('notifications').where({ recipient_type: 'admin' })
    .whereRaw("metadata->>'dedupeKey' = ?", [dedupeKey]).first('read_at', 'metadata');
  let existingMeta = existing?.metadata;
  if (typeof existingMeta === 'string') { try { existingMeta = JSON.parse(existingMeta); } catch { existingMeta = null; } }
  const wasAutoCleared = Boolean(existing?.read_at) && existingMeta?.autoCleared === true;
  const priorGeneration = Number(existingMeta?.recurrenceGeneration) || 0;
  const generation = wasAutoCleared ? priorGeneration + 1 : priorGeneration;
  const dedupeVersion = `${baseFingerprint}::g${generation}`;
  const anchorDate = dateOnly(anchor.scheduled_date);
  // Cancelled members get distinct copy (Codex P1 on this fix): the office
  // action isn't "split it by hand" — the visit already isn't happening —
  // it's removing that sibling's share of the still-open combined charge.
  // A cancelled member can ALSO have moved off the anchor's date; the
  // cancellation copy always wins for it since that's the actual remaining
  // action, regardless of date.
  const cancelledMembers = diverging.filter((d) => d.status === 'cancelled');
  const movedMembers = diverging.filter((d) => d.status !== 'cancelled');
  const detailParts = [
    ...movedMembers.map((d) => `visit ${d.id} now on ${dateOnly(d.scheduled_date)} (was ${anchorDate})`),
    ...cancelledMembers.map((d) => `visit ${d.id} was cancelled — remove its charge from the combined invoice`),
  ];
  const detail = detailParts.join('; ');
  const invoiceRef = invoice
    ? `Invoice ${invoice.invoice_number || invoice.invoice_id}.`
    : `Check the first-application invoice for estimate #${estimateId}.`;
  // The lead sentence and the required action both depend on whether any
  // member actually still needs a hand split (movedMembers) versus only a
  // cancelled member's charge needing removal — a Postgres regression test
  // (first-application-sibling-split.postgres.test.js) asserts the exact
  // "split it by hand" substring survives whenever a moved member is
  // present, so that phrase is never rewritten for that case.
  const leadSentence = movedMembers.length
    ? 'Same-trip visits from one estimate landed on different days'
    : 'A same-trip visit from one estimate was cancelled';
  const actionSentence = movedMembers.length
    ? 'The combined first-application invoice still charges for both — split it by hand.'
    : 'The combined first-application invoice still charges for it — remove that charge.';
  await require('./notification-service').notifyAdmin(
    'billing',
    'First-application invoice may need to be split by hand',
    `${leadSentence}: ${detail}. ${actionSentence} ${invoiceRef}`,
    {
      link: invoice ? `/admin/invoices?invoice=${invoice.invoice_id}` : `/admin/estimates/${estimateId}`,
      bell: true,
      metadata: {
        estimateId: String(estimateId),
        // Read back by loadEstablishedAnchorsByEstimate — the durable
        // reference frame for this estimate from here on, re-derived
        // directly by its OWN scheduled_service_id on every later tick,
        // never re-guessed from the (ambiguous, once a split exists)
        // structural scan again. See the module header.
        anchorId: String(anchor.id),
        divergingSiblingIds: diverging.map((d) => String(d.id)),
        customerId: customerId ? String(customerId) : null,
        invoiceId: invoice ? String(invoice.invoice_id) : null,
        // An alert we are (re)raising right now is by definition not in the
        // auto-cleared state any more — explicitly cleared here since
        // notifyAdmin's refresh merges onto the OLD metadata, which would
        // otherwise leave a stale autoCleared:true sitting on a reopened
        // alert forever.
        autoCleared: false,
        recurrenceGeneration: generation,
      },
      dedupeKey,
      dedupeVersion,
      refreshOnDedupe: true,
      trx: conn,
    },
  );
}

// Re-derives one estimate's group fresh and acts on the COMBINED verdict
// across every candidate row loadCandidates returned for it — the whole
// unit a single transaction covers. In the steady state (an established
// anchor — see the module header) this is exactly one row, so the union
// below degenerates to that one verdict; it only matters as a narrow
// safety net for the rare pre-established case where the structural scan
// itself found more than one row. Any row finding a genuine divergence is
// enough to alert (their diverging sets are unioned); the estimate clears
// only when EVERY row agrees nothing is wrong.
async function evaluateEstimateCandidates(conn, candidatesForEstimate) {
  const { customer_id: customerId, source_estimate_id: estimateId } = candidatesForEstimate[0];
  const members = await loadGroupMembers(conn, { customerId, sourceEstimateId: estimateId });
  const prefix = DEDUPE_PREFIX(estimateId);

  // loadCandidates' invoice_status/invoice_total are read OUTSIDE this
  // transaction (plain `db`, not `conn` — see loadCandidates/runSweepInner),
  // so by the time this estimate's own transaction opens, the invoice can
  // already have settled underneath the candidate row (Codex P2). Re-read
  // every distinct invoice this estimate's rows reference here, under
  // FOR UPDATE (the same lock convention invoice.js itself takes before
  // acting on an invoice row), and decide settled vs. open from THIS fresh
  // read, never the stale one loadCandidates returned.
  const invoiceIds = [...new Set(candidatesForEstimate.map((c) => c.invoice_id).filter((id) => id != null).map(String))];
  const freshInvoicesById = new Map();
  if (invoiceIds.length) {
    const freshRows = await conn('invoices').whereIn('id', invoiceIds).forUpdate()
      .select('id', 'status', 'invoice_number', 'total');
    for (const row of freshRows) freshInvoicesById.set(String(row.id), row);
  }

  const perAnchor = candidatesForEstimate.map((candidate) => {
    const {
      anchor_id: anchorId, invoice_id: invoiceId,
      anchor_scheduled_date: anchorScheduledDate, anchor_completed_at: anchorCompletedAt,
    } = candidate;
    const freshInvoice = invoiceId != null ? freshInvoicesById.get(String(invoiceId)) : null;
    const invoiceStatus = freshInvoice ? freshInvoice.status : null;
    const anchor = members.find((m) => String(m.id) === String(anchorId))
      || { id: anchorId, scheduled_date: anchorScheduledDate, completed_at: anchorCompletedAt };
    return {
      anchor,
      verdict: evaluateGroupDivergence({ anchor, members, invoiceStatus }),
      invoice: freshInvoice
        ? { invoice_id: freshInvoice.id, invoice_number: freshInvoice.invoice_number, total: freshInvoice.total }
        : null,
    };
  });

  const alerting = perAnchor.filter((p) => p.verdict.action === 'alert');
  if (!alerting.length) {
    const cleared = await clearStandingAlerts(conn, prefix);
    return {
      estimateId, action: 'cleared', reason: perAnchor[0].verdict.reason, cleared,
    };
  }

  // Union every alerting anchor's own unresolved diverging set — the same
  // member row, if flagged from more than one anchor's perspective, is
  // deduped by id (the row objects are identical either way, since every
  // anchor evaluates against the SAME shared `members` list).
  const unresolvedUnion = new Map();
  for (const p of alerting) {
    for (const d of p.verdict.diverging) unresolvedUnion.set(String(d.id), d);
  }
  const diverging = [...unresolvedUnion.values()];
  const sortedIds = [...new Set(diverging.map((d) => String(d.id)))].sort();
  const dedupeKey = `${prefix}${sortedIds.join(',')}`;
  const { anchor, invoice } = alerting[0];
  // Any OTHER standing alert for this estimate (a different diverging set
  // than the one we're about to raise/refresh) is stale — clear it first.
  await clearStandingAlerts(conn, prefix, { exceptKey: dedupeKey });
  await raiseDivergenceAlert(conn, {
    estimateId, anchor, diverging, customerId, invoice, dedupeKey,
  });
  return { estimateId, action: 'alerted', divergingSiblingIds: sortedIds };
}

const SWEEP_CURSOR_TABLE = 'first_application_sibling_split_sweep_cursor';
const FRESH_BATCH_LIMIT = 200;

// The one persisted row's last-visited estimate id among the FRESH
// (not-yet-established) candidates — see the cursor table's own migration
// comment. Best-effort: a missing row (pre-migration, or a deleted row) is
// treated as "start from the beginning", never a sweep failure.
async function loadSweepCursor(conn) {
  const row = await conn(SWEEP_CURSOR_TABLE).where({ id: 1 }).first('last_estimate_id');
  return row ? row.last_estimate_id : null;
}

async function saveSweepCursor(conn, lastEstimateId) {
  await conn(SWEEP_CURSOR_TABLE).where({ id: 1 })
    .update({ last_estimate_id: lastEstimateId, updated_at: conn.fn.now() });
}

// Bound the FRESH structural candidates to a fair, per-tick batch so one
// tick can never run unbounded (Codex P2) — but NEVER bound the
// established-anchor groups: those are the stale-alert-recovery path
// (a standing alert whose invoice has since settled, or whose group has
// since realigned/split — see loadCandidates), and skipping any of them
// even one tick would leave a resolved alert standing or a genuinely
// reopened one silent. groups is ordered the same way loadCandidates'
// structural query is (anchor.source_estimate_id ascending), so slicing
// after the cursor and wrapping is a stable keyset walk: every fresh
// candidate is visited within ceil(freshCount / FRESH_BATCH_LIMIT) ticks,
// never starved behind an always-same head of the list.
function selectFreshBatch(freshGroups, cursor) {
  if (freshGroups.length <= FRESH_BATCH_LIMIT) return freshGroups;
  const estimateIdOf = (group) => String(group[0].source_estimate_id);
  let startIndex = 0;
  if (cursor != null) {
    const afterCursor = freshGroups.findIndex((group) => estimateIdOf(group) > String(cursor));
    startIndex = afterCursor === -1 ? 0 : afterCursor;
  }
  const batch = [];
  for (let i = 0; i < freshGroups.length && batch.length < FRESH_BATCH_LIMIT; i += 1) {
    batch.push(freshGroups[(startIndex + i) % freshGroups.length]);
  }
  return batch;
}

async function runSweepInner() {
  const candidates = await loadCandidates(db);
  // Every row for an estimate is evaluated TOGETHER (see the module
  // header) — never a picked-by-heuristic representative.
  const allGroups = groupCandidatesByEstimate(candidates);
  // A group's rows are all 'fresh' or all 'established' — loadCandidates
  // never lets the same estimate appear in both (an established anchor is
  // re-derived directly, never through the structural scan — see its own
  // comment).
  const establishedGroups = allGroups.filter((group) => group[0].candidate_source === 'established');
  const freshGroups = allGroups.filter((group) => group[0].candidate_source !== 'established');

  const cursor = freshGroups.length > FRESH_BATCH_LIMIT ? await loadSweepCursor(db) : null;
  const freshBatch = selectFreshBatch(freshGroups, cursor);
  const groups = [...establishedGroups, ...freshBatch];

  let alerted = 0;
  let cleared = 0;
  let failed = 0;
  for (const group of groups) {
    try {
      const result = await db.transaction((trx) => evaluateEstimateCandidates(trx, group));
      if (result.action === 'alerted') alerted += 1;
      else if (result.action === 'cleared' && result.cleared) cleared += 1;
    } catch (err) {
      failed += 1;
      logger.error(`[first-application-sibling-split] sweep failed for estimate ${group[0].source_estimate_id}: ${err.message}`);
    }
  }
  // Advance the cursor to the LAST fresh estimate this tick actually
  // touched, so the next tick resumes right after it — even a batch that
  // included a failure still advances (the failed estimate is retried on
  // its own next natural pass through the rotation, same as the
  // unbounded-loop's own existing retry contract; it never blocks the
  // cursor from moving forward and starving everyone behind it).
  if (freshGroups.length > FRESH_BATCH_LIMIT && freshBatch.length) {
    const lastEstimateId = freshBatch[freshBatch.length - 1][0].source_estimate_id;
    try { await saveSweepCursor(db, lastEstimateId); } catch (err) {
      logger.warn(`[first-application-sibling-split] sweep cursor save failed (non-fatal): ${err.message}`);
    }
  }
  if (failed) {
    throw new Error(`${failed} of ${groups.length} first-application sibling-split group(s) failed this tick — left for the next run`);
  }
  return {
    scanned: candidates.length, alerted, cleared, failed, freshTotal: freshGroups.length, freshBatch: freshBatch.length,
  };
}

async function runFirstApplicationSiblingSplitSweep() {
  const { runExclusive } = require('../utils/cron-lock');
  return runExclusive('first-application-sibling-split-sweep', runSweepInner);
}

