// Same-trip first-application billing ALERT — periodic SWEEP over STAMPED
// PROVENANCE (owner ruling, 2026-09-27; supersedes the #5021 round-3..9
// "alert from every writer" design AND the round-10..r8 structural-guessing
// sweep — see the PR body for the full ruling history). A reserved-accept
// slot that sells MORE than one recurring program mints ONE combined
// "First service application" invoice, linked to the RESERVED row
// (invoices.scheduled_service_id). Every OTHER program's promoted parent is
// left with estimated_price NULL on purpose — treated as covered by that
// shared invoice while both visits share a date (see estimate-converter.js
// reservedAcceptPerVisitSplit and estimate-first-application-invoice.js
// findFirstApplicationInvoiceForEstimateService).
//
// PRIOR DESIGNS (superseded, see PR #5021's body for the full history):
// round 1-2 auto-split the shared invoice's money at move time. Round 3-7
// replaced that with a durable, invoice-row hold. Round 8-9 replaced the
// hold with an in-transaction admin alert fired from every date-changing
// writer. Round 10 replaced that with a periodic sweep that GUESSED
// same-trip membership structurally (an unpriced sibling, or one with no
// live invoice of its own) — Codex round-8-on-the-sweep proved that guess
// can't tell a genuine same-trip pair apart from two independently billed
// recurring programs that simply haven't both been invoiced yet.
//
// THIS DESIGN (owner ruling 2026-09-27): record the relationship AT THE
// SOURCE instead of guessing it later. scheduled_services.
// first_application_invoice_id is stamped, once, on every member a combined
// invoice covers — the reserved anchor AND each promoted same-day sibling —
// by estimate-converter.js's stampCombinedFirstApplicationInvoiceCoverage,
// in the SAME transaction that mints the invoice, and ONLY when 2+ programs
// actually share it (a single-program accept is never stamped as a pair).
// A backfill migration (20260927220000) stamped the small number of live
// historical pairs using the OLD text-based recognition
// (isAutoGeneratedPayPerApplicationInvoice) one time. This module now
// NEVER guesses membership: it reads the stamp, period. A periodic sweep
// (every 10-15 minutes, see server/services/scheduler.js) finds every
// stamped visit, groups by invoice, re-derives each group's state fresh
// from current data, and opens/refreshes or clears ONE durable admin alert
// per estimate — judged on live state, never on which write just happened.
// No auto-split, no invoice hold, no structural inference: the office
// splits the invoice by hand.
//
// Candidate discovery (loadCandidates) is now a single, direct query:
// every scheduled_services row with first_application_invoice_id NOT NULL,
// joined to that invoice, restricted to an OPEN invoice OR one with a
// standing alert not yet confirmed resolved (see loadCandidates for the
// exact recovery condition — this replaces the old established-anchor
// history lookup with a much smaller, directly-correlated EXISTS keyed on
// the alert's own stamped invoiceId). groupCandidatesByInvoice groups the
// resulting rows by first_application_invoice_id — ALWAYS exactly the
// invoice's own covered members, never an inferred or unioned set. The
// anchor is simply the member whose id the invoice's own
// scheduled_service_id points at (invoices.scheduled_service_id) — no
// anchor-identity machinery, no union-of-verdicts safety net, no
// established-vs-fresh split: every group is evaluated the same way, once.
//
// Divergence identification (evaluateGroupDivergence/divergingSiblings) is
// UNCHANGED from the structural-guessing design and stays exactly as
// reliable: a sibling diverges whether or not it has picked up its own
// estimated_price, whether or not it has since COMPLETED (completing a
// visit never settles or rewrites the still-open combined invoice), and a
// member in ANY "work will not be performed" terminal status (cancelled,
// skipped, no-show — the shared VISIT_NEVER_RAN_STATUSES vocabulary,
// invoice-helpers.js) still needs review regardless of date divergence,
// since none of those statuses removes its charge from the combined
// invoice (voidOpenInvoicesForCancelledService and its skip/no-show
// equivalents only void an invoice linked to THAT service's OWN
// scheduled_service_id).
//
// A diverging or never-ran member resolves the SAME way either design:
// once it has its OWN LIVE invoice (has_own_live_invoice, linked via
// invoices.scheduled_service_id to its own id — the same linkage
// findFirstApplicationInvoiceForEstimateService uses), the office has
// completed the instructed manual split for that visit and it no longer
// needs an alert. "Live" excludes the full canonical canceled vocabulary
// (InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES), not just void.
// This remains signal (a) ALONE, deliberately, never a dollar
// reconciliation against the combined invoice's total — three independent
// rounds of the structural-guessing design proved a dollar comparison
// unreliable here (setup fees, gross/net plan-credit mismatches,
// multi-sibling attribution ambiguity in a 3+ program group), and none of
// that changes just because membership is now stamped instead of guessed.
//
// Settlement is judged from the invoice's OWN status only — paid, prepaid,
// processing, or the canonical void/refunded/canceled/cancelled
// vocabulary (SETTLED_INVOICE_STATUSES, reused directly from
// invoice-helpers.js's INVOICE_UNCOLLECTIBLE_STATUSES) — re-read FRESH
// under FOR UPDATE inside this estimate's own evaluation transaction
// (evaluateEstimateCandidates), never the possibly-stale status
// loadCandidates read outside any per-estimate transaction.
//
// Durable record: the admin notification itself (notification-service.
// notifyAdmin, category 'billing'), keyed on estimate id + the sorted
// diverging visit ids — no invoice column, no separate "resolved" table.
// When the condition no longer holds (dates realigned, or the invoice
// settles/voids), the standing alert for that estimate is marked read with
// an `autoCleared` stamp. Dedupe version is a DETERMINISTIC fingerprint of
// the live state (divergenceStateFingerprint) — anchor date, each
// unresolved member's own id+date+never-ran bucket, and the invoice's
// id+total — never a fresh timestamp, so an unchanged state stays
// dismissed and only a genuine change reopens it. A standing alert the
// SWEEP ITSELF auto-cleared that recurs is always a genuinely NEW
// recurrence even when the fingerprint happens to exactly match the
// pre-clear state (recurrenceGeneration, bumped only on an auto-cleared
// recurrence). Race safety: the reopen-after-dismissal decision takes the
// SAME advisory lock notifyAdmin's own dedupe path takes, held through
// notifyAdmin's own write.
//
// Fair batching: the whole stamped candidate set is bounded to a
// SWEEP_BATCH_LIMIT-sized batch per tick via a small persisted cursor
// (first_application_sibling_split_sweep_cursor — its `last_estimate_id`
// column now holds the last-visited first_application_invoice_id; the
// column keeps its original name because the migration that created it is
// already pushed and frozen, but a uuid is a uuid either way and the
// pagination logic never inspects which kind of id it holds), ordered and
// wrapped by invoice id so every candidate is visited within a bounded
// number of ticks and none is starved. The "always re-check a standing,
// unconfirmed alert even after its invoice settles" recovery this used to
// need a whole separate established-anchor code path for is now just one
// clause of loadCandidates' own WHERE — every candidate loadCandidates
// returns is equally current, so there is no more "recovery path that
// must never be bounded" to special-case; the same fair batch covers
// everything.
//
// Durability: each candidate INVOICE GROUP is evaluated in its OWN
// transaction. A failure on one group is logged and left for the next
// tick to retry — it never blocks or rolls back any other group's
// evaluation in the same run.

const db = require('../models/db');
const logger = require('./logger');
const InvoiceService = require('./invoice');
const { INVOICE_UNCOLLECTIBLE_STATUSES, VISIT_NEVER_RAN_STATUSES } = require('./invoice-helpers');

// The canonical "this visit will never be serviced" vocabulary: 'skipped'
// and 'no_show' are equally terminal, equally never-serviced statuses on
// the same scheduled_services.status CHECK constraint (AGENTS.md) as
// 'cancelled', and every one of them leaves a same-trip sibling's charge
// on the combined invoice exactly the way a cancellation does. 'canceled'
// (single L) is in the shared list defensively but is not a value the
// CHECK constraint accepts for scheduled_services — harmless to check for,
// never actually matched. Deliberately NOT 'completed': work WAS
// performed, so it is never a "will not be serviced" status.
function neverRan(status) {
  return VISIT_NEVER_RAN_STATUSES.includes(String(status || ''));
}

// Per-status alert phrasing for a never-ran member (raiseDivergenceAlert) —
// falls back to a neutral phrase for any future addition to the shared
// vocabulary this module hasn't been taught specific wording for yet.
const NEVER_RAN_PHRASE = Object.freeze({
  cancelled: 'was cancelled',
  canceled: 'was cancelled',
  skipped: 'was skipped',
  no_show: 'was a no-show',
});
function neverRanPhrase(status) {
  return NEVER_RAN_PHRASE[String(status || '')] || 'will not be serviced';
}

// The canonical "this invoice will never collect any more money"
// vocabulary — reused directly from invoice-helpers.js so this module can
// never locally drift from it (it once did, missing 'processing').
const SETTLED_INVOICE_STATUSES = INVOICE_UNCOLLECTIBLE_STATUSES;
const SWEEP_LIMIT = 500;
const DEDUPE_PREFIX = (estimateId) => `first_application_sibling_divergence:${estimateId}:`;

function dateOnly(value) {
  if (!value) return null;
  if (value instanceof Date) return value.toISOString().slice(0, 10);
  return String(value).split('T')[0].slice(0, 10);
}

function isInvoiceSettled(status) {
  return SETTLED_INVOICE_STATUSES.includes(String(status));
}

// Members currently diverging from the anchor's date: not the anchor
// itself — deliberately NOT filtered on estimated_price (a sibling that
// has picked up its own price still shares the same combined charge on
// the invoice until someone actually splits it), NOT filtered on
// completed_at (completing a visit never settles or rewrites the
// still-open COMBINED invoice), and NOT filtered on status at all — a
// never-ran member can still appear here if it also happens to have moved
// off the anchor's date; evaluateGroupDivergence's own
// neverRanNeedingReview is what actually decides a never-ran member's
// fate, date-diverged or not. Also NOT filtered on has_own_live_invoice —
// this is the RAW divergence (dates disagree); evaluateGroupDivergence is
// the one that decides which of these still need an alert.
function divergingSiblings(anchor, members) {
  const anchorDate = dateOnly(anchor.scheduled_date);
  return members.filter((m) => String(m.id) !== String(anchor.id)
    && dateOnly(m.scheduled_date) !== anchorDate);
}

// The pure detection predicate: given the group's anchor row, every member
// row (each carrying has_own_live_invoice and status), and the shared
// invoice's current status, decide whether to alert, clear a standing
// alert, or do nothing. No DB access — the sweep and every unit test call
// this the same way.
function evaluateGroupDivergence({ anchor, members, invoiceStatus }) {
  if (!anchor || !Array.isArray(members) || members.length < 2) {
    return { action: 'clear', reason: 'no_group' };
  }
  if (isInvoiceSettled(invoiceStatus)) {
    return { action: 'clear', reason: 'invoice_settled' };
  }
  const diverging = divergingSiblings(anchor, members);
  // A diverging sibling that has already picked up its OWN live invoice
  // has been split off by hand — the office completed the instructed
  // manual split for that visit, so it no longer needs an alert. A
  // NEVER-RAN diverging sibling (cancelled, skipped, or no-show) is
  // handled separately below (neverRanNeedingReview), never here — it
  // needs different alert copy and, unlike a plain diverging sibling,
  // needs review even when it never diverged by date at all.
  const unresolvedDiverging = diverging.filter((m) => !m.has_own_live_invoice && !neverRan(m.status));

  // A top-level sibling in ANY "work will not be performed" terminal
  // status still covered by the combined invoice: none of those statuses
  // removes its share of the combined charge, so it leaves a stale charge
  // whether or not its date ever diverged from the anchor's. "Covered"
  // mirrors has_own_live_invoice's own scope: once the sibling has its own
  // live invoice, it no longer needs review here.
  const neverRanNeedingReview = members.filter((m) => String(m.id) !== String(anchor.id)
    && neverRan(m.status) && !m.has_own_live_invoice);

  const unresolved = [...unresolvedDiverging, ...neverRanNeedingReview];
  if (!unresolved.length) {
    // 'split_completed' whenever there was ever something here needing
    // hand resolution (a diverging or never-ran-and-covered sibling) that
    // has since been resolved — 'realigned' only when the group never had
    // anything beyond a plain date mismatch to begin with.
    const everNeededResolution = diverging.length > 0
      || members.some((m) => String(m.id) !== String(anchor.id) && neverRan(m.status));
    return { action: 'clear', reason: everNeededResolution ? 'split_completed' : 'realigned' };
  }
  return { action: 'alert', reason: 'diverged', diverging: unresolved };
}

// Deterministic fingerprint of the live divergence state — the anchor's
// own date, each alerted sibling's own id+date+never-ran bucket (sorted,
// so member ORDER never matters), and the shared invoice's id+total. Used
// as notifyAdmin's dedupeVersion: NOT a fresh timestamp minted whenever
// the standing alert happens to be dismissed. Only a changed fingerprint
// reopens a dismissed alert; an unchanged fingerprint stays dismissed.
// Never-ran status is folded in as a coarse bucket, not the raw status
// string: an ACTIVE member's status churning through its normal lifecycle
// (confirmed → en_route → on_site) while still diverging is lifecycle
// noise, never a real change in the billing conflict, and must not reopen
// a dismissal.
function divergenceStateFingerprint({ anchor, diverging, invoiceId, invoiceTotal }) {
  const anchorDate = dateOnly(anchor.scheduled_date);
  const parts = diverging
    .map((d) => `${d.id}:${dateOnly(d.scheduled_date)}:${neverRan(d.status) ? 'never_ran' : 'active'}`)
    .sort();
  const total = invoiceTotal != null && Number.isFinite(Number(invoiceTotal)) ? Number(invoiceTotal).toFixed(2) : null;
  return JSON.stringify({
    anchorDate,
    diverging: parts,
    invoiceId: invoiceId != null ? String(invoiceId) : null,
    invoiceTotal: total,
  });
}

// Candidate discovery: a single, direct query over the durable stamp — no
// structural guessing, no anchor inference. Every scheduled_services row
// with first_application_invoice_id NOT NULL is, by construction (see
// estimate-converter.js stampCombinedFirstApplicationInvoiceCoverage and
// the backfill migration), a genuine member of a real combined invoice.
//
// Restricted to an OPEN invoice OR one with a standing alert not yet
// confirmed resolved: once an invoice settles, its group would otherwise
// disappear from every future sweep forever with no chance to confirm+
// clear a still-standing alert — exactly the "recovery" problem the old
// structural-guessing design needed a whole separate established-anchor
// history lookup for. Here it collapses to one small, directly-correlated
// EXISTS: raiseDivergenceAlert always stamps metadata.invoiceId, so a
// standing alert for THIS invoice, not yet confirmed autoCleared, is found
// by exact id match — no estimateId/anchorId indirection needed, because
// the stamp already makes membership unambiguous.
async function loadCandidates(conn, { limit = SWEEP_LIMIT } = {}) {
  const rows = await conn('scheduled_services as m')
    .join('invoices as i', 'i.id', 'm.first_application_invoice_id')
    .whereNotNull('m.first_application_invoice_id')
    .where((scope) => {
      scope.whereNotIn('i.status', SETTLED_INVOICE_STATUSES)
        .orWhereExists(function standingUnresolvedAlertExists() {
          this.select(1).from('notifications as n')
            .where('n.recipient_type', 'admin')
            .whereRaw("n.metadata->>'dedupeKey' LIKE 'first_application_sibling_divergence:%'")
            .whereRaw("n.metadata->>'invoiceId' = i.id::text")
            .whereRaw("n.metadata->>'autoCleared' IS DISTINCT FROM 'true'");
        });
    })
    .orderBy('m.first_application_invoice_id', 'asc')
    .orderBy('m.id', 'asc')
    .select(
      'm.id', 'm.scheduled_date', 'm.completed_at', 'm.status',
      'm.customer_id', 'm.source_estimate_id',
      'm.first_application_invoice_id as invoice_id',
    );
  if (rows.length >= limit) {
    logger.warn(`[first-application-sibling-split] ${rows.length} stamped first-application visits under evaluation — past the ${limit}-row watch threshold; every one is still swept this tick, but the backlog itself is worth investigating`);
  }
  return rows;
}

// Groups candidate MEMBER rows by the invoice they are stamped with — the
// whole group IS the invoice's covered members, never an inferred or
// unioned set. A group of fewer than 2 (a stray single stamp — should
// never happen given stampCombinedFirstApplicationInvoiceCoverage's own
// 2+-only guarantee, but defensive against a manual edit or a bug) is
// dropped: the sweep only ever evaluates a genuine pair or larger.
function groupCandidatesByInvoice(candidates) {
  const byInvoice = new Map();
  for (const candidate of candidates) {
    const key = candidate.invoice_id;
    if (!byInvoice.has(key)) byInvoice.set(key, []);
    byInvoice.get(key).push(candidate);
  }
  return [...byInvoice.values()].filter((group) => group.length >= 2);
}

// Marks read (with an autoCleared stamp) every standing alert for this
// estimate whose dedupeKey carries the given prefix — optionally excluding
// one key that is about to be raised/refreshed instead. Deliberately NOT
// scoped to whereNull('read_at'): an alert a human already DISMISSED while
// the group was still diverging must ALSO get the autoCleared stamp once
// the group genuinely resolves — otherwise raiseDivergenceAlert's
// wasAutoCleared check never sees the resolution, and an identical-dates
// recurrence after a plain dismissal + real realignment stays silently
// dismissed forever. COALESCE(read_at, NOW()) never disturbs an existing
// dismissal timestamp; it only sets read_at on a row that was still
// unread.
async function clearStandingAlerts(conn, prefix, { exceptKey = null } = {}) {
  let q = conn('notifications').where({ recipient_type: 'admin' })
    .whereRaw("metadata->>'dedupeKey' LIKE ?", [`${prefix}%`]);
  if (exceptKey) q = q.whereRaw("metadata->>'dedupeKey' <> ?", [exceptKey]);
  return q.update({
    read_at: conn.raw('COALESCE(read_at, NOW())'),
    metadata: conn.raw("COALESCE(metadata, '{}'::jsonb) || ?::jsonb", [JSON.stringify({ autoCleared: true })]),
  });
}

// Raises (or refreshes) the durable admin alert for this exact diverging
// set. Takes the SAME advisory lock notifyAdmin's own dedupe path takes,
// and holds it through notifyAdmin's own write, so a concurrent dismissal
// can never land between the decision and the write. Never touches the
// invoice or any visit row.
async function raiseDivergenceAlert(conn, {
  estimateId, anchor, diverging, invoice, customerId, dedupeKey,
}) {
  await conn.raw('SELECT pg_advisory_xact_lock(hashtext(?))', [`admin:${dedupeKey}`]);
  const baseFingerprint = divergenceStateFingerprint({
    anchor, diverging, invoiceId: invoice?.invoice_id, invoiceTotal: invoice?.total,
  });
  // A standing alert the SWEEP ITSELF auto-cleared that is diverging again
  // is a genuinely NEW recurrence even when its fingerprint happens to
  // exactly match the pre-clear state — recurrenceGeneration is bumped
  // only on an auto-cleared recurrence, so repeated identical resolve/
  // recur cycles each still produce a distinct dedupeVersion. A PLAIN
  // human dismissal (read_at set, never autoCleared) keeps the
  // deterministic-fingerprint dedupe: unchanged state stays dismissed.
  const existing = await conn('notifications').where({ recipient_type: 'admin' })
    .whereRaw("metadata->>'dedupeKey' = ?", [dedupeKey]).first('read_at', 'metadata');
  let existingMeta = existing?.metadata;
  if (typeof existingMeta === 'string') { try { existingMeta = JSON.parse(existingMeta); } catch { existingMeta = null; } }
  const wasAutoCleared = Boolean(existing?.read_at) && existingMeta?.autoCleared === true;
  const priorGeneration = Number(existingMeta?.recurrenceGeneration) || 0;
  const generation = wasAutoCleared ? priorGeneration + 1 : priorGeneration;
  const dedupeVersion = `${baseFingerprint}::g${generation}`;
  const anchorDate = dateOnly(anchor.scheduled_date);
  // Never-ran members (cancelled/skipped/no-show) get distinct copy: the
  // office action isn't "split it by hand" — the visit already isn't
  // happening — it's removing that sibling's share of the still-open
  // combined charge. A never-ran member can ALSO have moved off the
  // anchor's date; the never-ran copy always wins for it since that's the
  // actual remaining action, regardless of date.
  const neverRanMembers = diverging.filter((d) => neverRan(d.status));
  const movedMembers = diverging.filter((d) => !neverRan(d.status));
  const detailParts = [
    ...movedMembers.map((d) => `visit ${d.id} now on ${dateOnly(d.scheduled_date)} (was ${anchorDate})`),
    ...neverRanMembers.map((d) => `visit ${d.id} ${neverRanPhrase(d.status)} — remove its charge from the combined invoice`),
  ];
  const detail = detailParts.join('; ');
  const invoiceRef = invoice
    ? `Invoice ${invoice.invoice_number || invoice.invoice_id}.`
    : `Check the first-application invoice for estimate #${estimateId}.`;
  // A Postgres regression test asserts the exact "split it by hand"
  // substring survives whenever a moved member is present, so that phrase
  // is never rewritten for that case.
  const leadSentence = movedMembers.length
    ? 'Same-trip visits from one estimate landed on different days'
    : 'A same-trip visit from one estimate will not be serviced';
  const actionSentence = movedMembers.length
    ? 'The combined first-application invoice still charges for both — split it by hand.'
    : 'The combined first-application invoice still charges for it — remove that charge.';
  await require('./notification-service').notifyAdmin(
    'billing',
    'First-application invoice may need to be split by hand',
    `${leadSentence}: ${detail}. ${actionSentence} ${invoiceRef}`,
    {
      link: invoice ? `/admin/invoices?invoice=${invoice.invoice_id}` : `/admin/estimates/${estimateId}`,
      bell: true,
      metadata: {
        estimateId: String(estimateId),
        anchorId: String(anchor.id),
        divergingSiblingIds: diverging.map((d) => String(d.id)),
        customerId: customerId ? String(customerId) : null,
        // Read back by loadCandidates' own recovery EXISTS clause — the
        // exact-match key that lets a settled invoice's still-standing,
        // not-yet-confirmed alert get one more evaluation instead of
        // disappearing from every future sweep.
        invoiceId: invoice ? String(invoice.invoice_id) : null,
        // An alert we are (re)raising right now is by definition not in
        // the auto-cleared state any more — explicitly cleared here since
        // notifyAdmin's refresh merges onto the OLD metadata, which would
        // otherwise leave a stale autoCleared:true sitting on a reopened
        // alert forever.
        autoCleared: false,
        recurrenceGeneration: generation,
      },
      dedupeKey,
      dedupeVersion,
      refreshOnDedupe: true,
      trx: conn,
    },
  );
}

// Re-derives one invoice group's state fresh and acts on it — the whole
// unit a single transaction covers. membersForInvoice is EXACTLY the
// invoice's stamped covered members (2+, guaranteed by
// groupCandidatesByInvoice); the anchor is simply whichever member the
// invoice's own scheduled_service_id points at.
async function evaluateEstimateCandidates(conn, membersForInvoice) {
  if (!Array.isArray(membersForInvoice) || membersForInvoice.length < 2) {
    return { estimateId: membersForInvoice?.[0]?.source_estimate_id ?? null, action: 'skipped', reason: 'not_a_pair' };
  }
  const { source_estimate_id: estimateId, customer_id: customerId, invoice_id: invoiceId } = membersForInvoice[0];
  const prefix = DEDUPE_PREFIX(estimateId);

  // Re-read the invoice fresh under FOR UPDATE inside this transaction —
  // loadCandidates' own invoice status is read outside any per-estimate
  // transaction and could already be stale by the time this runs.
  const freshInvoice = await conn('invoices').where({ id: invoiceId }).forUpdate()
    .first('id', 'status', 'invoice_number', 'total', 'scheduled_service_id');
  if (!freshInvoice) {
    // The invoice row is gone from under the stamp (ON DELETE SET NULL
    // means this should be unreachable in practice — a deleted invoice
    // clears the stamp itself — but fail safe rather than throw).
    const cleared = await clearStandingAlerts(conn, prefix);
    return {
      estimateId, action: 'cleared', reason: 'invoice_missing', cleared,
    };
  }
  const anchor = membersForInvoice.find((m) => String(m.id) === String(freshInvoice.scheduled_service_id));
  if (!anchor) {
    // The invoice's own scheduled_service_id isn't among the stamped
    // members — stampCombinedFirstApplicationInvoiceCoverage always
    // includes the anchor, so this should be unreachable; fail safe.
    const cleared = await clearStandingAlerts(conn, prefix);
    return {
      estimateId, action: 'cleared', reason: 'no_anchor', cleared,
    };
  }

  // has_own_live_invoice per member: a LIVE invoice linked to that
  // member's OWN scheduled_service_id — the real-data signal that the
  // office has already hand-split that visit off the shared invoice.
  // "Live" excludes the FULL canonical canceled vocabulary, not just
  // void.
  const memberIds = membersForInvoice.map((m) => m.id);
  const ownInvoiceIds = await conn('invoices')
    .whereIn('scheduled_service_id', memberIds)
    .whereNotIn('status', InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES)
    .pluck('scheduled_service_id');
  const ownInvoiceSet = new Set(ownInvoiceIds.map(String));
  const members = membersForInvoice.map((m) => ({ ...m, has_own_live_invoice: ownInvoiceSet.has(String(m.id)) }));
  const anchorWithFlag = members.find((m) => String(m.id) === String(anchor.id));

  const verdict = evaluateGroupDivergence({ anchor: anchorWithFlag, members, invoiceStatus: freshInvoice.status });
  if (verdict.action === 'clear') {
    const cleared = await clearStandingAlerts(conn, prefix);
    return {
      estimateId, action: 'cleared', reason: verdict.reason, cleared,
    };
  }

  const diverging = verdict.diverging;
  const sortedIds = [...new Set(diverging.map((d) => String(d.id)))].sort();
  const dedupeKey = `${prefix}${sortedIds.join(',')}`;
  const invoice = { invoice_id: freshInvoice.id, invoice_number: freshInvoice.invoice_number, total: freshInvoice.total };
  // Any OTHER standing alert for this estimate (a different diverging set
  // than the one we're about to raise/refresh) is stale — clear it first.
  await clearStandingAlerts(conn, prefix, { exceptKey: dedupeKey });
  await raiseDivergenceAlert(conn, {
    estimateId, anchor: anchorWithFlag, diverging, customerId, invoice, dedupeKey,
  });
  return { estimateId, action: 'alerted', divergingSiblingIds: sortedIds };
}

const SWEEP_CURSOR_TABLE = 'first_application_sibling_split_sweep_cursor';
const SWEEP_BATCH_LIMIT = 200;

// The one persisted row's last-visited invoice id — see the cursor
// table's own migration comment for why the column is still named
// last_estimate_id (it now holds a first_application_invoice_id; the
// migration that created the table is already pushed and frozen, and the
// pagination logic below never inspects which kind of uuid it holds, so
// renaming the column was not worth a whole extra migration). Best-effort:
// a missing row (pre-migration, or a deleted row) is treated as "start
// from the beginning", never a sweep failure.
async function loadSweepCursor(conn) {
  const row = await conn(SWEEP_CURSOR_TABLE).where({ id: 1 }).first('last_estimate_id');
  return row ? row.last_estimate_id : null;
}

async function saveSweepCursor(conn, lastInvoiceId) {
  await conn(SWEEP_CURSOR_TABLE).where({ id: 1 })
    .update({ last_estimate_id: lastInvoiceId, updated_at: conn.fn.now() });
}

// Bound the candidate groups to a fair, per-tick batch so one tick can
// never run unbounded. groups is ordered the same way loadCandidates'
// query is (invoice id ascending), so slicing after the cursor and
// wrapping is a stable keyset walk: every candidate is visited within
// ceil(groupCount / SWEEP_BATCH_LIMIT) ticks, never starved behind an
// always-same head of the list. Unlike the old structural-guessing
// design, there is no separate "established, never bounded" category any
// more — every stamped candidate loadCandidates returns (including a
// standing-alert recovery case) is equally current, so the SAME batch
// covers everything.
function selectSweepBatch(groups, cursor) {
  if (groups.length <= SWEEP_BATCH_LIMIT) return groups;
  const invoiceIdOf = (group) => String(group[0].invoice_id);
  let startIndex = 0;
  if (cursor != null) {
    const afterCursor = groups.findIndex((group) => invoiceIdOf(group) > String(cursor));
    startIndex = afterCursor === -1 ? 0 : afterCursor;
  }
  const batch = [];
  for (let i = 0; i < groups.length && batch.length < SWEEP_BATCH_LIMIT; i += 1) {
    batch.push(groups[(startIndex + i) % groups.length]);
  }
  return batch;
}

async function runSweepInner() {
  const candidates = await loadCandidates(db);
  const allGroups = groupCandidatesByInvoice(candidates);

  const cursor = allGroups.length > SWEEP_BATCH_LIMIT ? await loadSweepCursor(db) : null;
  const groups = selectSweepBatch(allGroups, cursor);

  let alerted = 0;
  let cleared = 0;
  let failed = 0;
  for (const group of groups) {
    try {
      const result = await db.transaction((trx) => evaluateEstimateCandidates(trx, group));
      if (result.action === 'alerted') alerted += 1;
      else if (result.action === 'cleared' && result.cleared) cleared += 1;
    } catch (err) {
      failed += 1;
      logger.error(`[first-application-sibling-split] sweep failed for invoice group ${group[0].invoice_id}: ${err.message}`);
    }
  }
  // Advance the cursor to the LAST invoice this tick actually touched, so
  // the next tick resumes right after it — even a batch that included a
  // failure still advances (the failed group is retried on its own next
  // natural pass through the rotation; it never blocks the cursor from
  // moving forward and starving everyone behind it).
  if (allGroups.length > SWEEP_BATCH_LIMIT && groups.length) {
    const lastInvoiceId = groups[groups.length - 1][0].invoice_id;
    try { await saveSweepCursor(db, lastInvoiceId); } catch (err) {
      logger.warn(`[first-application-sibling-split] sweep cursor save failed (non-fatal): ${err.message}`);
    }
  }
  if (failed) {
    throw new Error(`${failed} of ${groups.length} first-application sibling-split group(s) failed this tick — left for the next run`);
  }
  return {
    scanned: candidates.length, alerted, cleared, failed, groupsTotal: allGroups.length, groupsThisTick: groups.length,
  };
}

async function runFirstApplicationSiblingSplitSweep() {
  const { runExclusive } = require('../utils/cron-lock');
  return runExclusive('first-application-sibling-split-sweep', runSweepInner);
}

