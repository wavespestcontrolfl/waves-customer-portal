// Same-trip first-application billing ALERT — periodic SWEEP design
// (owner ruling, 2026-09-27; supersedes the #5021 round-3..9 "alert from
// every writer" design — see the PR body for the full ruling history). A
// reserved-accept slot that sells MORE than one recurring program mints ONE
// combined "First service application" invoice, linked to the RESERVED
// row (invoices.scheduled_service_id). Every OTHER program's promoted
// parent is left with estimated_price NULL on purpose — treated as covered
// by that shared invoice while both visits share a date (see
// estimate-converter.js reservedAcceptPerVisitSplit and
// estimate-first-application-invoice.js
// findFirstApplicationInvoiceForEstimateService, whose own date-keyed match
// simply stops matching once a member's date diverges — no code change
// needed there).
//
// PRIOR DESIGNS (superseded, see PR #5021's body for the full history):
// round 1-2 auto-split the shared invoice's money at move time. Round 3-7
// replaced that with a durable, invoice-row hold. Round 8-9 replaced the
// hold with an in-transaction admin alert fired from every date-changing
// writer (admin-schedule.js, visit-groups.js, rebooker.js,
// intelligence-bar/schedule-tools.js + tools.js) — but Codex round 5 found
// that shape structurally leaky: a grouped move judged mid-batch raised a
// false alarm on an interim state (bulk-reschedule landing both siblings on
// the SAME new day), a sibling that picked up ANY price was excluded from
// ever alerting even though the shared invoice still charged for it, and
// the dedupe-reopen decision raced the alert's own advisory lock. Fixing
// each writer's own view of "did this move actually diverge the group" was
// the wrong shape — every writer would need its own final-state
// reconciliation forever.
//
// OWNER RULING (this design): stop alerting from the movers entirely. A
// periodic SWEEP (every 10-15 minutes, see server/services/scheduler.js)
// finds every OPEN (non-settled) first-application invoice, re-derives its
// estimate group fresh from current data, and opens/refreshes or clears
// ONE durable admin alert per estimate — judged on live state, never on
// which write just happened. No auto-split, no invoice hold: the office
// splits the invoice by hand.
//
// Candidate discovery (loadCandidates): bounded by invoices.status NOT IN
// the settled vocabulary (indexed column) joined to its anchor row via
// invoices.scheduled_service_id (also indexed) — the two columns every
// non-settled first-application invoice is cheap to find by. The
// title/notes shape check (isAutoGeneratedPayPerApplicationInvoice, from
// estimate-first-application-invoice.js — reused, never re-derived) narrows
// that small set down to real first-application invoices in JS, same as
// every other caller of that helper.
//
// Divergence identification (evaluateGroupDivergence/divergingSiblings) is
// keyed ONLY on estimate + visit ids — customer_id + source_estimate_id +
// recurring_parent_id IS NULL, never on invoice title/notes text (that text
// match is solely how a candidate INVOICE is found above, same as every
// other caller). A sibling now diverges whether or not it has picked up its
// own estimated_price (Codex P1: a priced sibling still shares the same
// combined charge) — completed members are excluded (a completed visit's
// billing outcome is a settled fact a plain date move can't change).
//
// Settlement is judged from the invoice's OWN status only (paid, prepaid,
// or the canonical cancelled/refunded/void vocabulary
// InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES already defines) —
// never from the visits' estimated_price.
//
// Durable record: the admin notification itself (notification-service.
// notifyAdmin, category 'billing'), keyed on estimate id + the sorted
// diverging visit ids — no invoice column, no separate "resolved" table.
// When the condition no longer holds (dates realigned, or the invoice
// settles/voids), the standing alert for that estimate is marked read with
// an `autoCleared` stamp (same convention as supplies-consumption.js's
// clearMissedDeductionBells / ops-digest.js's resolved stamp) — the closest
// "resolve" mechanism notifications already support; there is no bespoke
// clear route to build here.
//
// Race safety (Codex P2): the reopen-after-dismissal decision takes the
// SAME advisory lock notifyAdmin's own dedupe path takes, and holds it
// continuously (same session, same transaction) through notifyAdmin's own
// write, so a concurrent dismissal can never land between the decision and
// the write.
//
// Dedupe version (pre-push P1 fix): dedupeVersion is built from a
// DETERMINISTIC fingerprint of the live state — anchor date, each
// unresolved diverging sibling's own id+date, and the invoice's id+total
// (divergenceStateFingerprint) — never a fresh timestamp minted just
// because the standing alert happens to be dismissed. A PLAIN human
// dismissal (read_at set, no autoCleared stamp) whose fingerprint is
// unchanged on the next tick stays dismissed; only a fingerprint change
// (a different dates tuple, or a different invoice id/total) re-opens it.
// A standing alert the SWEEP ITSELF auto-cleared (autoCleared:true —
// dates realigned or the group resolved) is different: its return is
// always a genuinely new recurrence, even when the fingerprint happens to
// exactly match the pre-clear state (realign, then diverge back onto the
// SAME date) — so raiseDivergenceAlert bumps a recurrenceGeneration
// counter on every auto-cleared recurrence and folds it into
// dedupeVersion, guaranteeing a fresh value each cycle without ever using
// a non-deterministic timestamp (Codex round-1 P1 on this fix).
//
// Manual-split resolution (pre-push P1 fix): once the office completes the
// instructed manual split, the sweep must stop alerting for the resolved
// sibling(s) without relying on invoice text. Signal chosen: a diverging
// sibling counts as split off once it has picked up its OWN LIVE invoice
// linked to its own scheduled_service_id (has_own_live_invoice, computed
// in loadGroupMembers) — the same invoices.scheduled_service_id linkage
// every other caller in this area (findFirstApplicationInvoiceForEstimateService)
// uses to resolve a visit's invoice, so a hand-split invoice is found the
// same way a minted one would be. "Live" excludes the full canonical
// canceled vocabulary (void, refunded, canceled, cancelled — Codex
// round-1 P1: void alone let a canceled "split" invoice falsely clear the
// alert), not just void.
//
// has_own_live_invoice is necessary but NOT sufficient (Codex round-4 P1):
// a brand-new sibling invoice can exist while the combined invoice still
// carries that sibling's full original charge (an unresolved duplicate
// charge). evaluateGroupDivergence additionally requires
// combinedChargeAdjusted — the combined invoice's CURRENT total strictly
// less than anchor.estimated_price, which IS the full same-day combined
// total at acceptance (reservedAcceptPerVisitSplit's `reservedPrice` — see
// estimate-converter.js, "its price is the route's same-day total") — real
// evidence something was actually carved back out of it, not merely that a
// second invoice now exists. This is more robust than comparing the shared
// invoice's line items/total against the per-visit split amounts
// (reservedAcceptPerVisitSplit) — those amounts are derived only at
// itemizeFirstApplication/closeout time (GATE_VISIT_CLOSEOUT-gated) and are
// not a durable, always-available record to diff against for an arbitrary
// group on an arbitrary sweep tick; comparing against anchor.estimated_price
// instead uses a value already persisted at acceptance, no re-derivation.
// Unreadable/missing evidence FAILS CLOSED (never treated as adjusted).
// evaluateGroupDivergence excludes any diverging sibling with BOTH
// has_own_live_invoice AND combinedChargeAdjusted from the alerted set;
// once EVERY diverging sibling clears that bar the group clears with reason
// 'split_completed' (distinct from 'realigned', which means the dates
// actually matched again).
//
// One representative row per estimate (Codex round-3 P1): loadCandidates
// can return MORE THAN ONE invoice row for the same estimate — a stale,
// now-settled invoice a standing alert still names (the second half of
// loadCandidates) alongside its LIVE replacement for the same anchor visit
// (the alerted invoice was voided and re-minted). Evaluating each
// independently — one per transaction, in whichever order loadCandidates
// returned them — let the settled row's own 'clear' verdict undo the live
// row's own 'alert' verdict for the SAME group. runSweepInner runs every
// candidate through representativeCandidatesByEstimate first, which always
// prefers a live (non-settled) row as the one that governs the group.
//
// Durability: each candidate estimate group is evaluated in its OWN
// transaction. A failure on one group is logged and left for the next
// tick to retry — it never blocks or rolls back any other group's
// evaluation in the same run.

const db = require('../models/db');
const logger = require('./logger');
const InvoiceService = require('./invoice');

const SETTLED_INVOICE_STATUSES = Object.freeze(['paid', 'prepaid', ...InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES]);
const SWEEP_LIMIT = 500;
const DEDUPE_PREFIX = (estimateId) => `first_application_sibling_divergence:${estimateId}:`;

function dateOnly(value) {
  if (!value) return null;
  if (value instanceof Date) return value.toISOString().slice(0, 10);
  return String(value).split('T')[0].slice(0, 10);
}

function isInvoiceSettled(status) {
  return SETTLED_INVOICE_STATUSES.includes(String(status));
}

// Members currently diverging from the anchor's date: not the anchor
// itself, not already completed (a completed row's billing outcome is a
// settled fact a plain date move can't change) — deliberately NOT filtered
// on estimated_price (Codex P1: a sibling that has picked up its own price
// still shares the same combined charge on the invoice until someone
// actually splits it). Also deliberately NOT filtered on has_own_live_invoice
// here — this is the RAW divergence (dates disagree); evaluateGroupDivergence
// is the one that decides which of these still need an alert.
function divergingSiblings(anchor, members) {
  const anchorDate = dateOnly(anchor.scheduled_date);
  return members.filter((m) => String(m.id) !== String(anchor.id)
    && !m.completed_at
    && dateOnly(m.scheduled_date) !== anchorDate);
}

// Cents, or null when unreadable — every money comparison below fails
// closed on null rather than coercing an unreadable value into 0. null and
// undefined are explicitly unreadable (Number(null) is 0, a real finite
// number, which would otherwise silently poison "unset" into "zero-priced"
// instead of "unknown").
function toCents(value) {
  if (value === null || value === undefined) return null;
  const n = Number(value);
  return Number.isFinite(n) ? Math.round(n * 100) : null;
}

// The pure detection predicate: given the group's anchor row (carrying its
// own estimated_price — see groupFullyAccountedFor below), every member row
// (each optionally carrying has_own_live_invoice + own_live_invoice_total —
// loadGroupMembers stamps these from a real invoices.scheduled_service_id
// lookup), the shared invoice's current status, and its current total,
// decide whether to alert, clear a standing alert, or do nothing. No DB
// access — the sweep and every unit test call this the same way.
function evaluateGroupDivergence({
  anchor, members, invoiceStatus, invoiceTotal,
}) {
  if (!anchor || !Array.isArray(members) || members.length < 2) {
    return { action: 'clear', reason: 'no_group' };
  }
  if (isInvoiceSettled(invoiceStatus)) {
    return { action: 'clear', reason: 'invoice_settled' };
  }
  const diverging = divergingSiblings(anchor, members);
  if (!diverging.length) {
    return { action: 'clear', reason: 'realigned' };
  }
  // A diverging sibling's own live invoice is proof the office STARTED the
  // split, but never proof they FINISHED it (Codex round-4 P1): a brand-new
  // sibling invoice can exist while the combined invoice still carries that
  // sibling's full original charge — an unresolved duplicate charge. And a
  // group-wide "SOME reduction happened" check is not enough either (Codex
  // round-5 P1): in a 3+ program group, creating both siblings' own
  // invoices but removing only ONE sibling's charge from the combined
  // invoice must not clear either of them — a partial reduction, or an
  // unrelated discount, must never be read as proof for a specific
  // sibling. So the WHOLE set of diverging siblings that have their own
  // invoice is only treated as resolved TOGETHER when the combined
  // invoice's reduction (anchor.estimated_price − its CURRENT total —
  // anchor.estimated_price IS the full same-day combined total at
  // acceptance, reservedAcceptPerVisitSplit's `reservedPrice`; see
  // estimate-converter.js, "its price is the route's same-day total")
  // covers AT LEAST the SUM of every one of those siblings' own invoice
  // totals — real evidence the specific amount that moved out was actually
  // removed, never merely SOME positive reduction. Unreadable/missing
  // evidence (no anchor.estimated_price, no invoiceTotal, or an unreadable
  // own_live_invoice_total on any sibling counted in the sum) FAILS CLOSED
  // and keeps the ENTIRE group alerting — this never guesses which
  // specific sibling(s) a partial reduction covers.
  const withOwnInvoice = diverging.filter((m) => m.has_own_live_invoice);
  const reductionCents = (() => {
    const anchorCents = toCents(anchor.estimated_price);
    const totalCents = toCents(invoiceTotal);
    return anchorCents != null && totalCents != null ? anchorCents - totalCents : null;
  })();
  const sumOwnInvoiceCents = withOwnInvoice.reduce((sum, m) => {
    if (sum === null) return null;
    const cents = toCents(m.own_live_invoice_total);
    return cents != null ? sum + cents : null;
  }, 0);
  const groupFullyAccountedFor = withOwnInvoice.length > 0
    && reductionCents != null && sumOwnInvoiceCents != null
    && reductionCents >= sumOwnInvoiceCents;
  const unresolved = groupFullyAccountedFor
    ? diverging.filter((m) => !m.has_own_live_invoice)
    : diverging;
  if (!unresolved.length) {
    return { action: 'clear', reason: 'split_completed' };
  }
  return { action: 'alert', reason: 'diverged', diverging: unresolved };
}

// Deterministic fingerprint of the live divergence state — the anchor's own
// date, each alerted sibling's own id+date (sorted, so member ORDER never
// matters), and the shared invoice's id+total. Used as notifyAdmin's
// dedupeVersion (pre-push P1 fix): NOT a fresh timestamp minted whenever the
// standing alert happens to be dismissed — that would reopen a dismissed
// alert on every sweep tick even with nothing materially different. Only a
// changed fingerprint (a different dates tuple, or a different invoice id
// or total) reopens a dismissed alert; an unchanged fingerprint stays
// dismissed.
function divergenceStateFingerprint({ anchor, diverging, invoiceId, invoiceTotal }) {
  const anchorDate = dateOnly(anchor.scheduled_date);
  const parts = diverging.map((d) => `${d.id}:${dateOnly(d.scheduled_date)}`).sort();
  const total = invoiceTotal != null && Number.isFinite(Number(invoiceTotal)) ? Number(invoiceTotal).toFixed(2) : null;
  return JSON.stringify({
    anchorDate,
    diverging: parts,
    invoiceId: invoiceId != null ? String(invoiceId) : null,
    invoiceTotal: total,
  });
}

const CANDIDATE_COLUMNS = [
  'i.id as invoice_id', 'i.status as invoice_status', 'i.invoice_number', 'i.title', 'i.notes',
  'i.total as invoice_total', 'i.created_at as invoice_created_at',
  'anchor.id as anchor_id', 'anchor.customer_id', 'anchor.source_estimate_id',
  'anchor.scheduled_date as anchor_scheduled_date', 'anchor.completed_at as anchor_completed_at',
  'anchor.estimated_price as anchor_estimated_price',
];

// Consolidates multiple candidate INVOICE rows for the SAME estimate down
// to ONE representative to evaluate (Codex round-3 P1 on the pre-push
// fix): loadCandidates' second half can return a stale, now-SETTLED
// invoice a standing alert still names alongside its LIVE replacement for
// the same anchor visit (the alerted invoice was voided and re-minted).
// Evaluating both independently — one per transaction, in whichever order
// loadCandidates happened to return them — let the settled row's own
// 'clear' verdict undo the live row's own 'alert' verdict for the SAME
// estimate group. A live (non-settled) row always wins: that is the
// invoice actually governing the group right now. Only when EVERY row for
// the estimate is settled (the group is genuinely, fully resolved) does a
// settled row represent it — any one of them decides the same 'clear'
// verdict either way, so ties there are broken by newest invoice only for
// determinism, not correctness.
function representativeCandidatesByEstimate(candidates) {
  const byEstimate = new Map();
  for (const candidate of candidates) {
    const key = candidate.source_estimate_id;
    const current = byEstimate.get(key);
    if (!current) { byEstimate.set(key, candidate); continue; }
    const currentLive = !isInvoiceSettled(current.invoice_status);
    const candidateLive = !isInvoiceSettled(candidate.invoice_status);
    if (candidateLive && !currentLive) {
      byEstimate.set(key, candidate);
    } else if (candidateLive === currentLive) {
      const currentCreated = current.invoice_created_at ? new Date(current.invoice_created_at).getTime() : 0;
      const candidateCreated = candidate.invoice_created_at ? new Date(candidate.invoice_created_at).getTime() : 0;
      if (candidateCreated > currentCreated) byEstimate.set(key, candidate);
    }
  }
  return [...byEstimate.values()];
}

// invoiceId values every currently-UNREAD sibling-divergence alert names in
// its own metadata (stamped there when raised — see raiseDivergenceAlert).
// Small and cheap by construction: bounded by however many such alerts are
// presently unread, never by total invoice history.
async function loadStaleAlertInvoiceIds(conn) {
  const alerts = await conn('notifications')
    .where({ recipient_type: 'admin' })
    .whereNull('read_at')
    .whereRaw("metadata->>'dedupeKey' LIKE 'first_application_sibling_divergence:%'")
    .select('metadata');
  const ids = new Set();
  for (const row of alerts) {
    let meta = row.metadata;
    if (typeof meta === 'string') { try { meta = JSON.parse(meta); } catch { meta = null; } }
    if (meta && meta.invoiceId) ids.add(meta.invoiceId);
  }
  return [...ids];
}

// Every currently OPEN (non-settled) first-application invoice, joined to
// its anchor (reserved/priced) scheduled_services row — bounded by two
// indexed columns (invoices.status, invoices.scheduled_service_id) — PLUS
// any invoice a currently-unread standing alert still names even though it
// no longer qualifies above (settled since the alert was raised — a PK
// lookup, bounded by the small unread-alert set above): without this
// second half, an invoice that settles between ticks would silently drop
// out of every future sweep and its alert would never auto-clear.
//
// Deliberately UNBOUNDED by row count (Codex P1): the set this query
// selects is already bounded by "currently non-settled" — operationally
// small — so an ORDER BY + LIMIT here would silently starve every
// candidate past the cutoff forever (the same oldest N rows every tick,
// with nothing ever aging the newer ones in). `limit` is a WARNING
// threshold only — crossing it means the open backlog has grown large
// enough to be its own problem, worth an ops signal, never a reason to
// evaluate fewer of them.
async function loadCandidates(conn, { limit = SWEEP_LIMIT } = {}) {
  const openRows = await conn('invoices as i')
    .join('scheduled_services as anchor', 'anchor.id', 'i.scheduled_service_id')
    .whereNotIn('i.status', SETTLED_INVOICE_STATUSES)
    .whereNotNull('anchor.source_estimate_id')
    .whereNull('anchor.recurring_parent_id')
    .orderBy('i.created_at', 'asc')
    .select(CANDIDATE_COLUMNS);
  if (openRows.length >= limit) {
    logger.warn(`[first-application-sibling-split] ${openRows.length} open first-application invoices — past the ${limit}-row watch threshold; every one is still swept this tick, but the backlog itself is worth investigating`);
  }
  const { isAutoGeneratedPayPerApplicationInvoice } = require('./estimate-first-application-invoice');
  const matched = openRows.filter((row) => isAutoGeneratedPayPerApplicationInvoice({ title: row.title, notes: row.notes }));

  const staleInvoiceIds = await loadStaleAlertInvoiceIds(conn);
  const covered = new Set(matched.map((r) => r.invoice_id));
  const missing = staleInvoiceIds.filter((id) => !covered.has(id));
  if (!missing.length) return matched;
  const staleRows = await conn('invoices as i')
    .join('scheduled_services as anchor', 'anchor.id', 'i.scheduled_service_id')
    .whereIn('i.id', missing)
    .select(CANDIDATE_COLUMNS);
  return [...matched, ...staleRows];
}

// Every member of the estimate group, each stamped with:
//   has_own_live_invoice: true when a LIVE invoice is linked to that
//     member's OWN scheduled_service_id — the real-data signal that the
//     office has already hand-split that visit off the shared invoice
//     (see the module header). "Live" excludes the FULL canonical
//     canceled vocabulary (InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES:
//     void, refunded, canceled, cancelled — pre-push P1: void alone let a
//     canceled "split" invoice falsely clear the alert while the sibling
//     still has no real replacement charge), not just 'void'.
//   own_live_invoice_total: the SUM of that member's own live invoice(s)'
//     totals (null when has_own_live_invoice is false) — read by
//     evaluateGroupDivergence's groupFullyAccountedFor check (Codex
//     round-5 P1) to verify the combined invoice's reduction actually
//     covers what moved out, not merely that a sibling invoice exists.
// Cheap and bounded: one extra query keyed on this small group's own ids.
async function loadGroupMembers(conn, { customerId, sourceEstimateId }) {
  const members = await conn('scheduled_services')
    .where({ customer_id: customerId, source_estimate_id: sourceEstimateId })
    .whereNull('recurring_parent_id')
    .orderBy('id')
    .select('id', 'scheduled_date', 'completed_at', 'estimated_price');
  if (!members.length) return members;
  const ownInvoiceRows = await conn('invoices')
    .whereIn('scheduled_service_id', members.map((m) => m.id))
    .whereNotIn('status', InvoiceService.CANCELLED_SERVICE_RESOLVED_STATUSES)
    .select('scheduled_service_id', 'total');
  // A member could in principle carry more than one live invoice of its
  // own (e.g. a second hand-corrected mint) — sum them, since every one of
  // them is real money charged for that visit outside the combined one.
  const ownTotalsByMember = new Map();
  for (const row of ownInvoiceRows) {
    const key = String(row.scheduled_service_id);
    const cents = toCents(row.total);
    // An unreadable individual row's amount still marks the member as
    // having its own invoice (has_own_live_invoice), but poisons the SUM
    // to null — groupFullyAccountedFor then fails closed rather than
    // silently undercounting what moved out.
    const prior = ownTotalsByMember.has(key) ? ownTotalsByMember.get(key) : 0;
    ownTotalsByMember.set(key, prior === null || cents === null ? null : prior + cents);
  }
  return members.map((m) => {
    const key = String(m.id);
    const hasOwn = ownTotalsByMember.has(key);
    const cents = hasOwn ? ownTotalsByMember.get(key) : null;
    return {
      ...m,
      has_own_live_invoice: hasOwn,
      own_live_invoice_total: cents != null ? cents / 100 : null,
    };
  });
}

// Marks read (with an autoCleared stamp) every standing alert for this
// estimate whose dedupeKey carries the given prefix — optionally excluding
// one key that is about to be raised/refreshed instead. Same "plain
// update, best-effort" shape as supplies-consumption.js's
// clearMissedDeductionBells / ops-digest.js's resolved stamp — the closest
// existing "resolve a dedupe-keyed notification" convention; there is no
// larger resolve mechanism to build here.
//
// Deliberately NOT scoped to whereNull('read_at') (Codex round-1 P1 on the
// pre-push fix): an alert a human already DISMISSED while the group was
// still diverging must ALSO get the autoCleared stamp once the group
// genuinely resolves — otherwise raiseDivergenceAlert's wasAutoCleared
// check never sees the resolution, and an identical-dates recurrence after
// a plain dismissal + real realignment stays silently dismissed forever.
// COALESCE(read_at, NOW()) never disturbs an existing dismissal timestamp;
// it only sets read_at on a row that was still unread.
async function clearStandingAlerts(conn, prefix, { exceptKey = null } = {}) {
  let q = conn('notifications').where({ recipient_type: 'admin' })
    .whereRaw("metadata->>'dedupeKey' LIKE ?", [`${prefix}%`]);
  if (exceptKey) q = q.whereRaw("metadata->>'dedupeKey' <> ?", [exceptKey]);
  return q.update({
    read_at: conn.raw('COALESCE(read_at, NOW())'),
    metadata: conn.raw("COALESCE(metadata, '{}'::jsonb) || ?::jsonb", [JSON.stringify({ autoCleared: true })]),
  });
}

// Raises (or refreshes) the durable admin alert for this exact diverging
// set — see the module header for the race-safety note. Never touches the
// invoice or any visit row.
async function raiseDivergenceAlert(conn, {
  estimateId, anchor, diverging, invoice, customerId, dedupeKey,
}) {
  // Takes the SAME advisory lock notifyAdmin's own dedupe path takes, and
  // holds it (same connection/transaction) through notifyAdmin's write
  // below — the read and the write below can never straddle a concurrent
  // dismissal (Codex P2).
  await conn.raw('SELECT pg_advisory_xact_lock(hashtext(?))', [`admin:${dedupeKey}`]);
  const baseFingerprint = divergenceStateFingerprint({
    anchor, diverging, invoiceId: invoice?.invoice_id, invoiceTotal: invoice?.total,
  });
  // A standing alert the SWEEP ITSELF auto-cleared (the group looked
  // resolved on a prior tick — clearStandingAlerts' autoCleared stamp) that
  // is diverging again is a genuinely NEW recurrence even when its
  // fingerprint happens to exactly match the pre-clear state (Codex P1:
  // realign, then diverge back onto the SAME date — same fingerprint,
  // same notification content, so plain fingerprint dedupe would silently
  // stay cleared). The resolution stated the problem was gone; its return
  // is new information, never a no-op re-alert. A PLAIN human dismissal
  // (read_at set, never autoCleared) instead keeps the deterministic-
  // fingerprint dedupe: unchanged state stays dismissed. recurrenceGeneration
  // is bumped only on an auto-cleared recurrence, so repeated identical
  // resolve/recur cycles each still produce a distinct dedupeVersion.
  const existing = await conn('notifications').where({ recipient_type: 'admin' })
    .whereRaw("metadata->>'dedupeKey' = ?", [dedupeKey]).first('read_at', 'metadata');
  let existingMeta = existing?.metadata;
  if (typeof existingMeta === 'string') { try { existingMeta = JSON.parse(existingMeta); } catch { existingMeta = null; } }
  const wasAutoCleared = Boolean(existing?.read_at) && existingMeta?.autoCleared === true;
  const priorGeneration = Number(existingMeta?.recurrenceGeneration) || 0;
  const generation = wasAutoCleared ? priorGeneration + 1 : priorGeneration;
  const dedupeVersion = `${baseFingerprint}::g${generation}`;
  const anchorDate = dateOnly(anchor.scheduled_date);
  const detail = diverging.map((d) => `visit ${d.id} now on ${dateOnly(d.scheduled_date)} (was ${anchorDate})`).join('; ');
  const invoiceRef = invoice
    ? `Invoice ${invoice.invoice_number || invoice.invoice_id}.`
    : `Check the first-application invoice for estimate #${estimateId}.`;
  await require('./notification-service').notifyAdmin(
    'billing',
    'First-application invoice may need to be split by hand',
    `Same-trip visits from one estimate landed on different days: ${detail}. The combined first-application invoice still charges for both — split it by hand. ${invoiceRef}`,
    {
      link: invoice ? `/admin/invoices?invoice=${invoice.invoice_id}` : `/admin/estimates/${estimateId}`,
      bell: true,
      metadata: {
        estimateId: String(estimateId),
        divergingSiblingIds: diverging.map((d) => String(d.id)),
        customerId: customerId ? String(customerId) : null,
        // Read back by loadStaleAlertInvoiceIds so an invoice that settles
        // between sweep ticks (and so drops out of loadCandidates' own
        // non-settled scan) is still found and its alert auto-cleared.
        invoiceId: invoice ? String(invoice.invoice_id) : null,
        // An alert we are (re)raising right now is by definition not in the
        // auto-cleared state any more — explicitly cleared here since
        // notifyAdmin's refresh merges onto the OLD metadata, which would
        // otherwise leave a stale autoCleared:true sitting on a reopened
        // alert forever.
        autoCleared: false,
        recurrenceGeneration: generation,
      },
      dedupeKey,
      dedupeVersion,
      refreshOnDedupe: true,
      trx: conn,
    },
  );
}

// Re-derives one candidate's estimate group fresh and acts on the verdict —
// the whole unit a single transaction covers.
async function evaluateCandidate(conn, candidate) {
  const {
    anchor_id: anchorId, customer_id: customerId, source_estimate_id: estimateId,
    invoice_id: invoiceId, invoice_status: invoiceStatus, invoice_number: invoiceNumber,
    invoice_total: invoiceTotal,
    anchor_scheduled_date: anchorScheduledDate, anchor_completed_at: anchorCompletedAt,
    anchor_estimated_price: anchorEstimatedPrice,
  } = candidate;
  const members = await loadGroupMembers(conn, { customerId, sourceEstimateId: estimateId });
  const anchor = members.find((m) => String(m.id) === String(anchorId))
    || {
      id: anchorId, scheduled_date: anchorScheduledDate, completed_at: anchorCompletedAt, estimated_price: anchorEstimatedPrice,
    };
  const verdict = evaluateGroupDivergence({
    anchor, members, invoiceStatus, invoiceTotal,
  });
  const prefix = DEDUPE_PREFIX(estimateId);
  if (verdict.action === 'clear') {
    const cleared = await clearStandingAlerts(conn, prefix);
    return {
      estimateId, action: 'cleared', reason: verdict.reason, cleared,
    };
  }
  const sortedIds = [...new Set(verdict.diverging.map((d) => String(d.id)))].sort();
  const dedupeKey = `${prefix}${sortedIds.join(',')}`;
  // Any OTHER standing alert for this estimate (a different diverging set
  // than the one we're about to raise/refresh) is stale — clear it first.
  await clearStandingAlerts(conn, prefix, { exceptKey: dedupeKey });
  await raiseDivergenceAlert(conn, {
    estimateId,
    anchor,
    diverging: verdict.diverging,
    customerId,
    invoice: invoiceId ? { invoice_id: invoiceId, invoice_number: invoiceNumber, total: invoiceTotal } : null,
    dedupeKey,
  });
  return { estimateId, action: 'alerted', divergingSiblingIds: sortedIds };
}

async function runSweepInner() {
  const candidates = await loadCandidates(db);
  // One representative row per estimate (Codex round-3 P1) — never evaluate
  // a stale/settled invoice candidate and its live replacement as two
  // independent groups for the same estimate.
  const representatives = representativeCandidatesByEstimate(candidates);
  let alerted = 0;
  let cleared = 0;
  let failed = 0;
  for (const candidate of representatives) {
    try {
      const result = await db.transaction((trx) => evaluateCandidate(trx, candidate));
      if (result.action === 'alerted') alerted += 1;
      else if (result.action === 'cleared' && result.cleared) cleared += 1;
    } catch (err) {
      failed += 1;
      logger.error(`[first-application-sibling-split] sweep failed for estimate ${candidate.source_estimate_id}: ${err.message}`);
    }
  }
  if (failed) {
    throw new Error(`${failed} of ${representatives.length} first-application sibling-split group(s) failed this tick — left for the next run`);
  }
  return {
    scanned: candidates.length, alerted, cleared, failed,
  };
}

async function runFirstApplicationSiblingSplitSweep() {
  const { runExclusive } = require('../utils/cron-lock');
  return runExclusive('first-application-sibling-split-sweep', runSweepInner);
}

