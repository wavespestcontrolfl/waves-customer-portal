const { randomUUID } = require('crypto');
const knexFactory = require('knex');
const migration = require('../../models/migrations/20260907000010_lawn_assessments_property_id');
const { etDateString, addETDays } = require('../../utils/datetime-et');

/** Clone definitions only. Every row, FK, lock and teardown is test-owned. */
async function createLawnHistoryDb() {
  const schema = `lawn_history_${randomUUID().replace(/-/g, '')}`;
  const knex = knexFactory({
    client: 'pg', connection: process.env.DATABASE_URL,
    searchPath: [schema], pool: { min: 0, max: 6 },
  });
  await knex.raw('CREATE SCHEMA ??', [schema]);
  for (const table of [
    'customers', 'customer_properties', 'scheduled_services', 'service_records',
    'lawn_assessments', 'lawn_baseline_resets', 'property_preferences', 'system_settings',
    'turf_height_readings', 'lawn_water_intake_snapshots', 'lawn_assessment_photos', 'customer_turf_profiles',
  ]) {
    await knex.raw('CREATE TABLE ??.?? (LIKE public.?? INCLUDING ALL)', [schema, table, table]);
    const columns = await knex(table).columnInfo();
    if (String(columns.id?.defaultValue || '').includes('nextval(')) {
      // LIKE copies serial defaults verbatim. Give this clone its own sequence
      // rather than advancing a sequence belonging to another dev session.
      await knex.raw('ALTER TABLE ??.?? ALTER COLUMN id DROP DEFAULT', [schema, table]);
      await knex.raw('ALTER TABLE ??.?? ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', [schema, table]);
    }
  }
  // CI may already have run the new DDL. Start these owned copies before it so
  // the same real migration is exercised locally and on the fully migrated CI DB.
  for (const table of ['lawn_assessments', 'lawn_baseline_resets']) {
    if (await knex.schema.hasColumn(table, 'property_id')) {
      await knex.schema.alterTable(table, (t) => t.dropColumn('property_id'));
    }
  }
  await migration.up(knex);
  return {
    knex, schema,
    async dispose() { await knex.raw('DROP SCHEMA ?? CASCADE', [schema]); await knex.destroy(); },
  };
}

async function fixture(knex) {
  const customerId = randomUUID();
  const phone = `+1555${String(parseInt(customerId.slice(0, 6), 16) % 10000000).padStart(7, '0')}`;
  await knex('customers').insert({ id: customerId, first_name: 'Lawn fixture', phone });
  const [property] = await knex('customer_properties').insert({
    customer_id: customerId, address_line1: '100 Fixture Street', city: 'Fixture City', zip: '34201', is_primary: true,
  }).returning('*');
  async function visit(offset = -10, changes = {}) {
    const [row] = await knex('scheduled_services').insert({
      customer_id: customerId, property_id: property.id,
      scheduled_date: etDateString(addETDays(new Date(), offset)), service_type: 'Lawn fixture', ...changes,
    }).returning('*');
    return row;
  }
  async function record(visitRow, changes = {}) {
    const [row] = await knex('service_records').insert({
      customer_id: customerId, scheduled_service_id: visitRow?.id || null,
      service_date: visitRow?.scheduled_date || etDateString(), service_type: 'Lawn fixture', ...changes,
    }).returning('*');
    return row;
  }
  async function assessment(visitRow, changes = {}) {
    const [row] = await knex('lawn_assessments').insert({
      customer_id: customerId, service_id: visitRow?.id || null,
      property_id: visitRow?.property_id || null,
      service_date: etDateString(), confirmed_by_tech: true, confirmed_at: new Date(),
      turf_density: 70, weed_suppression: 80, color_health: 70, stress_damage: 80,
      ...changes,
    }).returning('*');
    return row;
  }
  return { customerId, property, visit, record, assessment };
}

module.exports = { createLawnHistoryDb, fixture };
