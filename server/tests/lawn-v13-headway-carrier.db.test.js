// Lawn protocol v13, the Headway take-all pass in 5 gal of water per 1,000 sq ft (migration 20261120140000, owner 2026-11-20),
// through PostgreSQL. Synthetic data only. Skips without DATABASE_URL; CI runs it.
//
// Pinned: up() gives 5 gal to every v13 Headway row of the April and October take-all windows that is not at 5 (2, another value,
// or empty), changes nothing else on it but updated_at, leaves every other row alone, and writes one audit row per protocol it
// changed with each row's old value. The Headway catalog note marks the label's soil-injection quote (30-150 gal) as soil injection
// only and gains the label's spray and handheld line, with one audit row; a note without the unmarked quote is left alone. A second
// run writes nothing; without the audit table up() throws before any write; down() is a no-op, so a rollback never puts an
// over-limit dose back.
const SKIP = !process.env.DATABASE_URL;
const describeDb = SKIP ? describe.skip : describe;

const { createLawnHistoryDb } = require('./helpers/lawn-history-db');
const migration = require('../models/migrations/20261120140000_lawn_v13_headway_carrier_5gal');
const staged = require('../models/migrations/20261005120000_lawn_protocol_v13_staged');

const N = staged.NAMES;
const V13 = staged.V13_VERSION;
const HEADWAY = migration.HEADWAY;
const [APR, OCT] = migration.WINDOWS;
const MAR = 'mar_v13_pre_m_hose';
const MONTH = { [MAR]: 3, [APR]: 4, [OCT]: 10 };
const TABLES = ['products_catalog', 'lawn_protocols', 'lawn_protocol_windows', 'lawn_protocol_products', 'lawn_protocol_audit_log'];
// The note production's Headway row holds (read 2026-11-20), written by the July 2026 backfill.
const SOURCE = 'distributor_label_pdf: https://labelsds.com/images/user_uploads/headway-fungicide-label.pdf';
const OLD_NOTE = `${SOURCE} — "Apply Headway at 1.5-3 fl oz per 1,000 sq ft. Spray carrier volume should fall within 30-150 gallons of water per 1,000 sq ft."`;
const ARTAVIA_NOTE = 'Artavia note, never touched.';
const FIXED_NOTE = `${SOURCE} — soil injection only (a liquid fungicide injector): "Apply Headway at 1.5-3 fl oz per 1,000 sq ft. Spray carrier `
  + `volume should fall within 30-150 gallons of water per 1,000 sq ft."\n\n${migration.NOTE_LINE}`;

// [protocol key, version, grass track, rows as [window, product, carrier]].
const PROTOCOLS = [
  ['fixture_hw_a', V13, 'st_augustine', [[APR, HEADWAY, 2], [OCT, HEADWAY, 2], [APR, N.ART, 2], [MAR, HEADWAY, 2]]],
  // Another value and an empty carrier: both dose over the label at 3 fl oz (an empty one falls back to the rig's carrier).
  ['fixture_hw_b', V13, 'bahia', [[APR, HEADWAY, null], [OCT, HEADWAY, 3]]],
  // Already at 5: nothing to write, so no audit row either.
  ['fixture_hw_c', V13, 'bermuda', [[APR, HEADWAY, 5], [OCT, HEADWAY, 5]]],
  // Not v13: the 2026.06 program.
  ['fixture_hw_old', '2026.06', 'zoysia', [[APR, HEADWAY, 2]]],
];
// What up() changes: [protocol key, window, carrier before].
const TARGETS = [['fixture_hw_a', APR, 2], ['fixture_hw_a', OCT, 2], ['fixture_hw_b', APR, null], ['fixture_hw_b', OCT, 3]];

describeDb('v13 Headway carrier migration through PostgreSQL', () => {
  let owned;
  let knex;

  beforeAll(async () => {
    owned = await createLawnHistoryDb(); knex = owned.knex;
    for (const table of TABLES) {
      await knex.raw('CREATE TABLE ??.?? (LIKE public.?? INCLUDING ALL)', [owned.schema, table, table]);
      const columns = await knex(table).columnInfo();
      if (String(columns.id?.defaultValue || '').includes('nextval(')) {
        await knex.raw('ALTER TABLE ??.?? ALTER COLUMN id DROP DEFAULT', [owned.schema, table]);
        await knex.raw('ALTER TABLE ??.?? ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', [owned.schema, table]);
      }
    }
  }, 60000);
  afterAll(async () => { if (owned) await owned.dispose(); });

  const rows = () => knex('lawn_protocol_products as p')
    .join('lawn_protocol_windows as w', 'p.lawn_protocol_window_id', 'w.id')
    .join('lawn_protocols as l', 'w.lawn_protocol_id', 'l.id')
    .orderBy(['l.protocol_key', 'w.window_key', 'p.product_name'])
    .select('p.*', 'l.protocol_key', 'w.window_key');
  const rowAt = async (key, windowKey) => (await rows()).find((r) => r.protocol_key === key && r.window_key === windowKey && r.product_name === HEADWAY);
  const isTarget = (row) => row.product_name === HEADWAY && TARGETS.some(([key, windowKey]) => row.protocol_key === key && row.window_key === windowKey);
  const ours = () => knex('lawn_protocol_audit_log').where({ action: migration.ACTION }).orderBy('lawn_protocol_id');
  const noteAudit = () => knex('lawn_protocol_audit_log').where({ action: migration.NOTE_ACTION });
  const catalog = () => knex('products_catalog').orderBy('name').select('*');
  const everything = async () => ({ products: await rows(), catalog: await catalog(), audit: await ours(), notes: await noteAudit() });

  async function reset() {
    for (const table of ['lawn_protocol_audit_log', 'lawn_protocol_products', 'lawn_protocol_windows', 'lawn_protocols', 'products_catalog']) await knex(table).del();
    const ids = {};
    for (const [name, note] of [[HEADWAY, OLD_NOTE], [N.ART, ARTAVIA_NOTE]]) {
      const [made] = await knex('products_catalog').insert({ name, category: 'fungicide', formulation: 'liquid', default_rate_per_1000: 3, rate_unit: 'fl oz', active: true, label_source_note: note }).returning('*');
      ids[name] = made.id;
    }
    let sort = 0;
    for (const [key, version, track, specs] of PROTOCOLS) {
      const [protocol] = await knex('lawn_protocols').insert({ protocol_key: key, version, name: 'Fixture', status: 'staged', grass_track: track, region: 'swfl', effective_from: '2000-01-01' }).returning('*');
      const windows = {};
      for (const windowKey of [...new Set(specs.map(([w]) => w))]) {
        [windows[windowKey]] = await knex('lawn_protocol_windows').insert({ lawn_protocol_id: protocol.id, month: MONTH[windowKey], window_key: windowKey, title: windowKey, visit_type: 'granular_production_plus_spots', production_mode: 'spreader_plus_spot_backpack', goal: 'Fixture visit.' }).returning('*');
      }
      for (const [windowKey, name, carrier] of specs) {
        sort += 1;
        await knex('lawn_protocol_products').insert({
          lawn_protocol_window_id: windows[windowKey].id, product_name: name, product_id: ids[name], role: 'fungicide_spot', application_mode: 'spot',
          rate_per_1000: 3, rate_unit: 'fl oz', carrier_gal_per_1000: carrier, default_in_plan: false,
          gates: JSON.stringify({ trigger: `fixture_${windowKey}` }), annual_counter: JSON.stringify({}), mixing: JSON.stringify({}), sort_order: sort,
        });
      }
    }
    const aged = new Date('2026-10-08T21:48:15Z');
    await knex('lawn_protocol_products').update({ updated_at: aged });
    await knex('products_catalog').update({ updated_at: aged });
  }

  describe('up', () => {
    let before;
    beforeAll(async () => { await reset(); before = { products: await rows(), catalog: await catalog() }; await migration.up(knex); });

    test('every v13 Headway take-all row not at 5 gal holds 5, with only updated_at changed beside it', async () => {
      const after = await rows();
      expect(after.filter(isTarget).map((r) => [r.protocol_key, r.window_key, Number(r.carrier_gal_per_1000)]))
        .toEqual(TARGETS.map(([key, windowKey]) => [key, windowKey, 5]));
      for (const row of after.filter(isTarget)) {
        const old = before.products.find((b) => b.id === row.id);
        expect({ ...row, carrier_gal_per_1000: old.carrier_gal_per_1000, updated_at: old.updated_at }).toEqual(old);
        expect(row.updated_at.getTime()).toBeGreaterThan(old.updated_at.getTime());
      }
    });

    test('every other row is untouched: another product, another window, a row already at 5, the old program', async () => {
      expect((await rows()).filter((r) => !isTarget(r))).toEqual(before.products.filter((r) => !isTarget(r)));
    });

    test('one audit row per protocol it changed holds each row\'s carrier before and after; none for a protocol already at 5', async () => {
      const protocols = await knex('lawn_protocols').whereIn('protocol_key', ['fixture_hw_a', 'fixture_hw_b']).select('id', 'protocol_key');
      const audit = await ours();
      expect(audit.map((a) => a.lawn_protocol_id).sort()).toEqual(protocols.map((p) => p.id).sort());
      for (const protocol of protocols) {
        const log = audit.find((a) => a.lawn_protocol_id === protocol.id);
        const moved = await Promise.all(TARGETS.filter(([key]) => key === protocol.protocol_key)
          .map(async ([key, windowKey, carrier]) => ({ rowId: (await rowAt(key, windowKey)).id, windowKey, carrier })));
        expect(log).toMatchObject({ entity_type: 'protocol', entity_id: protocol.id, actor_name: 'migration 20261120140000', changed_fields: ['carrier_gal_per_1000'] });
        expect(log.before_snapshot.rows).toEqual(moved.map(({ rowId, windowKey, carrier }) => ({ rowId, windowKey, carrier_gal_per_1000: carrier })));
        expect(log.after_snapshot.rows).toEqual(moved.map(({ rowId, windowKey }) => ({ rowId, windowKey, carrier_gal_per_1000: 5 })));
        expect(log.metadata).toMatchObject({ migration: migration.MIGRATION, product: HEADWAY });
      }
    });

    test('the Headway note marks the injection quote as soil injection only and gains the spray line, with one audit row; Artavia\'s note stays', async () => {
      const byName = (list, name) => list.find((row) => row.name === name);
      const after = await catalog();
      const headway = byName(after, HEADWAY);
      expect(headway.label_source_note).toBe(FIXED_NOTE);
      // The added line quotes the label's turf spray volume, the handheld limit and the 5 gal spot mix.
      for (const quote of ['"1.0 to 5.0 gallons of water per 1,000 sq ft"', '0.615 fl oz', '"3.0 fl oz ... per 5.0 gallons of water"']) {
        expect(migration.NOTE_LINE).toContain(quote);
      }
      expect(headway.updated_at.getTime()).toBeGreaterThan(byName(before.catalog, HEADWAY).updated_at.getTime());
      expect({ ...headway, label_source_note: OLD_NOTE, updated_at: null }).toEqual({ ...byName(before.catalog, HEADWAY), updated_at: null });
      expect(byName(after, N.ART)).toEqual(byName(before.catalog, N.ART));
      const [log, ...more] = await noteAudit();
      expect(more).toEqual([]);
      expect(log).toMatchObject({
        lawn_protocol_id: null, entity_type: 'catalog', entity_id: headway.id, changed_fields: ['label_source_note'],
        before_snapshot: { label_source_note: OLD_NOTE }, after_snapshot: { label_source_note: FIXED_NOTE },
      });
    });

    test('a second run writes nothing', async () => {
      const once = await everything();
      await migration.up(knex);
      expect(await everything()).toEqual(once);
    });

    test('down() is a no-op: every row keeps 5 gal, the note stays corrected and every audit row stays', async () => {
      const upped = await everything();
      await migration.down(knex);
      expect(await everything()).toEqual(upped);
    });
  });

  test('a catalog row named in another case gets the same note fix, as the July backfill matched LOWER(name)', async () => {
    await reset();
    await knex('products_catalog').where({ name: HEADWAY }).update({ name: 'HEADWAY fungicide' });
    await migration.up(knex);
    expect((await knex('products_catalog').where({ name: 'HEADWAY fungicide' }).first()).label_source_note).toBe(FIXED_NOTE);
    expect(await noteAudit()).toHaveLength(1);
  });

  test('a catalog note without the unmarked injection quote (an office edit) is left as it is, with no audit row', async () => {
    await reset();
    await knex('products_catalog').where({ name: HEADWAY }).update({ label_source_note: 'Office note: 5 gal per 1,000 sq ft from the backpack.' });
    const before = await catalog();
    await migration.up(knex);
    expect(await catalog()).toEqual(before);
    expect(await noteAudit()).toEqual([]);
  });

  test('without lawn_protocol_audit_log, up() throws before any write, so knex never records a correction it did not make', async () => {
    await reset();
    const before = { products: await rows(), catalog: await catalog() };
    await knex.raw('ALTER TABLE ??.lawn_protocol_audit_log RENAME TO lawn_protocol_audit_log_away', [owned.schema]);
    try {
      await expect(migration.up(knex)).rejects.toThrow(/lawn_protocol_audit_log is missing; 4 Headway row\(s\) still need the change/);
      expect(await rows()).toEqual(before.products);
      expect(await catalog()).toEqual(before.catalog);
      // With every row already at 5, the note alone still needs the change, and up() throws before writing it.
      await knex('lawn_protocol_products').where({ product_name: HEADWAY }).update({ carrier_gal_per_1000: 5 });
      await expect(migration.up(knex)).rejects.toThrow(/lawn_protocol_audit_log is missing; 1 Headway catalog note\(s\) still need the change/);
      expect(await catalog()).toEqual(before.catalog);
    } finally {
      await knex.raw('ALTER TABLE ??.lawn_protocol_audit_log_away RENAME TO lawn_protocol_audit_log', [owned.schema]);
    }
  });

  test('with no Headway row, up() writes nothing to the protocol rows', async () => {
    await reset();
    await knex('lawn_protocol_products').where({ product_name: HEADWAY }).del();
    const before = await rows();
    await migration.up(knex);
    expect(await rows()).toEqual(before);
    expect(await ours()).toEqual([]);
  });
});
