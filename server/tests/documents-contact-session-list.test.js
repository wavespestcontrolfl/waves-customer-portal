'use strict';

// GET /api/documents for a contact session (GATE_CONTACT_LOGIN), codex #6363
// r4 P1 + P2: every completed visit's report is listed (a holder's linked
// stored copy does not hide it) and reached ONLY through the authenticated,
// contact-safe PDF route — never the public /report or /api/reports bearers,
// whose pages render the holder's identity — and project reports (public
// bearer only; holder name, email, phone, pay link) are not listed at all.
// The holder's list is unchanged.

process.env.JWT_SECRET = process.env.JWT_SECRET || 'test-jwt-secret';

const mockSession = { contact: null, unauthenticated: false };
jest.mock('../middleware/auth', () => ({
  authenticate: (req, res, next) => {
    if (mockSession.unauthenticated) return res.status(401).json({ error: 'Authentication required' });
    req.customerId = 'cust-1';
    req.customer = { id: 'cust-1', first_name: 'Pat', last_name: 'Owner', contact_role: null };
    if (mockSession.contact) req.contactSession = mockSession.contact;
    next();
  },
}));
jest.mock('../services/logger', () => ({ info: jest.fn(), warn: jest.fn(), error: jest.fn() }));
jest.mock('../services/photos', () => ({ CUSTOMER_DWELL_TTL_SECONDS: 86400, getViewUrl: jest.fn(async () => 'https://cdn/p'), getDownloadUrl: jest.fn() }));
const PRIMARY_SCOPE = { customerId: 'cust-1', enabled: true, multi: true, scoped: true, closed: false, property: { id: 'prop-1', is_primary: true } };
jest.mock('../services/contact-session-projection', () => ({
  ...jest.requireActual('../services/contact-session-projection'),
  contactSessionReportsWithheld: jest.fn(async () => false),
  contactRecordScope: jest.fn(async (req) => (req.contactSession ? PRIMARY_SCOPE : null)),
  scopeContactRecords: jest.fn((q) => q),
}));
jest.mock('../models/db', () => jest.fn());
jest.mock('../services/annual-plan-documents', () => ({
  AnnualPlanLabelsUnavailableError: class AnnualPlanLabelsUnavailableError extends Error {},
  listAnnualPlanDocumentsForCustomer: jest.fn(),
  getAnnualPlanDocumentForCustomer: jest.fn(),
}));
jest.mock('../services/pdf/annual-plan-pdf', () => ({ renderAnnualPlanPdf: jest.fn() }));

const express = require('express');
const db = require('../models/db');
const { scopeContactRecords } = require('../services/contact-session-projection');
const documentsRouter = require('../routes/documents');
const {
  AnnualPlanLabelsUnavailableError,
  listAnnualPlanDocumentsForCustomer,
  getAnnualPlanDocumentForCustomer,
} = require('../services/annual-plan-documents');
const { renderAnnualPlanPdf } = require('../services/pdf/annual-plan-pdf');
const priorAnnualGate = process.env.GATE_ANNUAL_PLAN_DOCUMENTS;
const ANNUAL = {
  id: 'annual_plan_22222222-2222-4222-8222-222222222222',
  documentType: 'annual_summary',
  title: 'Annual plan renewal',
  fileName: 'Annual_Plan_Renewal_current.pdf',
  downloadUrl: '/api/documents/annual-plan/annual_plan_22222222-2222-4222-8222-222222222222',
  isAutoGenerated: true,
  shareable: false,
};

const SERVICES = [
  { id: 'svc-1', service_date: '2026-10-01', service_type: 'Pest Control', report_view_token: 'tok-1', report_template_version: 'service_report_v1', structured_notes: null, technician_name: 'Adam' },
  { id: 'svc-2', service_date: '2026-09-01', service_type: 'Lawn Care', report_view_token: 'tok-2', report_template_version: null, structured_notes: null, technician_name: 'Adam' },
];
// The holder's stored copy of svc-2's report.
const STORED = [{ id: 'doc-1', document_type: 'service_report', title: 'Visit Report', file_name: 'r.pdf', file_size_bytes: 10, uploaded_by: 'admin', linked_service_record_id: 'svc-2', created_at: '2026-09-02', s3_key: 'k', storage_key: 'k' }];
const PROJECTS = [{ id: 'proj-1', project_type: 'termite_treatment', status: 'sent', report_token: 'ptok', sent_at: '2026-08-01', created_at: '2026-07-01', title: 'Termite Treatment' }];

// Every raw predicate the list and count queries apply (the customer-visible
// report filter rides whereRaw).
let whereRawCalls;
function wire() {
  whereRawCalls = [];
  db.mockImplementation((table) => {
    const rows = table === 'service_records' ? SERVICES
      : table === 'customer_documents' ? STORED
      : table.startsWith('projects') ? PROJECTS
      : [];
    const q = {};
    for (const m of ['where', 'whereIn', 'whereNull', 'whereNot', 'orWhereNot', 'whereNotNull', 'orWhere', 'leftJoin', 'select', 'orderBy', 'orderByRaw', 'limit', 'offset']) q[m] = () => q;
    q.whereRaw = (sql) => { if (table === 'service_records') whereRawCalls.push(sql); return q; };
    q.count = () => ({ then: (resolve, reject) => Promise.resolve([{ count: String(rows.length) }]).then(resolve, reject) });
    q.columnInfo = async () => ({});
    q.first = async () => rows[0] || null;
    q.catch = () => q;
    q.then = (resolve, reject) => Promise.resolve(rows).then(resolve, reject);
    return q;
  });
  db.raw = (s) => s;
}

let server; let base;
beforeAll(async () => {
  const app = express();
  app.use('/api/documents', documentsRouter);
  server = app.listen(0);
  await new Promise((resolve) => server.once('listening', resolve));
  base = `http://127.0.0.1:${server.address().port}`;
});
afterAll(async () => {
  await new Promise((resolve) => server.close(resolve));
  if (priorAnnualGate === undefined) delete process.env.GATE_ANNUAL_PLAN_DOCUMENTS;
  else process.env.GATE_ANNUAL_PLAN_DOCUMENTS = priorAnnualGate;
});
beforeEach(() => {
  jest.clearAllMocks();
  mockSession.contact = null;
  mockSession.unauthenticated = false;
  delete process.env.GATE_ANNUAL_PLAN_DOCUMENTS;
  listAnnualPlanDocumentsForCustomer.mockResolvedValue([ANNUAL]);
  getAnnualPlanDocumentForCustomer.mockResolvedValue(ANNUAL);
  renderAnnualPlanPdf.mockResolvedValue(Buffer.from('%PDF-fixture'));
  wire();
});

const list = async () => (await fetch(`${base}/api/documents`)).json();

test('the holder lists the stored copy, the public report links and the project report, as before', async () => {
  const body = await list();
  const reports = body.documents.service_report;
  expect(reports.map((d) => d.id)).toEqual(['doc-1', 'auto_report_svc-1', 'project_proj-1']);
  expect(reports[1]).toMatchObject({ viewUrl: '/report/tok-1', reportToken: 'tok-1', pdfUrl: '/api/reports/tok-1' });
  expect(body.total).toBe(1 + 2 + 1);
});

test('a contact lists every visit report through the authenticated PDF only — no public bearer, no stored copy, no project report', async () => {
  mockSession.contact = { slot: 1, name: 'Sam', phone: '+19415550202', contactRole: '', phoneKey: '9415550202' };
  const body = await list();
  expect(Object.keys(body.documents)).toEqual(['service_report']);
  const reports = body.documents.service_report;
  expect(reports.map((d) => d.id)).toEqual(['auto_report_svc-1', 'auto_report_svc-2']);
  for (const d of reports) {
    expect(d).toMatchObject({ viewUrl: null, reportToken: null, pdfUrl: `/api/documents/service-report/${d.linkedServiceRecordId}`, downloadUrl: `/api/documents/service-report/${d.linkedServiceRecordId}` });
  }
  expect(JSON.stringify(body)).not.toMatch(/tok-1|tok-2|ptok|\/report\//);
  expect(body.total).toBe(2);
  // Both the listed reports AND the total are scoped to the contact's primary property (codex r16 P1, r18 P2).
  expect(scopeContactRecords).toHaveBeenCalledTimes(2);
  for (const call of scopeContactRecords.mock.calls) expect(call[1]).toEqual(PRIMARY_SCOPE);
  // Internal-only typed completions are filtered in SQL on the page query AND
  // the count, so a hidden report neither takes a page slot nor inflates the
  // total (codex r33 P2).
  expect(whereRawCalls).toEqual(Array(2).fill("COALESCE(service_records.structured_notes->>'typedReportDelivery', 'auto_send') = 'auto_send'"));
});

test('the holder\'s page query and count apply the same internal-only filter in SQL', async () => {
  await list();
  expect(whereRawCalls).toEqual(Array(2).fill("COALESCE(service_records.structured_notes->>'typedReportDelivery', 'auto_send') = 'auto_send'"));
});

test('the holder\'s list and total are never run through the contact scope', async () => {
  await list();
  expect(scopeContactRecords).not.toHaveBeenCalled();
});

test('annual summaries are dark by default and add one owner-only document and count when enabled', async () => {
  expect((await list()).documents.annual_summary).toBeUndefined();
  expect(listAnnualPlanDocumentsForCustomer).not.toHaveBeenCalled();
  process.env.GATE_ANNUAL_PLAN_DOCUMENTS = 'true';
  const body = await list();
  expect(body.documents.annual_summary).toEqual([ANNUAL]);
  expect(body.total).toBe(5);
  expect(listAnnualPlanDocumentsForCustomer).toHaveBeenCalledWith('cust-1');
});

test('a failed annual-summary lookup drops only the summaries; reports and the count still return', async () => {
  process.env.GATE_ANNUAL_PLAN_DOCUMENTS = 'true';
  for (const failure of [new AnnualPlanLabelsUnavailableError(), new Error('connection reset')]) {
    listAnnualPlanDocumentsForCustomer.mockRejectedValueOnce(failure);
    const res = await fetch(`${base}/api/documents`);
    expect(res.status).toBe(200);
    const body = await res.json();
    expect(body.documents.annual_summary).toBeUndefined();
    expect(body.documents.service_report.map((d) => d.id)).toEqual(['doc-1', 'auto_report_svc-1', 'project_proj-1']);
    expect(body.total).toBe(4);
  }
});

test('contacts never query or list annual summaries even when the download feature is enabled', async () => {
  process.env.GATE_ANNUAL_PLAN_DOCUMENTS = 'true';
  mockSession.contact = { slot: 1 };
  const body = await list();
  expect(body.documents.annual_summary).toBeUndefined();
  expect(body.total).toBe(2);
  expect(listAnnualPlanDocumentsForCustomer).not.toHaveBeenCalled();
});

test.each(['', 'false', '1'])('annual download gate value %p returns 404 before any record lookup', async (gate) => {
  process.env.GATE_ANNUAL_PLAN_DOCUMENTS = gate;
  const res = await fetch(`${base}${ANNUAL.downloadUrl}`);
  expect(res.status).toBe(404);
  expect(getAnnualPlanDocumentForCustomer).not.toHaveBeenCalled();
  expect(db).not.toHaveBeenCalled();
});

test('annual downloads require authentication and reject contact sessions before lookup', async () => {
  process.env.GATE_ANNUAL_PLAN_DOCUMENTS = 'true';
  mockSession.unauthenticated = true;
  expect((await fetch(`${base}${ANNUAL.downloadUrl}`)).status).toBe(401);
  mockSession.unauthenticated = false;
  mockSession.contact = { slot: 1 };
  expect((await fetch(`${base}${ANNUAL.downloadUrl}`)).status).toBe(404);
  expect(getAnnualPlanDocumentForCustomer).not.toHaveBeenCalled();
  expect(db).not.toHaveBeenCalled();
});

test('malformed and ineligible annual document identifiers have the same generic 404', async () => {
  process.env.GATE_ANNUAL_PLAN_DOCUMENTS = 'true';
  const malformed = await fetch(`${base}/api/documents/annual-plan/annual_plan_invalid`);
  expect(malformed.status).toBe(404);
  expect(getAnnualPlanDocumentForCustomer).not.toHaveBeenCalled();
  getAnnualPlanDocumentForCustomer.mockResolvedValueOnce(null);
  const ineligible = await fetch(`${base}${ANNUAL.downloadUrl}`);
  expect(ineligible.status).toBe(404);
  expect(await ineligible.json()).toEqual(await malformed.json());
  expect(getAnnualPlanDocumentForCustomer).toHaveBeenCalledWith('cust-1', ANNUAL.id);
  expect(renderAnnualPlanPdf).not.toHaveBeenCalled();
});

test('an eligible annual summary downloads as a private PDF and cannot mint a public share link', async () => {
  process.env.GATE_ANNUAL_PLAN_DOCUMENTS = 'true';
  const res = await fetch(`${base}${ANNUAL.downloadUrl}`);
  expect(res.status).toBe(200);
  expect(res.headers.get('content-type')).toMatch(/application\/pdf/);
  expect(res.headers.get('cache-control')).toContain('no-store');
  expect(res.headers.get('content-disposition')).toContain(ANNUAL.fileName);
  expect(await res.text()).toBe('%PDF-fixture');
  expect(renderAnnualPlanPdf).toHaveBeenCalledWith(ANNUAL);
  const share = await fetch(`${base}/api/documents/share/${ANNUAL.id}`, { method: 'POST' });
  expect(share.status).toBe(404);
  expect(db).not.toHaveBeenCalled();
});

test('unclear annual-plan property labels return a retryable response without rendering a PDF', async () => {
  process.env.GATE_ANNUAL_PLAN_DOCUMENTS = 'true';
  getAnnualPlanDocumentForCustomer.mockRejectedValueOnce(new AnnualPlanLabelsUnavailableError());
  expect((await fetch(`${base}${ANNUAL.downloadUrl}`)).status).toBe(503);
  expect(renderAnnualPlanPdf).not.toHaveBeenCalled();
});
