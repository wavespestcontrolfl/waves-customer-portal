// Codex pre-push P0 (x2): a MINT decision (resolveScheduledServiceCharge,
// admin-schedule.js) must tell "definitely no relevant sibling invoice"
// apart from "a lookup failure" and "a terminal/refunded match" — both of
// which completion's own mint refuses to remint over. siblingCoverageForSchedule's
// display-safe wrapper (coveringSiblingInvoice) collapses all three
// non-covered cases to null on purpose (advisory, never toward a false
// "covered"); the verdict function underneath must NOT collapse them the
// same way, so a write caller can refuse instead of bill.
describe('siblingInvoiceCoverageVerdict', () => {
  test('covered — a live sibling invoice', async () => {
    findFirstApplicationInvoiceForEstimateService.mockResolvedValue({
      invoice: { id: 'inv-1', scheduled_service_id: 'svc-pest', status: 'sent', total: 153.6 },
      liveBeside: null,
    });
    expect(await siblingInvoiceCoverageVerdict(LAWN_SVC, {})).toEqual({
      status: 'covered',
      invoice: { id: 'inv-1', scheduled_service_id: 'svc-pest', status: 'sent', total: 153.6 },
    });
  });

  // A working dbConn is required from here on (codex pre-push P0, round
  // 9): a null-invoice verdict now also runs the fail-closed
  // sameTripSiblingHasUnrecognizedLiveInvoice guard, so `{}` is no longer
  // a valid stand-in for the `!inv` branch specifically — fakeDbConn()'s
  // default (no unrecognized invoice) preserves this exact 'none' verdict.
  test('none — no match at all', async () => {
    findFirstApplicationInvoiceForEstimateService.mockResolvedValue({ invoice: null, liveBeside: null });
    expect(await siblingInvoiceCoverageVerdict(LAWN_SVC, fakeDbConn())).toEqual({ status: 'none' });
  });

  test('none — a match naming this visit\'s OWN row (not a sibling)', async () => {
    findFirstApplicationInvoiceForEstimateService.mockResolvedValue({
      invoice: { id: 'inv-1', scheduled_service_id: LAWN_SVC.id, status: 'sent', total: 56.4 },
      liveBeside: null,
    });
    expect(await siblingInvoiceCoverageVerdict(LAWN_SVC, {})).toEqual({ status: 'none' });
  });

  test('needs_review — a terminal/refunded match, carrying any live replacement as liveBeside', async () => {
    findFirstApplicationInvoiceForEstimateService.mockResolvedValue({
      invoice: { id: 'inv-1', scheduled_service_id: 'svc-pest', status: 'refunded', total: 153.6 },
      liveBeside: { id: 'inv-2', scheduled_service_id: 'svc-pest', status: 'sent', total: 153.6 },
    });
    expect(await siblingInvoiceCoverageVerdict(LAWN_SVC, {})).toEqual({
      status: 'needs_review',
      invoice: { id: 'inv-1', scheduled_service_id: 'svc-pest', status: 'refunded', total: 153.6 },
      liveBeside: { id: 'inv-2', scheduled_service_id: 'svc-pest', status: 'sent', total: 153.6 },
    });
  });

  // Codex round-2 P0: the shared lookup deliberately returns a refunded
  // match ahead of any live replacement REGARDLESS of whose row it sits
  // on (no reliable refund-event clock), with the live replacement riding
  // along as `liveBeside`. The own-visit check ("just my own row, not a
  // sibling") must NOT be evaluated before the terminal-status check — an
  // own-visit REFUNDED match discarded as "none" would also discard a
  // live SIBLING invoice riding beside it, letting a write caller mint
  // the acceptance fee for a trip that sibling's live invoice already
  // covers.
  test('needs_review — a REFUNDED match naming this visit\'s OWN row, with a live SIBLING invoice riding as liveBeside', async () => {
    findFirstApplicationInvoiceForEstimateService.mockResolvedValue({
      invoice: { id: 'inv-1', scheduled_service_id: LAWN_SVC.id, status: 'refunded', total: 56.4 },
      liveBeside: { id: 'inv-2', scheduled_service_id: 'svc-pest', status: 'sent', total: 153.6 },
    });
    expect(await siblingInvoiceCoverageVerdict(LAWN_SVC, {})).toEqual({
      status: 'needs_review',
      invoice: { id: 'inv-1', scheduled_service_id: LAWN_SVC.id, status: 'refunded', total: 56.4 },
      liveBeside: { id: 'inv-2', scheduled_service_id: 'svc-pest', status: 'sent', total: 153.6 },
    });
  });

  test('error — the shared lookup throws', async () => {
    findFirstApplicationInvoiceForEstimateService.mockRejectedValue(new Error('db down'));
    expect(await siblingInvoiceCoverageVerdict(LAWN_SVC, {})).toEqual({ status: 'error' });
  });

  // Codex round-6 P1 (pre-push): `noWait` rides through to the shared
  // lookup ONLY when the caller passes it (the schedule mint's own recheck,
  // which already holds the estimate.deposit.ledger lock and must fail
  // fast rather than block into a deadlock against
  // withInvoiceDepositSettlement's invoice-row-then-ledger-lock order). A
  // NOWAIT lock-busy failure is just another lookup failure here.
  test('passes lockRows/noWait through to the shared lookup exactly as given', async () => {
    findFirstApplicationInvoiceForEstimateService.mockResolvedValue({ invoice: null, liveBeside: null });
    const trx = {};
    await siblingInvoiceCoverageVerdict(LAWN_SVC, trx, { lockRows: true, noWait: true });
    expect(findFirstApplicationInvoiceForEstimateService).toHaveBeenCalledWith(
      LAWN_SVC, trx, { lockRows: true, noWait: true },
    );
  });

  test('a NOWAIT lock-busy failure reads as a plain lookup error, not a crash', async () => {
    const busy = new Error('could not obtain lock on row');
    busy.code = '55P03';
    findFirstApplicationInvoiceForEstimateService.mockRejectedValue(busy);
    expect(await siblingInvoiceCoverageVerdict(LAWN_SVC, {}, { lockRows: true, noWait: true }))
      .toEqual({ status: 'error' });
  });

  // Codex pre-push P0 (round 2): the lookup's null-invoice return is NOT
  // always "no relevant match" — it also carries canceledSetupFee when a
  // canceled acceptance invoice included the one-time setup fee with no
  // live replacement. Losing that here would let a write caller mint only
  // the per-visit/per-application charge and silently drop the fee
  // completion itself parks for manual billing instead.
  test('needs_review — a canceled acceptance invoice carrying the setup fee, with no live replacement', async () => {
    findFirstApplicationInvoiceForEstimateService.mockResolvedValue({
      invoice: null,
      liveBeside: null,
      canceledSetupFee: { id: 'inv-3', invoice_number: 'WPC-2026-0400', status: 'canceled' },
    });
    expect(await siblingInvoiceCoverageVerdict(LAWN_SVC, {})).toEqual({
      status: 'needs_review',
      invoice: null,
      canceledSetupFee: { id: 'inv-3', invoice_number: 'WPC-2026-0400', status: 'canceled' },
    });
  });

  test('none — a null invoice with no canceledSetupFee either', async () => {
    findFirstApplicationInvoiceForEstimateService.mockResolvedValue({ invoice: null, liveBeside: null });
    expect(await siblingInvoiceCoverageVerdict(LAWN_SVC, fakeDbConn())).toEqual({ status: 'none' });
  });

  test('coveringSiblingInvoice (the display-safe wrapper) still collapses needs_review/error to null', async () => {
    findFirstApplicationInvoiceForEstimateService.mockResolvedValue({
      invoice: { id: 'inv-1', scheduled_service_id: 'svc-pest', status: 'refunded', total: 153.6 },
      liveBeside: null,
    });
    expect(await coveringSiblingInvoice(LAWN_SVC, {})).toBeNull();
    findFirstApplicationInvoiceForEstimateService.mockRejectedValue(new Error('db down'));
    expect(await coveringSiblingInvoice(LAWN_SVC, {})).toBeNull();
  });

  // Codex pre-push P0 (round 9) — the fail-closed guard itself: a null
  // invoice from the shared lookup is 'needs_review' (never 'none') when a
  // same-trip sibling carries a live invoice the lookup can't recognize
  // (e.g. a Charge Now remint on the reserved sibling after its original
  // combined invoice was voided). Scoped to unpriced/estimate-linked svc
  // shapes only — the reserved (priced) row itself never reaches this
  // function at all (isSiblingCoverageEligibleVisit gates every caller).
  describe('the fail-closed unrecognized-live-sibling-invoice guard', () => {
    test('needs_review with reason sibling_unrecognized_invoice when a same-trip sibling has a live unrecognized invoice', async () => {
      findFirstApplicationInvoiceForEstimateService.mockResolvedValue({ invoice: null, liveBeside: null });
      const dbConn = fakeDbConn({ unrecognizedSiblingInvoice: true });
      expect(await siblingInvoiceCoverageVerdict(LAWN_SVC, dbConn)).toEqual({
        status: 'needs_review', invoice: null, reason: 'sibling_unrecognized_invoice',
      });
    });

    // canceledSetupFee still wins (checked first) — this fix never
    // reclassifies that existing, already fail-closed verdict shape.
    test('canceledSetupFee still takes precedence over the new guard', async () => {
      findFirstApplicationInvoiceForEstimateService.mockResolvedValue({
        invoice: null, liveBeside: null,
        canceledSetupFee: { id: 'inv-3', invoice_number: 'WPC-2026-0400', status: 'canceled' },
      });
      const dbConn = fakeDbConn({ unrecognizedSiblingInvoice: true });
      expect(await siblingInvoiceCoverageVerdict(LAWN_SVC, dbConn)).toEqual({
        status: 'needs_review', invoice: null, canceledSetupFee: { id: 'inv-3', invoice_number: 'WPC-2026-0400', status: 'canceled' },
      });
    });

    // A recognized 'covered' verdict is untouched — the guard only ever
    // runs inside the `!inv` branch, never re-litigating an already-live
    // recognized match.
    test('never overrides an already-recognized "covered" verdict', async () => {
      findFirstApplicationInvoiceForEstimateService.mockResolvedValue({
        invoice: { id: 'inv-1', scheduled_service_id: 'svc-pest', status: 'sent', total: 153.6 },
        liveBeside: null,
      });
      const dbConn = fakeDbConn({ unrecognizedSiblingInvoice: true });
      expect(await siblingInvoiceCoverageVerdict(LAWN_SVC, dbConn)).toEqual({
        status: 'covered', invoice: { id: 'inv-1', scheduled_service_id: 'svc-pest', status: 'sent', total: 153.6 },
      });
    });

    // A query failure inside the guard fails CLOSED — the same way any
    // other lookup failure does — never silently as "no live invoice".
    test('a guard-query failure reads as a plain lookup error, not a silent "none"', async () => {
      findFirstApplicationInvoiceForEstimateService.mockResolvedValue({ invoice: null, liveBeside: null });
      const brokenDbConn = () => { throw new Error('connection lost'); };
      expect(await siblingInvoiceCoverageVerdict(LAWN_SVC, brokenDbConn)).toEqual({ status: 'error' });
    });

    // Owner ruling: "use the in-transaction recheck (lockRows) path too" —
    // the guard's own query takes the SAME forUpdate/noWait it's given,
    // so a concurrent void+remint between the pre-lock check and the
    // locked recheck is caught the same way.
    test('lockRows/noWait ride through to the guard\'s own query', async () => {
      findFirstApplicationInvoiceForEstimateService.mockResolvedValue({ invoice: null, liveBeside: null });
      const invoiceQueryCalls = [];
      const dbConn = fakeDbConn({ unrecognizedSiblingInvoice: true, invoiceQueryCalls });
      const verdict = await siblingInvoiceCoverageVerdict(LAWN_SVC, dbConn, { lockRows: true, noWait: true });
      expect(verdict).toEqual({ status: 'needs_review', invoice: null, reason: 'sibling_unrecognized_invoice' });
      expect(invoiceQueryCalls.some(([method]) => method === 'forUpdate')).toBe(true);
      expect(invoiceQueryCalls.some(([method]) => method === 'noWait')).toBe(true);
    });

    // Without lockRows, the guard's query must NOT take a row lock — a
    // plain read-only schedule-sheet prediction never holds rows.
    test('no forUpdate/noWait on the guard\'s query when lockRows is not requested', async () => {
      findFirstApplicationInvoiceForEstimateService.mockResolvedValue({ invoice: null, liveBeside: null });
      const invoiceQueryCalls = [];
      const dbConn = fakeDbConn({ unrecognizedSiblingInvoice: true, invoiceQueryCalls });
      await siblingInvoiceCoverageVerdict(LAWN_SVC, dbConn);
      expect(invoiceQueryCalls.some(([method]) => method === 'forUpdate')).toBe(false);
    });
  });
});

// Codex pre-push P0 (round 10, owner ruling — symmetric, minimal, narrow +
// fail closed): the OPPOSITE direction from siblingInvoiceCoverageVerdict's
// own fail-closed guard. A PRICED "reserved" row (svc-pest here, mirroring
// the sibling-coverage fixtures above) is otherwise entirely exempt from
// any sibling-coverage question — right for the ordinary case, but blind
// to the one narrow sequence where its own recognized first-application
// invoice was voided while its unpriced sibling (svc-lawn) was separately
// charged in the meantime.
describe('pricedSiblingCoverageVerdict', () => {
  const PEST_SVC = {
    id: 'svc-pest', customer_id: 'cust-1', source_estimate_id: 'est-1', scheduled_date: '2026-09-27', estimated_price: 153.6,
  };
  const RECOGNIZED_VOIDED_INVOICE = {
    id: 'inv-void', status: 'void', title: 'First application',
    notes: 'Auto-generated from accepted estimate #est-1 — customer selected pay per application — first application.',
  };

  test('needs_review with reason sibling_already_invoiced_after_void when BOTH hold', async () => {
    const dbConn = fakeDbConn({ voidedFirstApplicationInvoiceOnRow: RECOGNIZED_VOIDED_INVOICE, unrecognizedSiblingInvoice: true });
    expect(await pricedSiblingCoverageVerdict(PEST_SVC, dbConn)).toEqual({
      status: 'needs_review', reason: 'sibling_already_invoiced_after_void',
    });
  });

  test('none — no voided first-application invoice on this row at all (ordinary priced visit)', async () => {
    const dbConn = fakeDbConn({ voidedFirstApplicationInvoiceOnRow: null, unrecognizedSiblingInvoice: true });
    expect(await pricedSiblingCoverageVerdict(PEST_SVC, dbConn)).toEqual({ status: 'none' });
  });

  test('none — the invoice was voided but the sibling has no live invoice either', async () => {
    const dbConn = fakeDbConn({ voidedFirstApplicationInvoiceOnRow: RECOGNIZED_VOIDED_INVOICE, unrecognizedSiblingInvoice: false });
    expect(await pricedSiblingCoverageVerdict(PEST_SVC, dbConn)).toEqual({ status: 'none' });
  });

  // A terminal invoice on this row that does NOT carry the recognized
  // acceptance-flow notes (an ordinary voided/refunded office invoice) must
  // never trip the guard — no false positive from voiding an unrelated
  // invoice.
  test('none — a voided invoice exists on this row but is not a recognized first-application invoice', async () => {
    const dbConn = fakeDbConn({
      voidedFirstApplicationInvoiceOnRow: { id: 'inv-other', status: 'void', title: 'Ad hoc charge', notes: 'Unrelated' },
      unrecognizedSiblingInvoice: true,
    });
    expect(await pricedSiblingCoverageVerdict(PEST_SVC, dbConn)).toEqual({ status: 'none' });
  });

  test('error — the voided-invoice query fails', async () => {
    const brokenDbConn = () => { throw new Error('connection lost'); };
    expect(await pricedSiblingCoverageVerdict(PEST_SVC, brokenDbConn)).toEqual({ status: 'error' });
  });

  test('error — the sibling-live query fails after a recognized voided invoice is found', async () => {
    const dbConn = (table) => {
      if (table !== 'invoices') throw new Error(`unexpected table: ${table}`);
      const q = { _joined: false };
      q.where = () => q; q.whereNot = () => q; q.whereNull = () => q; q.whereNotIn = () => q;
      q.whereIn = () => q; q.orderBy = () => q; q.forUpdate = () => q; q.noWait = () => q;
      q.join = () => { q._joined = true; return q; };
      q.first = async () => {
        if (q._joined) throw new Error('sibling query connection lost');
        return RECOGNIZED_VOIDED_INVOICE;
      };
      return q;
    };
    expect(await pricedSiblingCoverageVerdict(PEST_SVC, dbConn)).toEqual({ status: 'error' });
  });

  // Owner ruling: "use the in-transaction recheck (lockRows) path too" —
  // rides through to BOTH sub-queries (the voided-invoice check and the
  // sibling-live check).
  test('lockRows/noWait ride through to both underlying queries', async () => {
    const invoiceQueryCalls = [];
    const dbConn = fakeDbConn({
      voidedFirstApplicationInvoiceOnRow: RECOGNIZED_VOIDED_INVOICE, unrecognizedSiblingInvoice: true, invoiceQueryCalls,
    });
    const verdict = await pricedSiblingCoverageVerdict(PEST_SVC, dbConn, { lockRows: true, noWait: true });
    expect(verdict).toEqual({ status: 'needs_review', reason: 'sibling_already_invoiced_after_void' });
    const forUpdateCalls = invoiceQueryCalls.filter(([method]) => method === 'forUpdate');
    const noWaitCalls = invoiceQueryCalls.filter(([method]) => method === 'noWait');
    expect(forUpdateCalls.length).toBeGreaterThanOrEqual(2);
    expect(noWaitCalls.length).toBeGreaterThanOrEqual(2);
  });
});

describe('siblingCoverageForSchedule — the PRICED-row branch (codex pre-push P0, round 10)', () => {
  const PEST_SVC = {
    id: 'svc-pest', customer_id: 'cust-1', source_estimate_id: 'est-1', scheduled_date: '2026-09-27', estimated_price: 153.6,
  };
  const RECOGNIZED_VOIDED_INVOICE = {
    id: 'inv-void', status: 'void', title: 'First application',
    notes: 'Auto-generated from accepted estimate #est-1 — customer selected pay per application — first application.',
  };

  test('surfaces a review verdict with reason sibling_already_invoiced_after_void for a priced row whose invoice was voided after its sibling was charged', async () => {
    const dbConn = fakeDbConn({ voidedFirstApplicationInvoiceOnRow: RECOGNIZED_VOIDED_INVOICE, unrecognizedSiblingInvoice: true });
    const { coverage, prediction } = await siblingCoverageForSchedule({ svc: PEST_SVC, dbConn });
    expect(coverage).toEqual({
      state: 'review', invoiceId: null, invoiceNumber: null, amountDue: null, reason: 'sibling_already_invoiced_after_void',
    });
    expect(prediction).toMatchObject({ kind: 'sibling_needs_review', amount: null, invoiceId: null, invoiceNumber: null });
  });

  // A normal priced visit (no voided combined invoice at all) reads exactly
  // as before this fix — 'none', never pushed into review.
  test('a normal priced visit with no voided combined invoice reads none, unchanged', async () => {
    const dbConn = fakeDbConn({ voidedFirstApplicationInvoiceOnRow: null, unrecognizedSiblingInvoice: true });
    const { coverage, prediction } = await siblingCoverageForSchedule({ svc: PEST_SVC, dbConn });
    expect(coverage.state).toBe('none');
    expect(prediction).toBeNull();
  });

  // A priced visit whose invoice was voided but whose sibling was NEVER
  // separately charged also reads 'none' — nothing to double-bill.
  test('a priced visit whose sibling has no live invoice reads none, unchanged', async () => {
    const dbConn = fakeDbConn({ voidedFirstApplicationInvoiceOnRow: RECOGNIZED_VOIDED_INVOICE, unrecognizedSiblingInvoice: false });
    const { coverage, prediction } = await siblingCoverageForSchedule({ svc: PEST_SVC, dbConn });
    expect(coverage.state).toBe('none');
    expect(prediction).toBeNull();
  });

  test('a query failure surfaces review with reason lookup_failed, never a false none', async () => {
    const brokenDbConn = () => { throw new Error('connection lost'); };
    const { coverage } = await siblingCoverageForSchedule({ svc: PEST_SVC, dbConn: brokenDbConn });
    expect(coverage.state).toBe('review');
    expect(coverage.reason).toBe('lookup_failed');
  });

  // An UNPRICED visit's own verdict path is completely untouched by this
  // branch — isPricedSiblingCoverageEligibleVisit requires hasOwnPrice, so
  // a voided-first-application fixture (only pricedSiblingCoverageVerdict's
  // OWN `.whereIn` query ever reads it) never even gets asked.
  test('an unpriced visit never enters the priced branch at all — the voided-invoice fixture is irrelevant to it', async () => {
    findFirstApplicationInvoiceForEstimateService.mockResolvedValue({ invoice: null, liveBeside: null });
    const dbConn = fakeDbConn({ voidedFirstApplicationInvoiceOnRow: RECOGNIZED_VOIDED_INVOICE, unrecognizedSiblingInvoice: false });
    const { coverage } = await siblingCoverageForSchedule({ svc: LAWN_SVC, dbConn });
    expect(coverage.state).toBe('none');
  });
});
