// Minimal knex-like stand-in: distinguishes the two 'scheduled_services'
// queries the function issues by their `where` shape — a lookup by id
// (the invoice's owning visit) vs. the same-day/estimate members scan.
// `unrecognizedSiblingInvoice` (codex pre-push P0, round 9) backs
// sameTripSiblingHasUnrecognizedLiveInvoice's own `invoices`-table query
// (the fail-closed guard for a same-trip sibling's invoice the notes-based
// lookup can't recognize) — every call site that doesn't pass it defaults
// to "no such invoice", keeping every EXISTING test's verdict unchanged.
// `voidedFirstApplicationInvoiceOnRow` (codex pre-push P0, round 10) backs
// pricedRowFirstApplicationInvoiceVoided's own `.whereIn(status, [...])`
// query (the PRICED-row counterpart) — a THIRD independently controllable
// shape on this same 'invoices' table, distinguished from the joined shape
// by whether `.join` was ever called on this query instance. `invoiceQueryCalls`
// (optional, out param) collects each `.where*` call made against the
// `invoices` query so a test can assert the query is correctly SCOPED
// (same estimate + same trip, excluding svc's own row) without a real
// database.
function fakeDbConn({
  byId = {}, members = [], unrecognizedSiblingInvoice = false, voidedFirstApplicationInvoiceOnRow = null, invoiceQueryCalls = null,
} = {}) {
  return (table) => {
    if (table === 'scheduled_services') {
      return {
        where(cond) {
          if (cond && cond.id !== undefined) {
            return { first: async () => byId[cond.id] || null };
          }
          return {
            whereNull: () => ({
              select: async () => members,
            }),
          };
        },
      };
    }
    if (table === 'invoices') {
      const q = { _joined: false };
      const record = (method) => (...args) => {
        if (method === 'join') q._joined = true;
        invoiceQueryCalls?.push([method, ...args]);
        return q;
      };
      q.join = record('join');
      q.where = record('where');
      q.whereNot = record('whereNot');
      q.whereNull = record('whereNull');
      q.whereNotIn = record('whereNotIn');
      q.whereIn = record('whereIn');
      q.orderBy = record('orderBy');
      q.forUpdate = record('forUpdate');
      q.noWait = record('noWait');
      q.first = async () => {
        if (q._joined) return unrecognizedSiblingInvoice ? { id: 'unrecognized-inv' } : undefined;
        return voidedFirstApplicationInvoiceOnRow;
      };
      return q;
    }
    throw new Error(`unexpected table: ${table}`);
  };
}

