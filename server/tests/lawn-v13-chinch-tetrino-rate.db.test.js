// GATE_LAWN_CHINCH_TETRINO_RATE (owner 2026-10-22) through the real plan engine and PostgreSQL (cloned schema): the v13 May Tetrino
// line is planned at 0.735 fl oz per 1,000 sq ft when the lawn has a chinch area mapped (active, or cleared within 365 days), and the
// one raised rate reaches the plan item, the completion defaults, the yearly-limit read and the note the technician sees. Synthetic
// data only. Skips without DATABASE_URL.
const { createLawnHistoryDb, fixture } = require('./helpers/lawn-history-db');
const { buildPlanForService } = require('../services/waveguard-plan-engine');
const { LAWN_V13_VERSION } = require('../services/lawn-program');
const { etDateString, addETDays } = require('../utils/datetime-et');

const describeDb = process.env.DATABASE_URL ? describe : describe.skip;
jest.setTimeout(60000);
const KEY = 'fixture_v13_lawn_may';
const TET = 'Tetrino Insecticide';
const GATES = ['GATE_LAWN_V13', 'GATE_LAWN_COMPLETION_DEFAULTS', 'GATE_LAWN_PROPERTY_HISTORY', 'GATE_LAWN_SPOT_RULES', 'GATE_LAWN_TREATMENT_GUIDE',
  'GATE_LAWN_TROUBLE_AREAS', 'GATE_LAWN_CHINCH_TETRINO_RATE'];
const NOTE = "Chinch bugs mapped here: Tetrino at the label's high rate, 0.735 fl oz per 1,000 sq ft.";
const day = etDateString(addETDays(new Date(), -1));

describeDb('May Tetrino chinch rate through PostgreSQL', () => {
  const saved = Object.fromEntries(GATES.map((name) => [name, process.env[name]]));
  let owned;
  let knex;

  async function clone(table) {
    await knex.raw('CREATE TABLE ??.?? (LIKE public.?? INCLUDING ALL)', [owned.schema, table, table]);
    const columns = await knex(table).columnInfo();
    if (String(columns.id?.defaultValue || '').includes('nextval(')) {
      await knex.raw('ALTER TABLE ??.?? ALTER COLUMN id DROP DEFAULT', [owned.schema, table]);
      await knex.raw('ALTER TABLE ??.?? ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', [owned.schema, table]);
    }
  }
  const setGates = (on = GATES) => { for (const name of GATES) { if (on.includes(name)) process.env[name] = 'true'; else delete process.env[name]; } };

  beforeAll(async () => {
    owned = await createLawnHistoryDb(); knex = owned.knex;
    for (const table of ['technicians', 'products_catalog', 'product_aliases', 'lawn_protocol_product_substitutions',
      'equipment_systems', 'equipment_calibrations', 'municipality_ordinances', 'property_nutrient_ledger',
      'service_products', 'lawn_protocols', 'lawn_protocol_windows', 'lawn_protocol_products', 'lawn_protocol_gates',
      'lawn_protocol_service_completions', 'lawn_protocol_product_actuals', 'product_limits', 'property_application_history',
      'lawn_trouble_areas']) {
      await clone(table);
    }
    const [tet] = await knex('products_catalog').insert({
      name: TET, category: 'insecticide', product_type: 'insecticide', default_rate_per_1000: 0.367, rate_unit: 'fl oz',
      label_verified_at: new Date(), inventory_on_hand: 1000, inventory_unit: 'fl oz', active: true,
    }).returning('*');
    const [staged] = await knex('lawn_protocols').insert({ protocol_key: KEY, version: LAWN_V13_VERSION, name: 'Fixture v13', status: 'staged', grass_track: 'bermuda', region: 'swfl', effective_from: '2000-01-01' }).returning('*');
    const [window] = await knex('lawn_protocol_windows').insert({ lawn_protocol_id: staged.id, month: 5, window_key: 'may_v13_tetrino_hose', title: 'May', visit_type: 'hose' }).returning('*');
    await knex('lawn_protocol_products').insert({
      lawn_protocol_window_id: window.id, product_id: tet.id, product_name: TET, role: 'insecticide', application_mode: 'broadcast',
      default_in_plan: true, rate_per_1000: 0.367, rate_unit: 'fl oz', gates: JSON.stringify({ sunnyTurfOnly: true, minDistanceFromWaterFt: 25, applyAlone: true }),
    });
    const [equipment] = await knex('equipment_systems').insert({ name: 'Fixture rig', system_type: 'skid', tank_capacity_gal: 110, active: true }).returning('*');
    await knex('equipment_calibrations').insert({ equipment_system_id: equipment.id, carrier_gal_per_1000: 1, active: true });
  }, 90000);
  afterAll(async () => { if (owned) await owned.dispose(); });
  beforeEach(async () => { setGates(); await knex('lawn_trouble_areas').del(); });
  afterEach(() => { for (const name of GATES) { if (saved[name] === undefined) delete process.env[name]; else process.env[name] = saved[name]; } });

  // A May visit at a fresh full-sun lawn of 10,000 sq ft, optionally with mapped areas ({ type, status, clearedDaysAgo }).
  async function mayVisit(areas = []) {
    const f = await fixture(knex);
    await knex('customers').where({ id: f.customerId }).update({ address_line1: f.property.address_line1, city: f.property.city, zip: f.property.zip, state: f.property.state, waveguard_tier: 'Silver' });
    await knex('customer_turf_profiles').insert({ customer_id: f.customerId, active: true, grass_type: 'bermuda', track_key: 'bermuda', lawn_sqft: 10000, sun_exposure: 'full_sun' });
    for (const [index, area] of areas.entries()) {
      const clearedAt = area.status === 'cleared' ? new Date(Date.now() - (area.clearedDaysAgo ?? 10) * 86400000) : null;
      await knex('lawn_trouble_areas').insert({
        customer_id: f.customerId, property_id: f.property.id, place: ['front', 'back', 'left_side', 'right_side'][index], type: area.type, status: area.status || 'active',
        source: 'tech_tap', first_seen_on: day, last_seen_on: day, cleared_at: clearedAt,
      });
    }
    return f.visit(0, { scheduled_date: '2027-05-10' });
  }
  const plan = (visit) => buildPlanForService(visit.id, { db: knex, includeCompletionDefaults: true });
  const tetOf = (list) => list.find((item) => item.product?.name === TET);
  const limitsSpy = () => jest.spyOn(require('../services/application-limits'), 'checkLimits');
  const limitedRate = (spy) => spy.mock.calls.find((call) => call[1] && call[4]?.proposed)?.[4].proposed.ratePer1000;

  test('active chinch, gate on: 0.735 fl oz per 1,000 (7.35 fl oz on 10,000 sq ft) in the plan item, the completion default and the limit read, with the note', async () => {
    const spy = limitsSpy();
    try {
      const result = await plan(await mayVisit([{ type: 'chinch' }]));
      const item = tetOf(result.mixCalculator.items);
      expect(item.mix).toMatchObject({ rateSource: 'protocol_rate', ratePer1000: 0.735, rateUnit: 'fl oz', amountUnit: 'fl oz' });
      expect(item.mix.amount).toBeCloseTo(7.35, 2);
      expect(item.gateNotes).toContainEqual({ key: 'chinchTetrinoRate', severity: 'note', text: NOTE });
      expect(item.raw).toMatch(/^Tetrino Insecticide — 0\.735 fl oz per 1,000 sq ft, sunny turf only.*, chinch bugs mapped$/);
      const defaulted = tetOf(result.completionDefaults.items);
      expect(defaulted.mix.ratePer1000).toBe(0.735);
      expect(defaulted.mix.amount).toBeCloseTo(7.35, 2);
      expect(defaulted.gateNotes).toContainEqual(expect.objectContaining({ key: 'chinchTetrinoRate', text: NOTE }));
      expect(limitedRate(spy)).toBe(0.735);
    } finally { spy.mockRestore(); }
  });

  test('chinch resolved 10 days ago and 364 days ago still raises; 366 days ago does not', async () => {
    for (const [daysAgo, rate] of [[10, 0.735], [364, 0.735], [366, 0.367]]) {
      const result = await plan(await mayVisit([{ type: 'chinch', status: 'cleared', clearedDaysAgo: daysAgo }]));
      expect(tetOf(result.mixCalculator.items).mix.ratePer1000).toBe(rate);
    }
  });

  test.each([
    ['no mapped area', []],
    ['fungus and take-all only', [{ type: 'fungus' }, { type: 'take_all' }]],
    ['other insects only', [{ type: 'other_insect' }]],
  ])('%s: the recipe 0.367 fl oz per 1,000, no note', async (_label, areas) => {
    const spy = limitsSpy();
    try {
      const result = await plan(await mayVisit(areas));
      const item = tetOf(result.mixCalculator.items);
      expect(item.mix.ratePer1000).toBe(0.367);
      expect(item.mix.amount).toBeCloseTo(3.67, 2);
      expect(JSON.stringify(item.gateNotes)).not.toContain('chinchTetrinoRate');
      expect(limitedRate(spy)).toBe(0.367);
    } finally { spy.mockRestore(); }
  });

  test('chinch mapped but the gate is off, or the trouble-areas gate is off: the old plan, byte for byte, no chinch note anywhere', async () => {
    const visit = await mayVisit([{ type: 'chinch' }]);
    setGates(GATES.filter((name) => name !== 'GATE_LAWN_CHINCH_TETRINO_RATE'));
    const gateOff = await plan(visit);
    setGates(GATES.filter((name) => name !== 'GATE_LAWN_TROUBLE_AREAS'));
    const areasOff = await plan(visit);
    for (const result of [gateOff, areasOff]) {
      const item = tetOf(result.mixCalculator.items);
      expect(item.mix.ratePer1000).toBe(0.367);
      expect(item.raw).toMatch(/^Tetrino Insecticide — 0\.367 fl oz per 1,000 sq ft, sunny turf only/);
      expect(JSON.stringify(result)).not.toContain('chinchTetrinoRate');
    }
    // The same visit with the gate off equals the same visit at a lawn whose chinch is not mapped: nothing else moved.
    const unmapped = await plan(await mayVisit([]));
    const strip = (result) => JSON.parse(JSON.stringify(result.mixCalculator.items.map((item) => ({ raw: item.raw, mix: item.mix, gateNotes: item.gateNotes }))));
    expect(strip(gateOff)).toEqual(strip(unmapped));
  });

  test('an archived v13 recipe pinned to a chinch-mapped lawn survives at the raised rate', async () => {
    await knex('lawn_protocols').where({ protocol_key: KEY, version: LAWN_V13_VERSION }).update({ status: 'archived' });
    try {
      const visit = await mayVisit([{ type: 'chinch' }]);
      await knex('scheduled_services').where({ id: visit.id }).update({ lawn_protocol_key: KEY, lawn_protocol_version: LAWN_V13_VERSION, lawn_protocol_window_key: 'may_v13_tetrino_hose' });
      const result = await plan(visit);
      expect(result.propertyGate.blocks.map((block) => block.code)).not.toContain('lawn_archived_recipe_unavailable');
      expect(tetOf(result.mixCalculator.items).mix.ratePer1000).toBe(0.735);
      expect(tetOf(result.completionDefaults.items).mix.ratePer1000).toBe(0.735);
    } finally {
      await knex('lawn_protocols').where({ protocol_key: KEY, version: LAWN_V13_VERSION }).update({ status: 'staged' });
    }
  });

  test('inside a transaction (packet closeout) the plan reads the areas through a savepoint and still raises', async () => {
    const visit = await mayVisit([{ type: 'chinch' }]);
    const result = await knex.transaction((trx) => buildPlanForService(visit.id, { db: trx, includeCompletionDefaults: true }));
    expect(tetOf(result.mixCalculator.items).mix.ratePer1000).toBe(0.735);
  });

  test('a failed trouble-area read: the strict plan throws, the lenient plan keeps the normal rate and still builds', async () => {
    const visit = await mayVisit([{ type: 'chinch' }]);
    const areas = require('../services/lawn-trouble-areas');
    const spy = jest.spyOn(areas, 'hasAreaOfType').mockRejectedValue(Object.assign(new Error('db down'), { code: 'ECONNRESET' }));
    try {
      await expect(plan(visit)).rejects.toThrow('db down');
      await expect(buildPlanForService(visit.id, { db: knex, strict: true, completionDefaultsEnabled: false })).rejects.toThrow('db down');
      const lenient = await buildPlanForService(visit.id, { db: knex, completionDefaultsEnabled: false });
      expect(tetOf(lenient.mixCalculator.items).mix.ratePer1000).toBe(0.367);
      expect(JSON.stringify(lenient)).not.toContain('chinchTetrinoRate');
    } finally { spy.mockRestore(); }
  });
});
