// Lawn protocol v13 summer potassium: a liquid potassium on the August and September hose visits, migration
// 20261029170000, owner 2026-10-29, through PostgreSQL. Synthetic data only. Skips without DATABASE_URL; CI runs it.
//
// Pinned: the catalog row is inserted once (a row that matches in any state makes up throw and write nothing) with NO
// price and NO vendor; every v13 protocol gets one row in each window directly after Nutra-TECH, with the Nutra-TECH
// gates and the North Port key; a later row moves down one place; the plan sizes the program rate per 1,000 sq ft and shows no cost
// while the product is unpriced; down is all or nothing: a full no-op when any v13 protocol is referenced or any inserted row
// was edited, an exact restore otherwise, and the catalog row goes only when unchanged, unpriced and unused.
const SKIP = !process.env.DATABASE_URL;
const describeDb = SKIP ? describe.skip : describe;

const { createLawnHistoryDb } = require('./helpers/lawn-history-db');
const engine = require('../services/waveguard-plan-engine');
const migration = require('../models/migrations/20261029170000_lawn_v13_summer_potassium');
const staged = require('../models/migrations/20261005120000_lawn_protocol_v13_staged');
const { validateRule } = require('../services/service-report/lawn-watering-rule');
const { approvedReportProductFacts } = require('../services/service-report/report-data');

// Every product-specific value is read from the migration's PRODUCT block.
const P = migration.PRODUCT;
const NAME = migration.NAME;
const NUTRA = migration.NUTRA;
const ARTAVIA = 'Artavia 2 SC (Azoxy)';
const ACELEPRYN = 'Acelepryn Insecticide';
const V13 = staged.V13_VERSION;
const KEYS = ['fixture_sum_a', 'fixture_sum_b'];
const AUG = migration.AUG_WINDOW;
const SEP = migration.SEP_WINDOW;
const JUN = 'jun_v13_hose_blackout';
const AUG_GATES = { requiresZeroNP: true, northPortProductWindow: true };
const SEP_GATES = { requiresZeroNP: true, holdForTropicalWatch: true, northPortProductWindow: true };
const CATALOG_TABLES = ['products_catalog', 'product_aliases', 'lawn_protocols', 'lawn_protocol_windows', 'lawn_protocol_products',
  'lawn_protocol_audit_log', 'lawn_protocol_service_completions', 'product_limits'];
const PRICES = ['best_price', 'best_vendor', 'cost_per_unit', 'cost_unit', 'best_vendor_pricing_id', 'best_price_amount_cached'];

describeDb('v13 summer potassium migration through PostgreSQL', () => {
  let owned;
  let knex;
  const ids = {};

  beforeAll(async () => {
    owned = await createLawnHistoryDb(); knex = owned.knex;
    for (const table of [...CATALOG_TABLES, 'service_products']) {
      await knex.raw('CREATE TABLE ??.?? (LIKE public.?? INCLUDING ALL)', [owned.schema, table, table]);
      const columns = await knex(table).columnInfo();
      if (String(columns.id?.defaultValue || '').includes('nextval(')) {
        await knex.raw('ALTER TABLE ??.?? ALTER COLUMN id DROP DEFAULT', [owned.schema, table]);
        await knex.raw('ALTER TABLE ??.?? ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', [owned.schema, table]);
      }
    }
    // LIKE copies no foreign keys; the product reference check reads them.
    await knex.raw('ALTER TABLE ??.product_limits ADD CONSTRAINT fixture_limits_product FOREIGN KEY (product_id) REFERENCES ??.products_catalog (id)', [owned.schema, owned.schema]);
    await knex.raw('ALTER TABLE ??.service_products ADD CONSTRAINT fixture_sp_product FOREIGN KEY (product_id) REFERENCES ??.products_catalog (id) ON DELETE SET NULL', [owned.schema, owned.schema]);
    await knex.raw('ALTER TABLE ??.lawn_protocol_audit_log ALTER COLUMN lawn_protocol_id DROP NOT NULL', [owned.schema]).catch(() => {});
  }, 60000);
  afterAll(async () => { if (owned) await owned.dispose(); });

  const newRow = () => knex('products_catalog').where({ name: NAME }).first();
  const rowsIn = (windowKey, name) => knex('lawn_protocol_products as p')
    .join('lawn_protocol_windows as w', 'p.lawn_protocol_window_id', 'w.id')
    .join('lawn_protocols as l', 'w.lawn_protocol_id', 'l.id')
    .where({ 'w.window_key': windowKey, 'l.version': V13, ...(name ? { 'p.product_name': name } : {}) })
    .orderBy(['l.protocol_key', 'p.sort_order']).select('p.*', 'l.protocol_key');
  const windowOrder = async (key, windowKey) => (await rowsIn(windowKey)).filter((r) => r.protocol_key === key).map((r) => r.product_name);
  const ours = () => knex('lawn_protocol_audit_log').whereIn('action', [migration.ACTION, migration.CATALOG_ACTION]);
  const strip = (rows) => rows.map(({ updated_at: _u, ...rest }) => rest);
  const snapshot = async () => ({
    products: strip(await knex('lawn_protocol_products').orderBy('id')),
    catalog: strip(await knex('products_catalog').orderBy('id')),
    audit: (await knex('lawn_protocol_audit_log').orderBy('id')).map(({ id: _i, created_at: _c, ...rest }) => rest),
  });

  // A clean fixture: two v13 protocols with the June, August and September windows as the staged migration leaves them.
  async function reset() {
    for (const table of ['service_products', 'product_limits', 'lawn_protocol_audit_log', 'lawn_protocol_products', 'lawn_protocol_windows',
      'lawn_protocol_service_completions', 'lawn_protocols', 'product_aliases', 'products_catalog']) await knex(table).del();
    await knex('scheduled_services').update({ lawn_protocol_key: null, lawn_protocol_version: null });
    const [nutra] = await knex('products_catalog').insert({ name: NUTRA, category: 'fertilizer', formulation: 'liquid', default_rate_per_1000: 12, rate_unit: 'fl oz', active: true }).returning('*');
    ids.nutra = nutra.id;
    for (const key of KEYS) {
      await knex('lawn_protocols').insert({ protocol_key: key, version: '2026.06', name: 'Fixture old', status: 'active', grass_track: 'bermuda', region: 'swfl' });
      const [protocol] = await knex('lawn_protocols').insert({ protocol_key: key, version: V13, name: 'Fixture v13', status: 'staged', grass_track: 'bermuda', region: 'swfl', effective_from: '2000-01-01' }).returning('*');
      let sort = key === KEYS[0] ? 10 : 50;
      for (const [month, windowKey, nutraGates, spots] of [[6, JUN, { requiresZeroNP: true, paleTurfRate: '16 fl oz', northPortProductWindow: true }, []], [8, AUG, AUG_GATES, [ARTAVIA, ACELEPRYN]], [9, SEP, SEP_GATES, [ARTAVIA, ACELEPRYN]]]) {
        const [window] = await knex('lawn_protocol_windows').insert({ lawn_protocol_id: protocol.id, month, window_key: windowKey, title: windowKey, visit_type: 'blackout_liquid_production_plus_spots', production_mode: 'main_reel_plus_spot_backpack', goal: 'Fixture hose visit.' }).returning('*');
        const rows = [{ product_name: NUTRA, product_id: nutra.id, role: 'micronutrients', application_mode: 'broadcast', rate_per_1000: 12, default_in_plan: true, gates: nutraGates }]
          .concat(spots.map((product_name) => ({ product_name, product_id: null, role: 'fungicide_spot', application_mode: 'spot', rate_per_1000: null, default_in_plan: false, gates: { trigger: 'fixture' } })));
        for (const row of rows) {
          sort += 1;
          await knex('lawn_protocol_products').insert({ lawn_protocol_window_id: window.id, rate_unit: 'fl oz', carrier_gal_per_1000: 1, sort_order: sort, ...row, gates: JSON.stringify(row.gates) });
        }
      }
    }
  }

  // A visit pinned to a v13 protocol (the references down() refuses to roll back over).
  async function pin(key) {
    const { fixture } = require('./helpers/lawn-history-db');
    const f = await fixture(knex);
    const row = await f.visit(1, {});
    await knex('scheduled_services').where({ id: row.id }).update({ lawn_protocol_key: key, lawn_protocol_version: V13 });
  }

  describe('fresh path: the catalog has no row for the product', () => {
    beforeAll(async () => { await reset(); await migration.up(knex); });

    test('one catalog row is inserted, with no price field and no vendor, pending pricing, and approved for the report', async () => {
      const rows = await knex('products_catalog').where({ name: NAME });
      expect(rows).toHaveLength(1);
      const row = rows[0];
      expect(row).toMatchObject({
        category: 'fertilizer', product_type: 'fertilizer', formulation: 'liquid', container_size: P.containerSize, rate_unit: 'fl_oz', inventory_unit: 'fl_oz',
        active: true, needs_pricing: true, content_status: 'draft', customer_visibility: 'internal_only', approved_for_service_report: true,
        public_summary: migration.SUMMARY, service_report_summary: migration.SUMMARY, customer_precaution_summary: migration.PRECAUTION,
        label_url: P.labelUrl, label_source_note: P.labelSourceNote, compatibility_notes: P.compatibilityNote,
        siteone_sku: P.siteoneSku, signal_word: P.signalWord, ppe_text: P.ppeText, display_name: P.displayName,
      });
      expect([row.analysis_n, row.analysis_p, row.analysis_k, row.default_rate_per_1000, row.min_label_rate_per_1000, row.max_label_rate_per_1000, row.unit_size_oz].map(Number)).toEqual([0, 0, P.analysisK, P.rate, P.minLabel, P.maxLabel, P.unitSizeOz]);
      expect(PRICES.map((column) => row[column])).toEqual([null, null, null, null, null, null]);
      expect(row.post_application_watering).toEqual(migration.WATERING_RULE);
      expect(validateRule(row.post_application_watering).valid).toBe(true);
    });

    test('the stored row freezes into report facts as a fertilizer with no watering change', async () => {
      const facts = approvedReportProductFacts(await newRow());
      expect(facts).toMatchObject({ productType: 'fertilizer', serviceReportSummary: migration.SUMMARY, precautionSummary: migration.PRECAUTION });
      expect(facts.wateringRule).toMatchObject({ mode: 'none', source: 'owner' });
    });

    test('every v13 protocol gets one row in August and one in September, linked, with the Nutra-TECH gates plus the North Port key', async () => {
      const row = await newRow();
      for (const [windowKey, gates] of [[AUG, AUG_GATES], [SEP, SEP_GATES]]) {
        const rows = await rowsIn(windowKey, NAME);
        expect(rows).toHaveLength(KEYS.length);
        for (const made of rows) {
          expect(made).toMatchObject({ product_id: row.id, role: 'potassium', application_mode: 'broadcast', rate_unit: P.rateUnit, default_in_plan: true, gates, annual_counter: {}, mixing: {}, report_copy: { role: 'potassium' } });
          expect([made.rate_per_1000, made.carrier_gal_per_1000].map(Number)).toEqual([P.rate, 1]);
        }
      }
      expect(await rowsIn(JUN, NAME)).toEqual([]);
    });

    test('the row sits directly after Nutra-TECH and the rows after it moved down one place, with no tie in a window', async () => {
      for (const key of KEYS) {
        for (const windowKey of [AUG, SEP]) {
          expect(await windowOrder(key, windowKey)).toEqual([NUTRA, NAME, ARTAVIA, ACELEPRYN]);
          const places = (await rowsIn(windowKey)).filter((r) => r.protocol_key === key).map((r) => r.sort_order);
          expect(new Set(places).size).toBe(places.length);
        }
      }
      // The June window and the Nutra-TECH rows are exactly as they were.
      expect(await windowOrder(KEYS[0], JUN)).toEqual([NUTRA]);
      for (const nutra of await rowsIn(JUN, NUTRA)) expect(nutra.gates).toEqual({ requiresZeroNP: true, paleTurfRate: '16 fl oz', northPortProductWindow: true });
    });

    test('the plan sizes the program rate per 1,000 sq ft and the unpriced product has no cost', async () => {
      const product = await newRow();
      const [aug] = await rowsIn(AUG, NAME);
      const mix = engine.calculateProductAmount({
        product, lawnSqft: 10000, areaFactor: 1, ...engine.v13RateOptions({ ratePer1000: aug.rate_per_1000, rateUnit: aug.rate_unit, gates: aug.gates }),
      });
      expect(mix).toMatchObject({ rateSource: 'protocol_rate', materialCost: null, materialCostSource: null });
      expect(Number(mix.ratePer1000)).toBe(P.rate);
      expect(mix.amount).toBeCloseTo(P.rate * 10, 3);
      const summary = engine.summarizeMaterialCost([{ selected: true, product, mix }]);
      expect(summary).toMatchObject({ pricedLineCount: 0, total: 0, missingPriceCount: 1, source: 'unavailable' });
    });

    test('North Port holds the row (not selected, no amount); another city does not', async () => {
      const product = await newRow();
      const rows = new Map(await Promise.all((await rowsIn(AUG, NAME)).slice(0, 1).map(async (r) => [String(product.id), r])));
      const items = [{ product, selected: true }];
      expect(engine.holdNorthPortProducts(items, rows, 'North Port')[0]).toMatchObject({ selected: false, selectionReason: 'north_port_product_window' });
      expect(engine.holdNorthPortProducts(items, rows, 'Parrish')).toEqual(items);
    });

    test('audit: one row per protocol with the rows before and after, and one catalog row naming the inserted product', async () => {
      const protocolLogs = await knex('lawn_protocol_audit_log').where({ action: migration.ACTION });
      expect(protocolLogs).toHaveLength(KEYS.length);
      const productId = (await newRow()).id;
      for (const log of protocolLogs) {
        const { rows, shifted } = log.after_snapshot;
        expect(rows.map((r) => r.windowKey).sort()).toEqual([AUG, SEP]);
        expect(rows[0].row).toMatchObject({ product_name: NAME, product_id: productId, role: 'potassium', rate_per_1000: P.rate });
        expect(shifted).toHaveLength(4);
        expect(log.before_snapshot.shifted).toHaveLength(4);
      }
      const catalogLogs = await knex('lawn_protocol_audit_log').where({ action: migration.CATALOG_ACTION });
      expect(catalogLogs).toHaveLength(1);
      expect(catalogLogs[0].lawn_protocol_id).toBeNull();
      expect(catalogLogs[0].after_snapshot).toMatchObject({ productId });
      expect(catalogLogs[0].after_snapshot.inserted).toMatchObject({ name: NAME, ...migration.INSERT_DEFAULTS });
      for (const action of [migration.ACTION, migration.CATALOG_ACTION]) expect(action.length).toBeLessThanOrEqual(96);
    });
  });

  describe('a catalog row that already matches, in ANY state: up throws and writes nothing', () => {
    beforeEach(async () => { await reset(); });
    const GOOD = { name: NAME, category: 'fertilizer', active: true, analysis_n: 0, analysis_p: 0, analysis_k: P.analysisK };
    const everything = async () => ({ catalog: strip(await knex('products_catalog').orderBy('id')), products: strip(await knex('lawn_protocol_products').orderBy('id')), audit: await knex('lawn_protocol_audit_log') });

    test.each([
      ['a correct active row', {}],
      ['an inactive row', { active: false }],
      ['an active-unset row', { active: null }],
      ['analysis_k 0', { analysis_k: 0 }],
      ['a bare name-only row', { analysis_n: null, analysis_p: null, analysis_k: null }],
    ])('%s: throws, nothing linked, nothing changed, no audit row', async (_label, change) => {
      await knex('products_catalog').insert({ ...GOOD, ...change });
      const before = await everything();
      await expect(migration.up(knex)).rejects.toThrow(/already exists; this migration only inserts/);
      expect(await everything()).toEqual(before);
      expect(await rowsIn(AUG, NAME)).toEqual([]);
    });

    test('an alias-only match (even a correct row under another name) throws', async () => {
      const [other] = await knex('products_catalog').insert({ ...GOOD, name: 'Some Other Liquid Potassium' }).returning('*');
      await knex('product_aliases').insert({ product_id: other.id, alias_name: NAME });
      const before = await everything();
      await expect(migration.up(knex)).rejects.toThrow(/already exists/);
      expect(await everything()).toEqual(before);
    });

    test('a row whose name differs only in case or spacing still throws', async () => {
      await knex('products_catalog').insert({ ...GOOD, name: NAME.toUpperCase().replace(/ /g, '  ') });
      await expect(migration.up(knex)).rejects.toThrow(/already exists/);
    });

    test('a failed up leaves the database as it was, and a second try after the row is removed inserts normally', async () => {
      const [stray] = await knex('products_catalog').insert({ ...GOOD, active: false }).returning('*');
      await expect(migration.up(knex)).rejects.toThrow();
      await knex('products_catalog').where({ id: stray.id }).del();
      await migration.up(knex);
      expect((await rowsIn(AUG, NAME)).length).toBe(KEYS.length);
    });
  });

  describe('re-running', () => {
    beforeEach(async () => { await reset(); });

    test('after a rollback that did nothing, the migration finds its own row and carries on without a second insert or a throw', async () => {
      await migration.up(knex);
      const once = await snapshot();
      await pin(KEYS[0]);
      await migration.down(knex); // a no-op: a visit references v13
      expect(await snapshot()).toEqual(once);
      await migration.up(knex);
      expect(await snapshot()).toEqual(once);
    });

    test('a window that already has the product is skipped', async () => {
      await migration.up(knex);
      const once = await snapshot();
      await knex('lawn_protocol_audit_log').where({ action: migration.ACTION }).del();
      await migration.up(knex);
      expect((await snapshot()).products).toEqual(once.products);
    });
  });

  describe('down: all or nothing', () => {
    beforeEach(async () => { await reset(); });

    test('clean up then down is the starting state exactly; up again is the first up (new catalog id aside)', async () => {
      const start = await snapshot();
      await migration.up(knex);
      const upped = await snapshot();
      await migration.down(knex);
      expect(await snapshot()).toEqual(start);
      await migration.up(knex);
      const again = await snapshot();
      // A second insert gets its own id, product link and created_at; everything else must match the first up.
      const unlinked = (rows) => rows.map(({ id: _i, product_id: _p, created_at: _c, ...rest }) => rest).sort((x, y) => `${x.lawn_protocol_window_id}${x.sort_order}`.localeCompare(`${y.lawn_protocol_window_id}${y.sort_order}`));
      expect(unlinked(again.products.filter((p) => p.product_name === NAME))).toEqual(unlinked(upped.products.filter((p) => p.product_name === NAME)));
      expect(await ours()).toHaveLength(KEYS.length + 1);
    });

    test('a visit pinned to ANY v13 protocol makes down a full no-op: every row, the catalog row and every audit row stay', async () => {
      await migration.up(knex);
      const upped = await snapshot();
      await pin(KEYS[0]); // pinned to one protocol only: the other protocol is NOT reverted either
      await migration.down(knex);
      expect(await snapshot()).toEqual(upped);
      expect((await rowsIn(AUG, NAME)).length).toBe(KEYS.length);
    });

    test('a completion that references a v13 protocol makes down a full no-op', async () => {
      await migration.up(knex);
      const upped = await snapshot();
      const [protocol] = await knex('lawn_protocols').where({ version: V13, protocol_key: KEYS[1] });
      const completionColumns = await knex('lawn_protocol_service_completions').columnInfo();
      const row = { lawn_protocol_id: protocol.id, protocol_key: KEYS[1], protocol_version: V13 };
      for (const [column, info] of Object.entries(completionColumns)) {
        if (column in row || column === 'id' || info.nullable || info.defaultValue != null) continue;
        row[column] = info.type.includes('uuid') ? require('crypto').randomUUID() : info.type.includes('int') ? 1 : info.type.includes('timestamp') ? new Date() : info.type === 'date' ? '2027-08-12' : info.type.includes('json') ? '{}' : 'fixture';
      }
      await knex('lawn_protocol_service_completions').insert(row);
      await migration.down(knex);
      expect(await snapshot()).toEqual(upped);
    });

    test.each([
      ['renamed', () => ({ product_name: 'Fixture renamed by staff' })],
      ['re-linked to another product', () => ({ product_id: ids.nutra })],
      ['re-rated', () => ({ rate_per_1000: P.rate + 1 })],
      ['re-gated', (a) => ({ gates: JSON.stringify({ ...a.gates, targetN: '1 lb N/1000' }) })],
      ['stripped of its North Port key', () => ({ gates: JSON.stringify({ requiresZeroNP: true }) })],
      ['moved', () => ({ sort_order: 999 })],
      ['switched off the default', () => ({ default_in_plan: false })],
    ])('one inserted row %s by staff makes down a full no-op: the other protocol is NOT reverted, the catalog row stays', async (_label, change) => {
      await migration.up(knex);
      const [a] = await rowsIn(AUG, NAME);
      await knex('lawn_protocol_products').where({ id: a.id }).update(change(a));
      const edited = await snapshot();
      await migration.down(knex);
      expect(await snapshot()).toEqual(edited);
      expect(await newRow()).toBeTruthy();
    });

    test('an inserted row staff deleted makes down a full no-op', async () => {
      await migration.up(knex);
      const [a] = await rowsIn(SEP, NAME);
      await knex('lawn_protocol_products').where({ id: a.id }).del();
      const edited = await snapshot();
      await migration.down(knex);
      expect(await snapshot()).toEqual(edited);
    });

    test('a moved row staff changed again keeps its own place; the rest go back', async () => {
      await migration.up(knex);
      const [artavia] = (await rowsIn(AUG, ARTAVIA)).filter((r) => r.protocol_key === KEYS[0]);
      await knex('lawn_protocol_products').where({ id: artavia.id }).update({ sort_order: 777 });
      await migration.down(knex);
      expect(await rowsIn(AUG, NAME)).toEqual([]);
      expect((await knex('lawn_protocol_products').where({ id: artavia.id }).first()).sort_order).toBe(777);
      expect(await windowOrder(KEYS[1], AUG)).toEqual([NUTRA, ARTAVIA, ACELEPRYN]);
    });

    test.each([
      ['priced', { best_price: 41 }],
      ['marked priced', { needs_pricing: false }],
      ['published', { content_status: 'approved_for_portal' }],
      ['made public', { customer_visibility: 'public' }],
      ['re-rated', { default_rate_per_1000: P.rate + 1 }],
      ['given a stray analysis', { analysis_n: 3 }],
    ])('a catalog row staff %s is kept with its audit row; the staged rows still go, and up() runs again', async (_label, change) => {
      await migration.up(knex);
      await knex('products_catalog').where({ name: NAME }).update(change);
      await migration.down(knex);
      expect(await rowsIn(AUG, NAME)).toEqual([]);
      expect(await rowsIn(SEP, NAME)).toEqual([]);
      expect(await newRow()).toBeTruthy();
      // The catalog audit row stays with the kept row, so a later up() knows the row is its own.
      expect((await ours()).map((log) => log.action)).toEqual([migration.CATALOG_ACTION]);
      await migration.up(knex);
      expect(await knex('products_catalog').where({ name: NAME })).toHaveLength(1);
      expect((await rowsIn(AUG, NAME)).length).toBe(KEYS.length);
    });

    test('a catalog row something references (an application limit) is kept; the staged rows still go', async () => {
      await migration.up(knex);
      const product = await newRow();
      await knex('product_limits').insert({ product_id: product.id, limit_type: 'annual_max_apps', limit_value: 2, limit_unit: 'applications', severity: 'warning' });
      await migration.down(knex);
      expect(await rowsIn(AUG, NAME)).toEqual([]);
      expect(await newRow()).toBeTruthy();
      expect((await ours()).map((log) => log.action)).toEqual([migration.CATALOG_ACTION]);
      await migration.up(knex);
      expect(await knex('products_catalog').where({ name: NAME })).toHaveLength(1);
    });
  });

  describe('protocols the migration skips', () => {
    beforeEach(async () => { await reset(); });

    test('a window with no Nutra-TECH row is skipped (the catalog row is still inserted); without a v13 protocol nothing is written', async () => {
      await knex('lawn_protocol_products').where({ product_name: NUTRA }).whereIn('lawn_protocol_window_id', knex('lawn_protocol_windows').where({ window_key: AUG }).select('id')).del();
      await migration.up(knex);
      expect(await rowsIn(AUG, NAME)).toEqual([]);
      expect((await rowsIn(SEP, NAME)).length).toBe(KEYS.length);
      await reset();
      await knex('lawn_protocol_audit_log').del();
      await knex('lawn_protocol_products').del();
      await knex('lawn_protocol_windows').del();
      await knex('lawn_protocols').where({ version: V13 }).del();
      const before = await snapshot();
      await migration.up(knex);
      expect(await snapshot()).toEqual(before);
    });
  });
});
