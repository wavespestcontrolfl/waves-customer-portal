// Lawn protocol v13 fungus prevention (gray leaf spot prevention in May, large patch spring pass in February), migration
// 20261101200000, owner 2026-11-01, through PostgreSQL. Synthetic data only. Skips without DATABASE_URL; CI runs it.
//
// Pinned: the rows are stored as the spec says (jsonb gates and counter, linked to the template row's catalog id, spot rows never in
// the plan by default); they are appended (no existing row changes); the treatment guide never offers the February spring pass as its
// fungus card and leaves May's first fungicide row first; down is all or nothing: a full no-op when any v13 protocol is referenced or any
// inserted row was edited or removed, an exact restore otherwise.
const SKIP = !process.env.DATABASE_URL;
const describeDb = SKIP ? describe.skip : describe;

const { createLawnHistoryDb } = require('./helpers/lawn-history-db');
const { pickAddOns } = require('../services/lawn-treatment-guide');
const migration = require('../models/migrations/20261101200000_lawn_v13_fungus_prevention');
const staged = require('../models/migrations/20261005120000_lawn_protocol_v13_staged');

const N = staged.NAMES;
const W = migration.WINDOWS;
const V13 = staged.V13_VERSION;
const KEYS = [['fixture_fung_a', 'st_augustine'], ['fixture_fung_b', 'bermuda'], ['fixture_fung_c', 'bahia']];
const TABLES = ['products_catalog', 'lawn_protocols', 'lawn_protocol_windows', 'lawn_protocol_products', 'lawn_protocol_audit_log', 'lawn_protocol_service_completions'];

// What each window holds before the migration (name, role, mode, default_in_plan, gates, annual_counter).
const CEL_GATES = { stressGate: true, annualCounter: 'celsius_oz_per_1000', annualMaxApps: 2 };
const CEL_COUNTER = { counter: 'celsius_oz_per_1000', maxApplications: 2 };
const BEFORE = {
  [W.FEB]: [[N.F24, 'nutrition', 'broadcast', true, {}, {}], [N.CEL, 'post_emergent_spot', 'spot', false, CEL_GATES, CEL_COUNTER]],
  [W.MAY]: [
    [N.TET, 'insecticide', 'broadcast', true, {}, {}], [N.DSP, 'wetting_agent_spot', 'spot', false, { trigger: 'dry_spots', noWaterIn: true }, {}],
    [N.VEL, 'fungicide_spot', 'spot', false, { trigger: 'fairy_ring_dollar_spot_rust_leaf_spot' }, {}],
  ],
  [W.JUN]: [[N.NT, 'micronutrients', 'broadcast', true, {}, {}], [N.ART, 'fungicide_spot', 'spot', false, { trigger: 'gray_leaf_spot_pythium_root_rot' }, {}]],
  [W.NOV]: [[N.F24, 'nutrition', 'broadcast', true, {}, {}], [N.VEL, 'fungicide_spot', 'spot', false, { trigger: 'mapped_large_patch' }, {}]],
};
const MONTH = { [W.FEB]: 2, [W.MAY]: 5, [W.JUN]: 6, [W.NOV]: 11 };

describeDb('v13 fungus prevention migration through PostgreSQL', () => {
  let owned;
  let knex;
  const catalog = {};

  beforeAll(async () => {
    owned = await createLawnHistoryDb(); knex = owned.knex;
    for (const table of TABLES) {
      await knex.raw('CREATE TABLE ??.?? (LIKE public.?? INCLUDING ALL)', [owned.schema, table, table]);
      const columns = await knex(table).columnInfo();
      if (String(columns.id?.defaultValue || '').includes('nextval(')) {
        await knex.raw('ALTER TABLE ??.?? ALTER COLUMN id DROP DEFAULT', [owned.schema, table]);
        await knex.raw('ALTER TABLE ??.?? ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', [owned.schema, table]);
      }
    }
    await knex.raw('ALTER TABLE ??.lawn_protocol_audit_log ALTER COLUMN lawn_protocol_id DROP NOT NULL', [owned.schema]).catch(() => {});
  }, 60000);
  afterAll(async () => { if (owned) await owned.dispose(); });

  const rowsIn = (windowKey, name) => knex('lawn_protocol_products as p')
    .join('lawn_protocol_windows as w', 'p.lawn_protocol_window_id', 'w.id')
    .join('lawn_protocols as l', 'w.lawn_protocol_id', 'l.id')
    .where({ 'w.window_key': windowKey, 'l.version': V13, ...(name ? { 'p.product_name': name } : {}) })
    .orderBy(['l.protocol_key', 'p.sort_order']).select('p.*', 'l.protocol_key', 'l.grass_track');
  const orderOf = async (key, windowKey) => (await rowsIn(windowKey)).filter((r) => r.protocol_key === key).map((r) => r.product_name);
  const ours = () => knex('lawn_protocol_audit_log').where({ action: migration.ACTION });
  const strip = (rows) => rows.map(({ updated_at: _u, ...rest }) => rest);
  const snapshot = async () => ({
    products: strip(await knex('lawn_protocol_products').orderBy('id')),
    audit: (await knex('lawn_protocol_audit_log').orderBy('id')).map(({ id: _i, created_at: _c, ...rest }) => rest),
  });

  // A clean fixture: three v13 protocols (two grass tracks and bahia) with the windows as the earlier migrations leave them.
  async function reset() {
    for (const table of ['lawn_protocol_audit_log', 'lawn_protocol_products', 'lawn_protocol_windows', 'lawn_protocol_service_completions', 'lawn_protocols', 'products_catalog']) await knex(table).del();
    await knex('scheduled_services').update({ lawn_protocol_key: null, lawn_protocol_version: null });
    const names = new Set(Object.values(BEFORE).flat().map(([name]) => name));
    for (const name of names) {
      const [made] = await knex('products_catalog').insert({ name, category: 'chemical', formulation: 'liquid', default_rate_per_1000: 1, rate_unit: 'fl oz', active: true }).returning('*');
      catalog[name] = made.id;
    }
    let sort = 0;
    for (const [key, track] of KEYS) {
      const [protocol] = await knex('lawn_protocols').insert({ protocol_key: key, version: V13, name: 'Fixture v13', status: 'staged', grass_track: track, region: 'swfl', effective_from: '2000-01-01' }).returning('*');
      for (const [windowKey, rows] of Object.entries(BEFORE)) {
        const [window] = await knex('lawn_protocol_windows').insert({ lawn_protocol_id: protocol.id, month: MONTH[windowKey], window_key: windowKey, title: windowKey, visit_type: 'liquid_production_plus_spots', production_mode: 'main_reel_plus_spot_backpack', goal: 'Fixture visit.' }).returning('*');
        for (const [name, role, mode, defaultInPlan, gates, counter] of rows) {
          sort += 1;
          await knex('lawn_protocol_products').insert({
            lawn_protocol_window_id: window.id, product_name: name, product_id: catalog[name], role, application_mode: mode, rate_unit: 'label_rate', carrier_gal_per_1000: 2,
            default_in_plan: defaultInPlan, gates: JSON.stringify(gates), annual_counter: JSON.stringify(counter), sort_order: sort,
          });
        }
      }
    }
  }

  // A visit pinned to a v13 protocol (the reference down() refuses to roll back over).
  async function pin(key) {
    const { fixture } = require('./helpers/lawn-history-db');
    const f = await fixture(knex);
    const row = await f.visit(1, {});
    await knex('scheduled_services').where({ id: row.id }).update({ lawn_protocol_key: key, lawn_protocol_version: V13 });
  }

  const offerIn = async (windowKey) => {
    const rows = (await rowsIn(windowKey)).filter((r) => r.protocol_key === KEYS[0][0]);
    const map = new Map(rows.map((r) => [String(r.product_id), { role: r.role, gates: r.gates }]));
    const candidates = rows.map((r) => ({ raw: { product: { id: r.product_id, name: r.product_name } }, item: { productId: r.product_id, name: r.product_name } }));
    return pickAddOns(candidates, map);
  };

  describe('up', () => {
    let before;
    beforeAll(async () => { await reset(); before = await snapshot(); await migration.up(knex); });

    test('the rows are stored as the spec says: linked to the existing catalog row, spot, never in the plan by default, on all three protocols', async () => {
      for (const [windowKey, specs] of migration.PLACEMENTS) {
        for (const spec of specs) {
          const rows = (await rowsIn(windowKey, spec.name)).filter((r) => !before.products.some((b) => b.id === r.id));
          expect(rows).toHaveLength(KEYS.length);
          for (const row of rows) {
            expect(row).toMatchObject({
              product_id: catalog[spec.name], role: 'fungicide_spot', application_mode: 'spot', rate_unit: 'label_rate', default_in_plan: false,
              gates: spec.gates, annual_counter: {}, mixing: {}, report_copy: { role: 'fungicide_spot' },
            });
            expect(row.rate_per_1000).toBeNull();
            expect(Number(row.carrier_gal_per_1000)).toBe(2);
          }
        }
      }
    });

    test('the triggers are stored as written', async () => {
      expect((await rowsIn(W.FEB, N.VEL)).map((r) => r.gates.trigger)).toEqual(Array(KEYS.length).fill('mapped_large_patch_spring'));
      const mayArtavia = await rowsIn(W.MAY, N.ART);
      expect(mayArtavia.map((r) => r.gates.trigger)).toEqual(Array(KEYS.length).fill('mapped_gray_leaf_spot_prevention'));
    });

    test('each window keeps its rows in place and gets the new one at the end, with no tie', async () => {
      const [a, b, c] = KEYS.map(([key]) => key);
      expect(await orderOf(a, W.FEB)).toEqual([N.F24, N.CEL, N.VEL]);
      expect(await orderOf(b, W.MAY)).toEqual([N.TET, N.DSP, N.VEL, N.ART]);
      expect(await orderOf(c, W.FEB)).toEqual([N.F24, N.CEL, N.VEL]);
      expect(await orderOf(a, W.JUN)).toEqual([N.NT, N.ART]);
      expect(await orderOf(a, W.NOV)).toEqual([N.F24, N.VEL]);
      for (const windowKey of Object.keys(BEFORE)) {
        for (const [key] of KEYS) {
          const places = (await rowsIn(windowKey)).filter((r) => r.protocol_key === key).map((r) => r.sort_order);
          expect(new Set(places).size).toBe(places.length);
        }
      }
    });

    test('no existing row changed', async () => {
      const after = await snapshot();
      const old = new Map(after.products.map((r) => [r.id, r]));
      for (const row of before.products) expect(old.get(row.id)).toEqual(row);
      expect(after.products.length).toBe(before.products.length + 2 * KEYS.length);
    });

    test('the treatment guide never offers the February spring pass as its fungus card, and May\'s first fungicide row stays Velista', async () => {
      expect((await offerIn(W.FEB)).fungus).toBeNull();
      // May: Velista was first and stays first; the appended Artavia row is not the offer.
      expect((await offerIn(W.MAY)).fungus.raw.product.name).toBe(N.VEL);
    });

    test('audit: one row per protocol listing its two inserted rows', async () => {
      const logs = await ours();
      expect(logs).toHaveLength(KEYS.length);
      for (const log of logs) expect(log.after_snapshot.rows).toHaveLength(2);
      expect(migration.ACTION.length).toBeLessThanOrEqual(96);
    });
  });

  describe('skips', () => {
    beforeEach(async () => { await reset(); });

    test('up twice adds nothing the second time', async () => {
      await migration.up(knex);
      const once = await snapshot();
      await migration.up(knex);
      expect(await snapshot()).toEqual(once);
    });

    test('a window that holds the product (retired or not) is skipped for it; an unlinked template row skips the product in that protocol', async () => {
      const [febWindow] = await knex('lawn_protocol_windows').join('lawn_protocols', 'lawn_protocol_windows.lawn_protocol_id', 'lawn_protocols.id')
        .where({ window_key: W.FEB, protocol_key: KEYS[0][0] }).select('lawn_protocol_windows.id');
      await knex('lawn_protocol_products').insert({
        lawn_protocol_window_id: febWindow.id, product_name: N.VEL, product_id: catalog[N.VEL], role: 'fungicide_spot', application_mode: 'spot', rate_unit: 'label_rate',
        carrier_gal_per_1000: 2, default_in_plan: false, gates: JSON.stringify({ retired: true, trigger: 'mapped_large_patch_spring' }), sort_order: 900,
      });
      await knex('lawn_protocol_products').where({ product_name: N.ART }).whereIn('lawn_protocol_window_id', knex('lawn_protocol_windows').where({ window_key: W.JUN }).select('id')).update({ product_id: null });
      await migration.up(knex);
      expect((await rowsIn(W.FEB, N.VEL)).filter((r) => r.protocol_key === KEYS[0][0])).toHaveLength(1);
      expect(await rowsIn(W.MAY, N.ART)).toEqual([]);
      expect((await rowsIn(W.FEB, N.VEL)).length).toBe(KEYS.length);
    });

    test('without a v13 protocol nothing is written', async () => {
      await knex('lawn_protocol_audit_log').del();
      await knex('lawn_protocol_products').del();
      await knex('lawn_protocol_windows').del();
      await knex('lawn_protocols').where({ version: V13 }).del();
      const before = await snapshot();
      await migration.up(knex);
      expect(await snapshot()).toEqual(before);
    });
  });

  describe('down: all or nothing', () => {
    beforeEach(async () => { await reset(); });

    test('up then down is the starting state exactly, and up again writes the same rows', async () => {
      const start = await snapshot();
      await migration.up(knex);
      const upped = await snapshot();
      await migration.down(knex);
      expect(await snapshot()).toEqual(start);
      await migration.up(knex);
      const again = await snapshot();
      expect(again.products.length).toBe(upped.products.length);
      expect(await ours()).toHaveLength(KEYS.length);
    });

    test('a visit pinned to ANY v13 protocol makes down a full no-op: every row and every audit row stay', async () => {
      await migration.up(knex);
      const upped = await snapshot();
      await pin(KEYS[0][0]);
      await migration.down(knex);
      expect(await snapshot()).toEqual(upped);
    });

    test('a completion that references a v13 protocol makes down a full no-op', async () => {
      await migration.up(knex);
      const upped = await snapshot();
      const [protocol] = await knex('lawn_protocols').where({ version: V13, protocol_key: KEYS[1][0] });
      const completionColumns = await knex('lawn_protocol_service_completions').columnInfo();
      const row = { lawn_protocol_id: protocol.id, protocol_key: KEYS[1][0], protocol_version: V13 };
      for (const [column, info] of Object.entries(completionColumns)) {
        if (column in row || column === 'id' || info.nullable || info.defaultValue != null) continue;
        row[column] = info.type.includes('uuid') ? require('crypto').randomUUID() : info.type.includes('int') ? 1 : info.type.includes('timestamp') ? new Date() : info.type === 'date' ? '2027-08-12' : 'x';
      }
      await knex('lawn_protocol_service_completions').insert(row);
      await migration.down(knex);
      expect(await snapshot()).toEqual(upped);
    });

    test.each([
      ['renamed', () => ({ product_name: 'Fixture renamed by staff' })],
      ['re-linked to another product', () => ({ product_id: catalog[N.F24] })],
      ['re-rated', () => ({ rate_per_1000: 3 })],
      ['re-gated', (a) => ({ gates: JSON.stringify({ ...a.gates, extra: true }) })],
      ['moved', () => ({ sort_order: 999 })],
      ['switched on by default', () => ({ default_in_plan: true })],
    ])('one inserted row %s by staff makes down a full no-op', async (_label, change) => {
      await migration.up(knex);
      const [a] = await rowsIn(W.MAY, N.ART);
      await knex('lawn_protocol_products').where({ id: a.id }).update(change(a));
      const edited = await snapshot();
      await migration.down(knex);
      expect(await snapshot()).toEqual(edited);
    });

    test('an inserted row staff deleted makes down a full no-op', async () => {
      await migration.up(knex);
      const [a] = (await rowsIn(W.FEB, N.VEL)).slice(-1);
      await knex('lawn_protocol_products').where({ id: a.id }).del();
      const edited = await snapshot();
      await migration.down(knex);
      expect(await snapshot()).toEqual(edited);
    });
  });
});
