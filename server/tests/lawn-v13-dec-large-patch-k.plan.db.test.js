// GATE_LAWN_DEC_LARGE_PATCH_K (owner 2026-10-23) through the real plan engine and PostgreSQL (cloned schema): the v13 December bag
// is LESCO Black Out 0-0-24 (4.125 lb per 1,000 from the 0.99 lb K2O target, 0 lb N) when the lawn has an ACTIVE mapped fungus area, and
// LESCO 10-0-22 at 4.5 lb otherwise. The one swapped bag reaches the plan item, the completion defaults (as the visit's default
// product), the yearly-limit read, the nitrogen projection, the cost line and the note the technician sees. Synthetic data only.
// Skips without DATABASE_URL.
const { createLawnHistoryDb, fixture } = require('./helpers/lawn-history-db');
const { buildPlanForService } = require('../services/waveguard-plan-engine');
const { LAWN_V13_VERSION } = require('../services/lawn-program');
const { etDateString, addETDays } = require('../utils/datetime-et');
const { DEC_FROM: TEN, DEC_K_PRODUCT: BO } = require('../config/lawn-v13-trouble-product-swaps');

const describeDb = process.env.DATABASE_URL ? describe : describe.skip;
jest.setTimeout(60000);
const KEY = 'fixture_v13_lawn_dec';
const WINDOW = 'dec_v13_spreader_feeding';
const GATES = ['GATE_LAWN_V13', 'GATE_LAWN_COMPLETION_DEFAULTS', 'GATE_LAWN_PROPERTY_HISTORY', 'GATE_LAWN_SPOT_RULES', 'GATE_LAWN_TREATMENT_GUIDE',
  'GATE_LAWN_TROUBLE_AREAS', 'GATE_LAWN_DEC_LARGE_PATCH_K'];
const NOTE = 'Active large patch mapped: potassium-only bag, no nitrogen (4.1 lb per 1,000 sq ft = 0.99 lb K2O). Used in place of the LESCO 10-0-22.';
const TEN_LINE = `${TEN} — 4.5 lb per 1,000 sq ft (0.45 lb N, 0.99 lb K2O), spreader`;
const day = etDateString(addETDays(new Date(), -1));
const LARGE = 'Large patch';

describeDb('December large patch potassium bag through PostgreSQL', () => {
  const saved = Object.fromEntries(GATES.map((name) => [name, process.env[name]]));
  let owned;
  let knex;
  let boProduct;

  async function clone(table) {
    await knex.raw('CREATE TABLE ??.?? (LIKE public.?? INCLUDING ALL)', [owned.schema, table, table]);
    const columns = await knex(table).columnInfo();
    if (String(columns.id?.defaultValue || '').includes('nextval(')) {
      await knex.raw('ALTER TABLE ??.?? ALTER COLUMN id DROP DEFAULT', [owned.schema, table]);
      await knex.raw('ALTER TABLE ??.?? ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', [owned.schema, table]);
    }
  }
  const setGates = (on = GATES) => { for (const name of GATES) { if (on.includes(name)) process.env[name] = 'true'; else delete process.env[name]; } };

  beforeAll(async () => {
    owned = await createLawnHistoryDb(); knex = owned.knex;
    for (const table of ['technicians', 'products_catalog', 'product_aliases', 'lawn_protocol_product_substitutions',
      'equipment_systems', 'equipment_calibrations', 'municipality_ordinances', 'property_nutrient_ledger',
      'service_products', 'lawn_protocols', 'lawn_protocol_windows', 'lawn_protocol_products', 'lawn_protocol_gates',
      'lawn_protocol_service_completions', 'lawn_protocol_product_actuals', 'product_limits', 'property_application_history',
      'lawn_trouble_areas']) {
      await clone(table);
    }
    const base = { category: 'fertilizer', product_type: 'fertilizer', formulation: 'granular', rate_unit: 'lb', label_verified_at: new Date(), inventory_on_hand: 1000, inventory_unit: 'lb', active: true, unit_size_oz: 800, container_size: '50 lb' };
    const [ten] = await knex('products_catalog').insert({ ...base, name: TEN, default_rate_per_1000: 4.5, analysis_n: 10, analysis_p: 0, analysis_k: 22 }).returning('*');
    [boProduct] = await knex('products_catalog').insert({ ...base, name: BO, default_rate_per_1000: 4.1, analysis_n: 0, analysis_p: 0, analysis_k: 24 }).returning('*');
    const [staged] = await knex('lawn_protocols').insert({ protocol_key: KEY, version: LAWN_V13_VERSION, name: 'Fixture v13', status: 'staged', grass_track: 'bermuda', region: 'swfl', effective_from: '2000-01-01' }).returning('*');
    const [window] = await knex('lawn_protocol_windows').insert({ lawn_protocol_id: staged.id, month: 12, window_key: WINDOW, title: 'December', visit_type: 'granular_production_plus_spots' }).returning('*');
    // The December window as the migration leaves it: the 10-0-22 default row and the non-default lb_k row.
    await knex('lawn_protocol_products').insert([
      { lawn_protocol_window_id: window.id, product_id: ten.id, product_name: TEN, role: 'nutrition', application_mode: 'broadcast', default_in_plan: true, rate_per_1000: null, rate_unit: 'lb_n', sort_order: 30,
        gates: JSON.stringify({ targetN: '0.45 lb N/1000', targetK2O: '0.99 lb K2O/1000', blackoutSensitive: true }) },
      { lawn_protocol_window_id: window.id, product_id: boProduct.id, product_name: BO, role: 'nutrition', application_mode: 'broadcast', default_in_plan: false, rate_per_1000: null, rate_unit: 'lb_k', sort_order: 31,
        gates: JSON.stringify({ targetK: '0.99 lb K2O/1000', trigger: 'active_large_patch_mapped' }) },
    ]);
    const [equipment] = await knex('equipment_systems').insert({ name: 'Fixture rig', system_type: 'skid', tank_capacity_gal: 110, active: true }).returning('*');
    await knex('equipment_calibrations').insert({ equipment_system_id: equipment.id, carrier_gal_per_1000: 1, active: true });
  }, 90000);
  afterAll(async () => { if (owned) await owned.dispose(); });
  beforeEach(async () => { setGates(); await knex('lawn_trouble_areas').del(); await knex('property_application_history').del(); await knex('products_catalog').where({ id: boProduct.id }).update({ best_price: null }); });
  afterEach(() => { for (const name of GATES) { if (saved[name] === undefined) delete process.env[name]; else process.env[name] = saved[name]; } });

  // A December visit at a fresh lawn, optionally with mapped areas ({ type, status, target }). `target` is the disease the newest fungicide
  // spot application at the area's place recorded (property_application_history.target_pest, from the sheet's target); a fungus area
  // with no `target` has no disease on record. `ledger` adds more application rows ({ place, target, daysAgo, category, retracted }).
  async function decemberVisit(areas = [], { city, ledger = [] } = {}) {
    const f = await fixture(knex);
    await knex('customers').where({ id: f.customerId }).update({ address_line1: f.property.address_line1, city: city || f.property.city, zip: f.property.zip, state: f.property.state, waveguard_tier: 'Silver' });
    await knex('customer_turf_profiles').insert({ customer_id: f.customerId, active: true, grass_type: 'bermuda', track_key: 'bermuda', lawn_sqft: 10000 });
    for (const [index, area] of areas.entries()) {
      await knex('lawn_trouble_areas').insert({
        customer_id: f.customerId, property_id: f.property.id, place: ['front', 'back', 'left_side', 'right_side'][index], type: area.type, status: area.status || 'active',
        source: 'tech_tap', first_seen_on: day, last_seen_on: day,
      });
      if (area.target) ledger = [{ place: ['front', 'back', 'left_side', 'right_side'][index], target: area.target }, ...ledger];
    }
    for (const row of ledger) {
      await knex('property_application_history').insert({
        customer_id: f.customerId, property_id: f.property.id, application_date: etDateString(addETDays(new Date(), -(row.daysAgo ?? 1))), category: row.category || 'fungicide',
        treated_place: row.place, target_pest: row.target, retracted_at: row.retracted ? new Date() : null,
      });
    }
    return f.visit(0, { scheduled_date: '2026-12-10' });
  }
  const plan = (visit) => buildPlanForService(visit.id, { db: knex, includeCompletionDefaults: true });
  const itemOf = (list, name) => list.find((item) => item.product?.name === name);
  const limitsSpy = () => jest.spyOn(require('../services/application-limits'), 'checkLimits');
  const limitedRate = (spy, productId) => spy.mock.calls.find((call) => call[1] === productId && call[4]?.proposed)?.[4].proposed.ratePer1000;

  test('active large patch, gate on: the 0-0-24 at 4.125 lb per 1,000 (41.25 lb on 10,000 sq ft) in the plan item, the completion default and the limit read, with the note and 0 lb N', async () => {
    const spy = limitsSpy();
    try {
      const result = await plan(await decemberVisit([{ type: 'fungus', target: LARGE }]));
      const item = itemOf(result.mixCalculator.items, BO);
      expect(item.mix).toMatchObject({ rateSource: 'target_k_analysis', targetKPer1000: 0.99, amountUnit: 'lb' });
      expect(item.mix.ratePer1000).toBeCloseTo(4.125, 3);
      expect(item.mix.amount).toBeCloseTo(41.25, 2);
      expect(item.gateNotes).toContainEqual({ key: 'activeLargePatchPotassium', severity: 'note', text: NOTE });
      expect(item.productSwapIn).toBe(true);
      expect(item.raw).toBe(`${BO} — 4.1 lb per 1,000 sq ft (0 lb N, 0.99 lb K2O), spreader, active patch mapped`);
      // The 10-0-22 is gone from the plan; no text still states its rate.
      expect(itemOf(result.mixCalculator.items, TEN)).toBeUndefined();
      expect(JSON.stringify(result.protocol)).not.toContain('4.5 lb per 1,000');
      // Nothing in the plan is a nitrogen block or warning; the visit puts down 0 N and 0.99 lb K2O per 1,000.
      expect(result.mixCalculator.nutrientProjection).toMatchObject({ nPer1000: 0, pPer1000: 0 });
      expect(result.mixCalculator.nutrientProjection.kPer1000).toBeCloseTo(0.99, 2);
      expect(JSON.stringify([result.propertyGate.blocks, result.propertyGate.warnings])).not.toMatch(/nitrogen/i);
      // The completion defaults carry the swapped bag as the visit's default product, at the same rate and note.
      const defaulted = itemOf(result.completionDefaults.items, BO);
      expect(defaulted).toBeTruthy();
      expect(defaulted.mix.ratePer1000).toBeCloseTo(4.125, 3);
      expect(defaulted.mix.amount).toBeCloseTo(41.25, 2);
      expect(defaulted.gateNotes).toContainEqual(expect.objectContaining({ key: 'activeLargePatchPotassium', text: NOTE }));
      expect(itemOf(result.completionDefaults.items, TEN)).toBeUndefined();
      expect(result.completionDefaults.message).toBeFalsy();
      expect(limitedRate(spy, boProduct.id)).toBeCloseTo(4.125, 3);
      // 4.125 lb x 24% = 0.99 lb K2O per 1,000.
      expect(item.mix.ratePer1000 * 0.24).toBeCloseTo(0.99, 3);
    } finally { spy.mockRestore(); }
  });

  test('the cost line: unpriced the bag has no cost; priced from the SiteOne $30.06 / 50 lb it costs $24.80 for the visit', async () => {
    const visit = await decemberVisit([{ type: 'fungus', target: LARGE }]);
    const unpriced = itemOf((await plan(visit)).mixCalculator.items, BO);
    expect(unpriced.mix.materialCost).toBeNull();
    await knex('products_catalog').where({ id: boProduct.id }).update({ best_price: 30.06 });
    const result = await plan(visit);
    const item = itemOf(result.mixCalculator.items, BO);
    expect(item.mix.materialCost).toBeCloseTo((41.25 * 16 / 800) * 30.06, 1);
    expect(result.mixCalculator.materialCostSummary).toMatchObject({ pricedLineCount: 1, missingPriceCount: 0 });
  });

  test.each([
    ['no mapped area', []],
    ['take-all only', [{ type: 'take_all' }]],
    ['weeds and chinch only', [{ type: 'weeds' }, { type: 'chinch' }]],
    ['a CLEARED fungus area', [{ type: 'fungus', status: 'cleared' }]],
  ])('%s: the 10-0-22 at 4.5 lb per 1,000 (0.45 lb N), no note, no 0-0-24 anywhere', async (_label, areas) => {
    const spy = limitsSpy();
    try {
      const result = await plan(await decemberVisit(areas));
      const item = itemOf(result.mixCalculator.items, TEN);
      expect(item.mix.ratePer1000).toBeCloseTo(4.5, 3);
      expect(item.mix.targetNPer1000).toBe(0.45);
      expect(item.raw).toBe(TEN_LINE);
      expect(item.productSwapIn).toBeUndefined();
      expect(itemOf(result.mixCalculator.items, BO)).toBeUndefined();
      expect(itemOf(result.completionDefaults.items, TEN)).toBeTruthy();
      expect(result.mixCalculator.nutrientProjection.nPer1000).toBeCloseTo(0.45, 2);
      expect(JSON.stringify(result)).not.toContain('activeLargePatchPotassium');
      expect(limitedRate(spy, item.product.id)).toBeCloseTo(4.5, 3);
    } finally { spy.mockRestore(); }
  });

  test('active large patch but the gate is off, or the trouble-areas gate is off: the old plan, byte for byte the same as a lawn with no patch', async () => {
    const visit = await decemberVisit([{ type: 'fungus', target: LARGE }]);
    const clean = await decemberVisit([]);
    const strip = (result) => JSON.parse(JSON.stringify(result.mixCalculator.items.map(({ product, mix, raw, gateNotes, selected }) => ({ name: product?.name, ratePer1000: mix?.ratePer1000, amount: mix?.amount, raw, gateNotes, selected }))));
    setGates(GATES.filter((name) => name !== 'GATE_LAWN_DEC_LARGE_PATCH_K'));
    const gateOff = await plan(visit);
    const baseline = await plan(clean);
    setGates(GATES.filter((name) => name !== 'GATE_LAWN_TROUBLE_AREAS'));
    const areasOff = await plan(visit);
    for (const result of [gateOff, areasOff]) {
      const item = itemOf(result.mixCalculator.items, TEN);
      expect(item.mix.ratePer1000).toBeCloseTo(4.5, 3);
      expect(item.raw).toBe(TEN_LINE);
      expect(strip(result)).toEqual(strip(baseline));
      expect(JSON.stringify(result)).not.toContain('activeLargePatchPotassium');
      expect(JSON.stringify(result)).not.toContain('productSwapIn');
    }
  });

  test('a city nitrogen window (North Port style) covering the visit: the swapped bag carries no nitrogen so nothing blocks it; the 10-0-22 on a lawn with no patch is blocked there', async () => {
    const [rule] = await knex('municipality_ordinances').insert({
      jurisdiction_name: 'Fixture December', jurisdiction_type: 'city', city: 'Fixture City', active: true, restricted_start_month: 12, restricted_start_day: 1,
      restricted_end_month: 12, restricted_end_day: 31, restricted_nitrogen: true, source_url: 'https://example.invalid/fixture', source_name: 'Synthetic test', source_checked_at: '2026-01-01',
    }).returning('id');
    try {
      const swapped = await plan(await decemberVisit([{ type: 'fungus', target: LARGE }]));
      expect(itemOf(swapped.mixCalculator.items, BO)).toBeTruthy();
      expect(swapped.propertyGate.blocks.map((block) => block.code)).not.toContain('nitrogen_blackout');
      const control = await plan(await decemberVisit([]));
      expect(control.propertyGate.blocks.map((block) => block.code)).toContain('nitrogen_blackout');
    } finally {
      await knex('municipality_ordinances').where({ id: rule.id || rule }).del();
    }
  });

  describe('a December visit pinned to v13 after v13 is ARCHIVED (the Nov rule\'s archived case)', () => {
    const archive = async (status) => knex('lawn_protocols').where({ protocol_key: KEY, version: LAWN_V13_VERSION }).update({ status });
    afterEach(() => archive('staged'));
    const pinned = async (areas) => {
      const visit = await decemberVisit(areas);
      await knex('scheduled_services').where({ id: visit.id }).update({ lawn_protocol_key: KEY, lawn_protocol_version: LAWN_V13_VERSION, lawn_protocol_window_key: WINDOW });
      return visit;
    };

    test('active large patch: the planned items and the completion defaults survive with the 0-0-24 (the 10-0-22 is not expected)', async () => {
      await archive('archived');
      const result = await plan(await pinned([{ type: 'fungus', target: LARGE }]));
      expect(result.protocol.structured.status).toBe('archived');
      expect(result.propertyGate.blocks.map((block) => block.code)).not.toContain('lawn_archived_recipe_unavailable');
      expect(itemOf(result.mixCalculator.items, BO).mix.ratePer1000).toBeCloseTo(4.125, 3);
      expect(itemOf(result.completionDefaults.items, BO)).toBeTruthy();
    });

    test('no large patch: the archived check passes with the 10-0-22 exactly as before', async () => {
      await archive('archived');
      const result = await plan(await pinned([]));
      expect(result.propertyGate.blocks.map((block) => block.code)).not.toContain('lawn_archived_recipe_unavailable');
      expect(itemOf(result.mixCalculator.items, TEN).mix.ratePer1000).toBeCloseTo(4.5, 3);
    });

    test('a K target the row does not state is still rejected for the swapped bag', async () => {
      await archive('archived');
      const stored = await knex('lawn_protocol_products').where({ product_id: boProduct.id }).first('id', 'gates');
      await knex('lawn_protocol_products').where({ id: stored.id }).update({ gates: JSON.stringify({ targetK: '0.5 lb K2O/1000', trigger: 'active_large_patch_mapped' }) });
      try {
        const result = await plan(await pinned([{ type: 'fungus', target: LARGE }]));
        expect(result.propertyGate.blocks.map((block) => block.code)).toContain('lawn_archived_recipe_unavailable');
        expect(result.mixCalculator.items).toEqual([]);
      } finally {
        await knex('lawn_protocol_products').where({ id: stored.id }).update({ gates: stored.gates });
      }
    });
  });

  describe('only a LARGE PATCH counts (a "fungus" area also stands for the other diseases)', () => {
    const swapped = async (visit) => !!itemOf((await plan(visit)).mixCalculator.items, BO);
    const normal = async (visit) => {
      const result = await plan(visit);
      expect(itemOf(result.mixCalculator.items, TEN).mix.ratePer1000).toBeCloseTo(4.5, 3);
      expect(itemOf(result.mixCalculator.items, BO)).toBeUndefined();
      expect(JSON.stringify(result)).not.toContain('activeLargePatchPotassium');
    };

    test.each(['Gray leaf spot', 'Pythium root rot', 'Dollar spot', 'Fairy ring', 'Rust'])('a fungus area treated for %s: the 10-0-22, no change', async (target) => {
      await normal(await decemberVisit([{ type: 'fungus', target }]));
    });

    test('a fungus area whose disease is not on record (no application, or an application with no target): the 10-0-22, no change (fails closed)', async () => {
      await normal(await decemberVisit([{ type: 'fungus' }]));
      await normal(await decemberVisit([{ type: 'fungus' }], { ledger: [{ place: 'front', target: '  ' }] }));
    });

    test.each(['Large patch', 'large patch (fungal) activity', 'Brown patch', 'Rhizoctonia blight'])('target %j: the swap applies', async (target) => {
      expect(await swapped(await decemberVisit([{ type: 'fungus', target }]))).toBe(true);
    });

    test('the NEWEST named target at the place decides: a later gray leaf spot treatment after a large patch one means no swap; the reverse means the swap', async () => {
      const lateOther = await decemberVisit([{ type: 'fungus', target: LARGE }], { ledger: [{ place: 'front', target: 'Gray leaf spot', daysAgo: 0 }] });
      await normal(lateOther);
      const lateLarge = await decemberVisit([{ type: 'fungus', target: 'Dollar spot' }], { ledger: [{ place: 'front', target: LARGE, daysAgo: 0 }] });
      expect(await swapped(lateLarge)).toBe(true);
    });

    test('a retracted large patch application, one at another place, a non-fungicide row and another property\'s row are not evidence', async () => {
      await normal(await decemberVisit([{ type: 'fungus' }], { ledger: [{ place: 'front', target: LARGE, retracted: true }] }));
      await normal(await decemberVisit([{ type: 'fungus' }], { ledger: [{ place: 'back', target: LARGE }] }));
      await normal(await decemberVisit([{ type: 'fungus' }], { ledger: [{ place: 'front', target: LARGE, category: 'herbicide' }] }));
      const other = await decemberVisit([{ type: 'fungus', target: LARGE }]);
      await normal(await decemberVisit([{ type: 'fungus' }]));
      expect(await swapped(other)).toBe(true);
    });

    test('a newer fungicide application with NO target outranks an older large patch one: the disease is unknown again, no swap', async () => {
      await normal(await decemberVisit([{ type: 'fungus', target: LARGE }], { ledger: [{ place: 'front', target: null, daysAgo: 0 }] }));
      await normal(await decemberVisit([{ type: 'fungus', target: LARGE }], { ledger: [{ place: 'front', target: '  ', daysAgo: 0 }] }));
      // An older blank row does not hide a newer large patch one.
      expect(await swapped(await decemberVisit([{ type: 'fungus', target: LARGE }], { ledger: [{ place: 'front', target: null, daysAgo: 5 }] }))).toBe(true);
    });

    test('a take-all area with a large patch application at its place is still take-all: no swap', async () => {
      await normal(await decemberVisit([{ type: 'take_all', target: LARGE }]));
    });

    test('a large patch application but no ACTIVE fungus area (cleared): no swap', async () => {
      await normal(await decemberVisit([{ type: 'fungus', status: 'cleared', target: LARGE }]));
    });
  });

  test('inside a transaction (packet closeout) the plan reads the areas through a savepoint and still swaps', async () => {
    const visit = await decemberVisit([{ type: 'fungus', target: LARGE }]);
    const result = await knex.transaction((trx) => buildPlanForService(visit.id, { db: trx, includeCompletionDefaults: true }));
    expect(itemOf(result.mixCalculator.items, BO).mix.ratePer1000).toBeCloseTo(4.125, 3);
  });

  test('a failed trouble-area read: the strict plan throws, the lenient plan keeps the 10-0-22 and still builds', async () => {
    const visit = await decemberVisit([{ type: 'fungus', target: LARGE }]);
    const areas = require('../services/lawn-trouble-areas');
    const spy = jest.spyOn(areas, 'loadActive').mockRejectedValue(Object.assign(new Error('db down'), { code: 'ECONNRESET' }));
    try {
      await expect(plan(visit)).rejects.toThrow('db down');
      await expect(buildPlanForService(visit.id, { db: knex, strict: true, completionDefaultsEnabled: false })).rejects.toThrow('db down');
      const lenient = await buildPlanForService(visit.id, { db: knex, completionDefaultsEnabled: false });
      expect(itemOf(lenient.mixCalculator.items, TEN).mix.ratePer1000).toBeCloseTo(4.5, 3);
      expect(JSON.stringify(lenient)).not.toContain('activeLargePatchPotassium');
    } finally { spy.mockRestore(); }
  });
});
