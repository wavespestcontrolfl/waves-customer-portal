// GATE_LAWN_RECLAIMED_HALF_N (owner 2026-10-23) through the real plan engine and PostgreSQL (cloned schema): the v13 November 24-0-11 bag is
// sized for half the nitrogen when the visit's property is marked reclaimed, and the one halved target reaches the plan item, the completion
// defaults, the yearly-limit read and the note the technician sees; the October Dimension bag (a pre-emergent plus fertilizer) keeps its rate.
// Synthetic data only. Skips without DATABASE_URL.
const { createLawnHistoryDb, fixture } = require('./helpers/lawn-history-db');
const { buildPlanForService } = require('../services/waveguard-plan-engine');
const { LAWN_V13_VERSION } = require('../services/lawn-program');
const { etDateString, addETDays } = require('../utils/datetime-et');

const describeDb = process.env.DATABASE_URL ? describe : describe.skip;
jest.setTimeout(60000);
const KEY = 'fixture_v13_lawn_reclaimed';
const F24 = 'LESCO 24-0-11 with PolyPlus OPTI';
const DIMENSION = 'LESCO Dimension 0.21% 18-0-10 50% PolyPlus OPTI45 MOP Pre-Emergent Plus Fertilizer';
const GATES = ['GATE_LAWN_V13', 'GATE_LAWN_COMPLETION_DEFAULTS', 'GATE_LAWN_PROPERTY_HISTORY', 'GATE_LAWN_SPOT_RULES', 'GATE_LAWN_TREATMENT_GUIDE',
  'GATE_LAWN_TROUBLE_AREAS', 'GATE_LAWN_NOV_LARGE_PATCH_N', 'GATE_LAWN_RECLAIMED_HALF_N'];
const HALF_NOTE = 'Reclaimed water: half nitrogen today (0.375 lb N, 1.6 lb per 1,000).';
const KEPT_NOTE = 'Reclaimed water: this bag carries the pre-emergent, so its full rate stays today.';
const day = etDateString(addETDays(new Date(), -1));

describeDb('reclaimed water half nitrogen through PostgreSQL', () => {
  const saved = Object.fromEntries(GATES.map((name) => [name, process.env[name]]));
  let owned;
  let knex;

  async function clone(table) {
    await knex.raw('CREATE TABLE ??.?? (LIKE public.?? INCLUDING ALL)', [owned.schema, table, table]);
    const columns = await knex(table).columnInfo();
    if (String(columns.id?.defaultValue || '').includes('nextval(')) {
      await knex.raw('ALTER TABLE ??.?? ALTER COLUMN id DROP DEFAULT', [owned.schema, table]);
      await knex.raw('ALTER TABLE ??.?? ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', [owned.schema, table]);
    }
  }
  const setGates = (on = GATES) => { for (const name of GATES) { if (on.includes(name)) process.env[name] = 'true'; else delete process.env[name]; } };

  beforeAll(async () => {
    owned = await createLawnHistoryDb(); knex = owned.knex;
    for (const table of ['technicians', 'products_catalog', 'product_aliases', 'lawn_protocol_product_substitutions',
      'equipment_systems', 'equipment_calibrations', 'municipality_ordinances', 'property_nutrient_ledger',
      'service_products', 'lawn_protocols', 'lawn_protocol_windows', 'lawn_protocol_products', 'lawn_protocol_gates',
      'lawn_protocol_service_completions', 'lawn_protocol_product_actuals', 'product_limits', 'property_application_history',
      'lawn_trouble_areas']) {
      await clone(table);
    }
    const [bag] = await knex('products_catalog').insert({
      name: F24, category: 'fertilizer', product_type: 'fertilizer', default_rate_per_1000: 4.2, rate_unit: 'lb', analysis_n: 24, analysis_p: 0, analysis_k: 11,
      label_verified_at: new Date(), inventory_on_hand: 1000, inventory_unit: 'lb', active: true,
    }).returning('*');
    const [dimension] = await knex('products_catalog').insert({
      name: DIMENSION, category: 'herbicide', product_type: 'pesticide', default_rate_per_1000: 4.04, rate_unit: 'lb', analysis_n: 18, analysis_p: 0, analysis_k: 10,
      label_verified_at: new Date(), inventory_on_hand: 1000, inventory_unit: 'lb', active: true,
    }).returning('*');
    const [staged] = await knex('lawn_protocols').insert({ protocol_key: KEY, version: LAWN_V13_VERSION, name: 'Fixture v13', status: 'staged', grass_track: 'bermuda', region: 'swfl', effective_from: '2000-01-01' }).returning('*');
    const [nov] = await knex('lawn_protocol_windows').insert({ lawn_protocol_id: staged.id, month: 11, window_key: 'nov_v13_spreader_feeding', title: 'November', visit_type: 'granular_production_plus_spots' }).returning('*');
    await knex('lawn_protocol_products').insert({
      lawn_protocol_window_id: nov.id, product_id: bag.id, product_name: F24, role: 'nutrition', application_mode: 'broadcast',
      default_in_plan: true, rate_per_1000: null, rate_unit: 'lb_n', gates: JSON.stringify({ targetN: '0.75 lb N/1000', blackoutSensitive: true }),
    });
    const [oct] = await knex('lawn_protocol_windows').insert({ lawn_protocol_id: staged.id, month: 10, window_key: 'oct_v13_spreader_fall', title: 'October', visit_type: 'granular_production_plus_spots' }).returning('*');
    await knex('lawn_protocol_products').insert({
      lawn_protocol_window_id: oct.id, product_id: dimension.id, product_name: DIMENSION, role: 'nutrition', application_mode: 'broadcast',
      default_in_plan: true, rate_per_1000: 4.04, rate_unit: 'lb', gates: JSON.stringify({ targetN: '0.73 lb N/1000', targetK2O: '0.4 lb K2O/1000', blackoutSensitive: true }),
    });
    const [equipment] = await knex('equipment_systems').insert({ name: 'Fixture rig', system_type: 'skid', tank_capacity_gal: 110, active: true }).returning('*');
    await knex('equipment_calibrations').insert({ equipment_system_id: equipment.id, carrier_gal_per_1000: 1, active: true });
  }, 90000);
  afterAll(async () => { if (owned) await owned.dispose(); });
  beforeEach(async () => { setGates(); await knex('lawn_trouble_areas').del(); });
  afterEach(() => { for (const name of GATES) { if (saved[name] === undefined) delete process.env[name]; else process.env[name] = saved[name]; } });

  // A visit on `date` at a fresh lawn; `water` sets the property's reclaimed value ({ value, source }), else the column stays NULL.
  async function visitOn(date, { water = null, areas = [] } = {}) {
    const f = await fixture(knex);
    await knex('customers').where({ id: f.customerId }).update({ address_line1: f.property.address_line1, city: f.property.city, zip: f.property.zip, state: f.property.state, waveguard_tier: 'Silver' });
    await knex('customer_turf_profiles').insert({ customer_id: f.customerId, active: true, grass_type: 'bermuda', track_key: 'bermuda', lawn_sqft: 10000 });
    if (water) await knex('customer_properties').where({ id: f.property.id }).update({ reclaimed_water: water.value, reclaimed_water_source: water.source, reclaimed_water_checked_at: new Date() });
    for (const [index, area] of areas.entries()) {
      await knex('lawn_trouble_areas').insert({
        customer_id: f.customerId, property_id: f.property.id, place: ['front', 'back', 'left_side', 'right_side'][index], type: area.type, status: 'active',
        source: 'tech_tap', first_seen_on: day, last_seen_on: day,
      });
    }
    return f.visit(0, { scheduled_date: date });
  }
  const plan = (visit) => buildPlanForService(visit.id, { db: knex, includeCompletionDefaults: true });
  const bagOf = (list, name = F24) => list.find((item) => item.product?.name === name);
  const limitsSpy = () => jest.spyOn(require('../services/application-limits'), 'checkLimits');
  const limitedRate = (spy) => spy.mock.calls.find((call) => call[1] && call[4]?.proposed)?.[4].proposed.ratePer1000;
  const COUNTY = { value: true, source: 'county_meter' };

  test('reclaimed, gate on: 1.5625 lb per 1,000 (15.6 lb on 10,000 sq ft) in the plan item, the completion default and the limit read, with the note', async () => {
    const spy = limitsSpy();
    try {
      const result = await plan(await visitOn('2026-11-10', { water: COUNTY }));
      const item = bagOf(result.mixCalculator.items);
      expect(item.mix).toMatchObject({ rateSource: 'target_n_analysis', targetNPer1000: 0.375, amountUnit: 'lb' });
      expect(item.mix.ratePer1000).toBeCloseTo(1.5625, 4);
      expect(item.mix.amount).toBeCloseTo(15.625, 3);
      expect(item.gateNotes).toContainEqual({ key: 'reclaimedNitrogen', severity: 'note', text: HALF_NOTE });
      expect(item.raw).toBe('LESCO 24-0-11 with PolyPlus OPTI — 1.6 lb per 1,000 sq ft (0.375 lb N), spreader, reclaimed water, half');
      const defaulted = bagOf(result.completionDefaults.items);
      expect(defaulted.mix.ratePer1000).toBeCloseTo(1.5625, 4);
      expect(defaulted.gateNotes).toContainEqual(expect.objectContaining({ key: 'reclaimedNitrogen', text: HALF_NOTE }));
      expect(limitedRate(spy)).toBeCloseTo(1.5625, 4);
      expect(item.mix.ratePer1000 * 0.24).toBeCloseTo(0.375, 4);
    } finally { spy.mockRestore(); }
  });

  test('an office value of "not reclaimed" beats a county meter; an office value of "reclaimed" needs no meter', async () => {
    const no = bagOf((await plan(await visitOn('2026-11-10', { water: { value: false, source: 'office' } }))).mixCalculator.items);
    expect(no.mix.ratePer1000).toBeCloseTo(3.125, 3);
    expect(JSON.stringify(no.gateNotes)).not.toContain('reclaimedNitrogen');
    const yes = bagOf((await plan(await visitOn('2026-11-10', { water: { value: true, source: 'office' } }))).mixCalculator.items);
    expect(yes.mix.ratePer1000).toBeCloseTo(1.5625, 4);
  });

  test.each([['never checked (NULL)', null], ['checked, not reclaimed', { value: false, source: 'county_meter' }]])('%s: the visit\'s 0.75 lb N (3.125 lb per 1,000), no note', async (_label, water) => {
    const result = await plan(await visitOn('2026-11-10', { water }));
    const item = bagOf(result.mixCalculator.items);
    expect(item.mix.ratePer1000).toBeCloseTo(3.125, 3);
    expect(item.mix.targetNPer1000).toBe(0.75);
    expect(JSON.stringify(result)).not.toContain('reclaimedNitrogen');
  });

  test('the gate off: a reclaimed lawn gets the old plan, no reclaimed note anywhere', async () => {
    const visit = await visitOn('2026-11-10', { water: COUNTY });
    setGates(GATES.filter((name) => name !== 'GATE_LAWN_RECLAIMED_HALF_N'));
    const result = await plan(visit);
    const item = bagOf(result.mixCalculator.items);
    expect(item.mix.ratePer1000).toBeCloseTo(3.125, 3);
    expect(item.raw).toBe('LESCO 24-0-11 with PolyPlus OPTI — 3.1 lb per 1,000 sq ft (0.75 lb N), spreader');
    expect(JSON.stringify(result)).not.toContain('reclaimedNitrogen');
  });

  test('reclaimed with active fungus in November: the smaller target (0.375), the reclaimed note only', async () => {
    const result = await plan(await visitOn('2026-11-10', { water: COUNTY, areas: [{ type: 'fungus' }] }));
    const item = bagOf(result.mixCalculator.items);
    expect(item.mix.targetNPer1000).toBe(0.375);
    expect(item.gateNotes.map((note) => note.key)).toContain('reclaimedNitrogen');
    expect(item.gateNotes.map((note) => note.key)).not.toContain('activeFungusNitrogen');
  });

  test('October Dimension 18-0-10 (a pre-emergent plus fertilizer bag) keeps its 4.04 lb and says why', async () => {
    const result = await plan(await visitOn('2026-10-14', { water: COUNTY }));
    const item = bagOf(result.mixCalculator.items, DIMENSION);
    expect(item).toBeDefined();
    expect(item.mix.ratePer1000).toBeCloseTo(4.04, 3);
    expect(item.mix.rateSource).toBe('protocol_rate');
    expect(item.gateNotes).toContainEqual({ key: 'reclaimedNitrogen', severity: 'note', text: KEPT_NOTE });
    expect(item.raw).toContain('4.04 lb per 1,000 sq ft (0.73 lb N, 0.4 lb K2O)');
    const plain = bagOf((await plan(await visitOn('2026-10-14'))).mixCalculator.items, DIMENSION);
    expect(plain.mix.ratePer1000).toBeCloseTo(4.04, 3);
    expect(JSON.stringify(plain.gateNotes)).not.toContain('reclaimedNitrogen');
  });

  test('inside a transaction (packet closeout) the plan reads the property through a savepoint and still halves', async () => {
    const visit = await visitOn('2026-11-10', { water: COUNTY });
    const result = await knex.transaction((trx) => buildPlanForService(visit.id, { db: trx, includeCompletionDefaults: true }));
    expect(bagOf(result.mixCalculator.items).mix.ratePer1000).toBeCloseTo(1.5625, 4);
  });

  test('a failed property read: the strict plan throws, the lenient plan keeps the normal target and still builds', async () => {
    const visit = await visitOn('2026-11-10', { water: COUNTY });
    const service = require('../services/lawn-reclaimed-water');
    const spy = jest.spyOn(service, 'isReclaimedService').mockImplementation(async (_knex, _svc, { strict } = {}) => {
      if (strict) throw Object.assign(new Error('db down'), { code: 'ECONNRESET' });
      return false;
    });
    try {
      await expect(plan(visit)).rejects.toThrow('db down');
      const lenient = await buildPlanForService(visit.id, { db: knex, completionDefaultsEnabled: false });
      expect(bagOf(lenient.mixCalculator.items).mix.ratePer1000).toBeCloseTo(3.125, 3);
    } finally { spy.mockRestore(); }
  });
});
